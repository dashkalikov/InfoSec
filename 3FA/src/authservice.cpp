AuthService::AuthService(Database *database, QObject *parent)
    : QObject(parent)                    // Инициализация базового класса Qt
    , m_database(database)               // Сохранение указателя на объект Database
    , m_isLoggedIn(false)                // Изначально пользователь не авторизован
    , m_currentSessionToken()            // Токен сессии пуст при создании
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА ВАЛИДНОСТИ DATABASE
    // ========================================================================
    // Проверяем, что передан валидный указатель на объект Database.
    // Если указатель nullptr, сохраняем ошибку для последующего использования.
    if (!m_database) 
    {
        setError("База данных не инициализирована");
    }
}


// ============================================================================
// МЕТОД registerUser
// ============================================================================
// Реализует пайплайн регистрации:
//   1. Валидация и проверка уникальности email.
//   2. Хеширование пароля.
//   3. Создание пользователя + аудит.
// ============================================================================
bool AuthService::registerUser(const QString &email, const QString &password)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ОЧИСТКА ПРЕДЫДУЩИХ ОШИБОК
    // ========================================================================
    // Очищаем текст последней ошибки перед началом новой операции регистрации.
    // Это необходимо для корректного отображения ошибок в UI.
    clearError();
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВАЛИДАЦИЯ ВХОДНЫХ ДАННЫХ
    // ========================================================================
    // Проверяем корректность email и пароля:
    //   - Email должен содержать @ и точку, иметь корректный формат
    //   - Пароль должен быть минимум 8 символов, содержать заглавные и строчные
    //     буквы, а также цифры
    // Если валидация не прошла, метод validateRegistrationData() уже сохранил
    // текст ошибки в m_lastError через setError().
    if (!validateRegistrationData(email, password)) 
    {
        return false; // Валидация не прошла, возвращаем false
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПРОВЕРКА УНИКАЛЬНОСТИ EMAIL
    // ========================================================================
    // Проверяем, не существует ли уже пользователь с таким email в базе данных.
    // Это предотвращает создание дубликатов пользователей.
    if (m_database->userExists(email)) 
    {
        setError("Пользователь с таким email уже существует");
        emit authenticationFailed("Пользователь уже существует");
        return false; // Пользователь уже существует, регистрация невозможна
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ХЕШИРОВАНИЕ ПАРОЛЯ
    // ========================================================================
    // Генерируем криптографический хеш пароля с использованием алгоритма
    // Stribog-256 и случайной соли. Результат сохраняется в формате
    // base64(salt:hash) для последующего хранения в базе данных.
    QString passwordHash = hashPassword(password);
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: СОЗДАНИЕ ОБЪЕКТА ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Создаем объект User с email и хешированным паролем.
    // Остальные поля (id, role, is_active) будут установлены базой данных
    // при сохранении.
    User newUser(email, passwordHash);
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: СОХРАНЕНИЕ ПОЛЬЗОВАТЕЛЯ В БАЗЕ ДАННЫХ
    // ========================================================================
    // Сохраняем нового пользователя в базу данных через объект Database.
    // Если сохранение не удалось, получаем текст ошибки из Database и
    // уведомляем об ошибке через сигнал errorOccurred().
    if (!m_database->createUser(newUser)) 
    {
        setError("Ошибка при создании пользователя: " + m_database->getLastError());
        emit errorOccurred(m_lastError);
        return false; // Ошибка при сохранении в БД
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: ЗАПИСЬ В АУДИТ-ЛОГ
    // ========================================================================
    // Записываем успешную регистрацию в таблицу audit_log для последующего
    // аудита и мониторинга безопасности.
    m_database->logSuccessfulRegistration(email);
    
    // ========================================================================
    // ДЕЙСТВИЕ 8: УВЕДОМЛЕНИЕ ОБ УСПЕШНОЙ РЕГИСТРАЦИИ
    // ========================================================================
    // Выводим отладочное сообщение и испускаем сигнал userRegistered(),
    // чтобы UI и другие компоненты могли отреагировать на успешную регистрацию.
    qDebug() << "AuthService: Пользователь зарегистрирован:" << email;
    emit userRegistered(email);
    
    return true; // Регистрация успешно завершена
}

// ============================================================================
// МЕТОД loginUser
// ============================================================================
// Проводит полную процедуру входа:
//   • проверка блока по brute-force (lockout);
//   • сверка пароля и статуса пользователя;
//   • фиксация успешной/неуспешной попытки;
//   • активация пользовательской сессии.
// ============================================================================
bool AuthService::loginUser(const QString &email, const QString &password)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ОЧИСТКА ПРЕДЫДУЩИХ ОШИБОК
    // ========================================================================
    // Очищаем текст последней ошибки перед началом новой попытки входа.
    clearError();
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВАЛИДАЦИЯ ВХОДНЫХ ДАННЫХ
    // ========================================================================
    // Выполняем минимальные проверки: email и пароль не должны быть пустыми.
    // Более детальная проверка формата email не требуется при входе,
    // так как пользователь уже зарегистрирован.
    if (!validateLoginData(email, password)) 
    {
        return false; // Валидация не прошла
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПОИСК ПОЛЬЗОВАТЕЛЯ В БАЗЕ ДАННЫХ
    // ========================================================================
    // Ищем пользователя по email в базе данных. Если пользователь не найден,
    // метод findUserByEmail() вернет невалидный объект User (id = -1).
    qDebug() << "AuthService: Поиск пользователя с email:" << email;
    User user = m_database->findUserByEmail(email);
    qDebug() << "AuthService: Найденный пользователь:" << user.toString();
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ПРОВЕРКА ВРЕМЕННОЙ БЛОКИРОВКИ ОТ BRUTE-FORCE
    // ========================================================================
    // Проверяем, не заблокирован ли аккаунт из-за множественных неудачных
    // попыток входа. Если аккаунт заблокирован, получаем время разблокировки
    // и вычисляем оставшееся время блокировки для информативного сообщения.
    QDateTime lockoutUntil;
    if (m_database->isLockedOut(email, lockoutUntil)) 
    {
        // ====================================================================
        // ПОДДЕЙСТВИЕ 4.1: ВЫЧИСЛЕНИЕ ОСТАВШЕГОСЯ ВРЕМЕНИ БЛОКИРОВКИ
        // ====================================================================
        // Вычисляем количество секунд до разблокировки аккаунта.
        // Если время уже истекло (отрицательное значение), устанавливаем
        // минимум 1 секунда для корректного отображения сообщения.
        int secondsRemaining = QDateTime::currentDateTime().secsTo(lockoutUntil);
        
        if (secondsRemaining <= 0) 
        {
            secondsRemaining = 1; // Минимум 1 секунда для отображения
        }
        
        // ====================================================================
        // ПОДДЕЙСТВИЕ 4.2: ФОРМАТИРОВАНИЕ ВРЕМЕНИ ДЛЯ СООБЩЕНИЯ
        // ====================================================================
        // Форматируем оставшееся время в удобочитаемый вид:
        //   - Если меньше минуты: показываем секунды
        //   - Если больше минуты: показываем минуты с правильным склонением
        QString timeText;
        if (secondsRemaining < 60) 
        {
            // Меньше минуты - показываем секунды
            timeText = QString("%1 секунд").arg(secondsRemaining);
        } 
        else 
        {
            // Больше минуты - округляем вверх и показываем минуты
            int minutesRemaining = (secondsRemaining + 59) / 60; // Округляем вверх
            if (minutesRemaining == 1) 
            {
                timeText = "1 минуту";
            } 
            else if (minutesRemaining < 5) 
            {
                timeText = QString("%1 минуты").arg(minutesRemaining);
            } 
            else 
            {
                timeText = QString("%1 минут").arg(minutesRemaining);
            }
        }
        
        // ====================================================================
        // ПОДДЕЙСТВИЕ 4.3: УВЕДОМЛЕНИЕ О БЛОКИРОВКЕ
        // ====================================================================
        // Формируем сообщение об ошибке с информацией о времени разблокировки
        // и уведомляем пользователя через сигнал authenticationFailed().
        QString errorMsg = QString("Аккаунт временно заблокирован из-за множественных неудачных попыток входа. Попробуйте снова через %1.").arg(timeText);
        setError(errorMsg);
        emit authenticationFailed(errorMsg);
        
        // ====================================================================
        // ПОДДЕЙСТВИЕ 4.4: ЗАПИСЬ В АУДИТ-ЛОГ
        // ====================================================================
        // Записываем попытку входа во время блокировки в audit_log для
        // мониторинга безопасности и анализа атак.
        int minutesForLog = (secondsRemaining + 59) / 60;
        m_database->logFailedLogin(email, QString("Попытка входа во время блокировки (разблокировка через %1 минут)").arg(minutesForLog));
        return false; // Аккаунт заблокирован, вход невозможен
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ПРОВЕРКА СУЩЕСТВОВАНИЯ ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Проверяем, был ли найден пользователь в базе данных.
    // Если пользователь не найден, объект User будет невалидным (id = -1).
    // В этом случае не сообщаем точную причину ошибки (пользователь не найден
    // или неверный пароль) для предотвращения перебора email'ов.
    if (!user.isValid()) 
    {
        setError("Пользователь не найден");
        emit authenticationFailed("Неверный email или пароль");
        // Записываем в audit_log попытку входа с несуществующим email
        m_database->logFailedLogin(email, "Пользователь не найден");
        return false; // Пользователь не найден
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ПРОВЕРКА АКТИВНОСТИ ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Проверяем, не заблокирован ли пользователь администратором
    // (поле is_active в базе данных). Заблокированные пользователи не могут
    // войти в систему, даже если пароль верный.
    if (!user.isActive()) 
    {
        setError("Вы заблокированы");
        emit authenticationFailed("Вы заблокированы");
        // Записываем в audit_log попытку входа заблокированного пользователя
        m_database->logFailedLogin(email, "Пользователь заблокирован администратором");
        return false; // Пользователь заблокирован администратором
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: ВЕРИФИКАЦИЯ ПАРОЛЯ
    // ========================================================================
    // Проверяем, соответствует ли введенный пароль сохраненному хешу.
    // Используется алгоритм Stribog-256 для сравнения хешей.
    if (!verifyPassword(password, user.getPasswordHash())) 
    {
        // ====================================================================
        // ПОДДЕЙСТВИЕ 7.1: ОБРАБОТКА НЕВЕРНОГО ПАРОЛЯ
        // ====================================================================
        // Пароль неверный - увеличиваем счетчик неудачных попыток входа.
        // Это необходимо для защиты от brute-force атак.
        m_database->incrementFailedAttempts(email);
        
        // ====================================================================
        // ПОДДЕЙСТВИЕ 7.2: ПОЛУЧЕНИЕ ТЕКУЩЕГО КОЛИЧЕСТВА НЕУДАЧНЫХ ПОПЫТОК
        // ====================================================================
        // Запрашиваем из базы данных текущее количество неудачных попыток
        // для проверки, не достигнут ли лимит MAX_FAILED_ATTEMPTS.
        QVariantList params;
        params << email;
        QSqlQuery query = m_database->select("SELECT failed_attempts FROM users WHERE email = ?", params);
        int failedAttempts = 0;
        if (query.next()) 
        {
            failedAttempts = query.value("failed_attempts").toInt();
        }
        
        // ====================================================================
        // ПОДДЕЙСТВИЕ 7.3: ПРОВЕРКА ЛИМИТА НЕУДАЧНЫХ ПОПЫТОК
        // ====================================================================
        // Если достигнут лимит неудачных попыток (MAX_FAILED_ATTEMPTS = 5),
        // блокируем аккаунт на LOCKOUT_DURATION_SECONDS (120 секунд = 2 минуты).
        if (failedAttempts >= MAX_FAILED_ATTEMPTS) 
        {
            QDateTime lockoutTime = QDateTime::currentDateTime().addSecs(LOCKOUT_DURATION_SECONDS);
            m_database->setLockoutUntil(email, lockoutTime);
            int minutes = LOCKOUT_DURATION_SECONDS / 60;
            QString errorMsg = QString("Превышено максимальное количество неудачных попыток входа. Аккаунт заблокирован на %1 минут.").arg(minutes);
            setError(errorMsg);
            emit authenticationFailed(errorMsg);
            // Записываем в audit_log блокировку аккаунта
            m_database->logFailedLogin(email, QString("Аккаунт заблокирован после %1 неудачных попыток").arg(failedAttempts));
            return false; // Аккаунт заблокирован
        }
        
        // ====================================================================
        // ПОДДЕЙСТВИЕ 7.4: УВЕДОМЛЕНИЕ О НЕВЕРНОМ ПАРОЛЕ
        // ====================================================================
        // Записываем неудачную попытку в audit_log и уведомляем пользователя
        // о неверном пароле, указывая количество оставшихся попыток.
        m_database->logFailedLogin(email, QString("Неверный пароль (попытка %1 из %2)").arg(failedAttempts).arg(MAX_FAILED_ATTEMPTS));
        
        // Вычисляем количество оставшихся попыток для информативного сообщения
        int remainingAttempts = MAX_FAILED_ATTEMPTS - failedAttempts;
        QString errorMsg = QString("Неверный пароль. Осталось попыток: %1 из %2").arg(remainingAttempts).arg(MAX_FAILED_ATTEMPTS);
        setError(errorMsg);
        emit authenticationFailed(errorMsg);
        return false; // Пароль неверный
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 8: УСПЕШНЫЙ ВХОД
    // ========================================================================
    // Пароль верный - сбрасываем счетчик неудачных попыток, так как вход
    // успешен. Это позволяет пользователю снова иметь MAX_FAILED_ATTEMPTS
    // попыток при следующей неудачной попытке входа.
    m_database->resetFailedAttempts(email);
    
    // ========================================================================
    // ДЕЙСТВИЕ 9: ОБНОВЛЕНИЕ СОСТОЯНИЯ СЕРВИСА
    // ========================================================================
    // Сохраняем данные пользователя в m_currentUser и устанавливаем флаг
    // m_isLoggedIn в true. Это означает, что пользователь успешно авторизован.
    m_currentUser = user;
    m_isLoggedIn = true;
    
    // ========================================================================
    // ДЕЙСТВИЕ 10: УВЕДОМЛЕНИЕ ОБ УСПЕШНОМ ВХОДЕ
    // ========================================================================
    // Выводим отладочное сообщение и испускаем сигнал userLoggedIn(),
    // чтобы UI и другие компоненты могли отреагировать на успешный вход.
    qDebug() << "AuthService: Пользователь вошел в систему:" << email;
    emit userLoggedIn(user);
    
    return true; // Вход успешно выполнен
}

// ============================================================================
// МЕТОД saveSessionToDb
// ============================================================================
// Сохраняет текущую сессию в таблицу sessions, создавая таблицу при
// необходимости. Использует отдельное QSqlDatabase соединение, чтобы
// не блокировать основной Database.
// ============================================================================
void AuthService::saveSessionToDb()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА СОСТОЯНИЯ АВТОРИЗАЦИИ
    // ========================================================================
    // Проверяем, что пользователь авторизован и данные пользователя валидны.
    // Если пользователь не авторизован, нет смысла сохранять сессию.
    if (!m_isLoggedIn || !m_currentUser.isValid()) 
    {
        return; // Пользователь не авторизован, выход из метода
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ОТКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Создаем временное соединение с базой данных для работы с таблицей sessions.
    // Используется отдельное соединение, чтобы не блокировать основной Database
    // при выполнении операций с сессиями.
    QSqlDatabase *db = getDbConnection();
    if (!db || !db->isOpen()) 
    {
        setError("Не удалось открыть соединение с базой данных для сохранения сессии");
        return; // Не удалось открыть соединение
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: СОЗДАНИЕ ТАБЛИЦЫ SESSIONS
    // ========================================================================
    // Создаем таблицу sessions, если её еще нет в базе данных.
    // Таблица содержит:
    //   - token: уникальный токен сессии (PRIMARY KEY)
    //   - user_id: идентификатор пользователя (FOREIGN KEY на users.id)
    //   - user_email: email пользователя для быстрого доступа
    //   - created_at: время создания сессии (Unix timestamp)
    //   - expires_at: время истечения сессии (Unix timestamp)
    // Используем ON DELETE CASCADE для автоматического удаления сессий
    // при удалении пользователя.
    {
    QSqlQuery createTableQuery(*db);
    QString createTable = R"(
        CREATE TABLE IF NOT EXISTS sessions (
            token TEXT PRIMARY KEY,
            user_id INTEGER NOT NULL,
            user_email TEXT NOT NULL,
            created_at INTEGER NOT NULL,
            expires_at INTEGER NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        )
    )";
    createTableQuery.exec(createTable);
        createTableQuery.finish(); // Явно завершаем запрос
        // createTableQuery уничтожится при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ПРОВЕРКА НАЛИЧИЯ АКТИВНОЙ СЕССИИ
    // ========================================================================
    // Проверяем, есть ли уже активная (не истекшая) сессия для этого пользователя.
    // Если активная сессия существует, используем её токен вместо создания новой.
    // Это предотвращает создание множественных сессий для одного пользователя.
    {
    QSqlQuery checkQuery(*db);
    checkQuery.prepare("SELECT token FROM sessions WHERE user_id = ? AND expires_at > ? LIMIT 1");
    checkQuery.addBindValue(m_currentUser.getId());
    checkQuery.addBindValue(QDateTime::currentDateTime().toSecsSinceEpoch());
    
        if (checkQuery.exec() && checkQuery.next()) 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 4.1: НАЙДЕНА АКТИВНАЯ СЕССИЯ
            // ====================================================================
            // У пользователя уже есть активная сессия - используем её токен.
            // Это позволяет пользователю продолжать работу с существующей сессией
            // без необходимости создавать новую при каждом входе.
        QString existingToken = checkQuery.value(0).toString();
        m_currentSessionToken = existingToken; // Сохраняем токен существующей сессии
            qDebug() << "AuthService: У пользователя уже есть активная сессия:" << existingToken.left(16) << "...";
        } 
        else 
        {
            // Активной сессии нет - продолжаем создание новой сессии
        }
        checkQuery.finish(); // Явно завершаем запрос
        // checkQuery уничтожится при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ВЫХОД ПРИ НАЛИЧИИ АКТИВНОЙ СЕССИИ
    // ========================================================================
    // Если нашли существующую активную сессию, закрываем соединение и выходим.
    // Нет необходимости создавать новую сессию, если уже есть активная.
    if (!m_currentSessionToken.isEmpty()) 
    {
        closeDbConnection(db);
        return; // Используем существующую сессию
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ОЧИСТКА СТАРЫХ ИСТЕКШИХ СЕССИЙ
    // ========================================================================
    // Удаляем все истекшие сессии пользователя перед созданием новой.
    // Это предотвращает накопление устаревших записей в базе данных.
    {
    QSqlQuery deleteQuery(*db);
    deleteQuery.prepare("DELETE FROM sessions WHERE user_id = ? AND expires_at <= ?");
    deleteQuery.addBindValue(m_currentUser.getId());
    deleteQuery.addBindValue(QDateTime::currentDateTime().toSecsSinceEpoch());
    deleteQuery.exec();
        deleteQuery.finish(); // Явно завершаем запрос
        // deleteQuery уничтожится при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: ГЕНЕРАЦИЯ ТОКЕНА СЕССИИ
    // ========================================================================
    // Генерируем криптографически стойкий токен сессии, используя:
    //   1. Случайные данные (32 байта) для обеспечения уникальности
    //   2. Текущее время в миллисекундах для обеспечения временной уникальности
    //   3. SHA-256 хеш для создания фиксированной длины токена
    //   4. Base64 кодирование с заменой символов для URL-безопасности
    QByteArray randomData;
    randomData.resize(32);
    for (int i = 0; i < 32; ++i) 
    {
        randomData[i] = static_cast<char>(QRandomGenerator::global()->bounded(256));
    }
    
    QByteArray timeData = QByteArray::number(QDateTime::currentMSecsSinceEpoch());
    
    QCryptographicHash hash(QCryptographicHash::Sha256);
    hash.addData(randomData);
    hash.addData(timeData);
    
    QString token = hash.result().toBase64();
    token.replace("+", "-");  // Заменяем + на - для URL-безопасности
    token.replace("/", "_");  // Заменяем / на _ для URL-безопасности
    token.replace("=", "");   // Удаляем padding символы =
    
    // ========================================================================
    // ДЕЙСТВИЕ 8: ВЫЧИСЛЕНИЕ ВРЕМЕНИ СОЗДАНИЯ И ИСТЕЧЕНИЯ
    // ========================================================================
    // Устанавливаем время создания сессии (текущее время) и время истечения
    // (текущее время + 24 часа = 86400 секунд). Сессия будет действительна
    // в течение 24 часов с момента создания.
    QDateTime createdAt = QDateTime::currentDateTime();
    QDateTime expiresAt = createdAt.addSecs(86400); // 24 часа
    
    // ========================================================================
    // ДЕЙСТВИЕ 9: СОХРАНЕНИЕ СЕССИИ В БАЗУ ДАННЫХ
    // ========================================================================
    // Сохраняем новую сессию в таблицу sessions со всеми необходимыми данными:
    // токен, идентификатор пользователя, email, время создания и истечения.
    {
    QSqlQuery query(*db);
    query.prepare("INSERT INTO sessions (token, user_id, user_email, created_at, expires_at) VALUES (?, ?, ?, ?, ?)");
    query.addBindValue(token);
    query.addBindValue(m_currentUser.getId());
    query.addBindValue(m_currentUser.getEmail());
    query.addBindValue(createdAt.toSecsSinceEpoch());
    query.addBindValue(expiresAt.toSecsSinceEpoch());
    
        if (query.exec()) 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 9.1: УСПЕШНОЕ СОХРАНЕНИЕ
            // ====================================================================
            // Сессия успешно сохранена - сохраняем токен в m_currentSessionToken
            // для последующего использования при проверке истечения сессии.
        m_currentSessionToken = token; // Сохраняем токен текущей сессии
            qDebug() << "AuthService: Сессия успешно сохранена в базу данных для пользователя" << m_currentUser.getEmail() << ", токен:" << token.left(16) << "...";
        } 
        else 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 9.2: ОШИБКА ПРИ СОХРАНЕНИИ
            // ====================================================================
            // Не удалось сохранить сессию - выводим предупреждение с текстом ошибки.
            // Это может произойти при проблемах с базой данных или нарушении
            // ограничений целостности.
            setError("Не удалось сохранить сессию в базу данных: " + query.lastError().text());
    }
        query.finish(); // Явно завершаем запрос
        // query уничтожится при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 10: ЗАКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Закрываем временное соединение с базой данных после завершения всех
    // операций. Это освобождает ресурсы и предотвращает утечки соединений.
    closeDbConnection(db);
}

// ============================================================================
// МЕТОД changePassword
// ============================================================================
// Изменяет пароль пользователя:
//   1. Проверка входных данных и существования пользователя.
//   2. Верификация старого пароля, защитная запись в журнал.
//   3. Сохранение нового хеша и сброс попыток.
// ============================================================================
bool AuthService::changePassword(const QString &email, const QString &oldPassword, const QString &newPassword)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ОЧИСТКА ПРЕДЫДУЩИХ ОШИБОК
    // ========================================================================
    // Очищаем текст последней ошибки перед началом операции изменения пароля.
    clearError();
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВЕРИФИКАЦИЯ СТАРОГО ПАРОЛЯ
    // ========================================================================
    // Проверяем, что старый пароль верный, используя метод loginUser().
    // Это гарантирует, что только пользователь, знающий текущий пароль,
    // может изменить его. Метод loginUser() также выполняет все необходимые
    // проверки (блокировка, активность пользователя и т.д.).
    if (!loginUser(email, oldPassword)) {
        setError("Неверный текущий пароль");
        return false; // Старый пароль неверный
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ВАЛИДАЦИЯ НОВОГО ПАРОЛЯ
    // ========================================================================
    // Проверяем, что новый пароль соответствует требованиям безопасности:
    //   - Минимум 8 символов
    //   - Содержит заглавные и строчные буквы
    //   - Содержит цифры
    // Это предотвращает использование слабых паролей.
    if (!User::isValidPassword(newPassword)) {
        setError("Новый пароль не соответствует требованиям безопасности");
        return false; // Новый пароль не соответствует требованиям
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ХЕШИРОВАНИЕ НОВОГО ПАРОЛЯ
    // ========================================================================
    // Генерируем криптографический хеш нового пароля с использованием
    // алгоритма Stribog-256 и случайной соли. Результат сохраняется в формате
    // base64(salt:hash) для последующего хранения в базе данных.
    QString newPasswordHash = hashPassword(newPassword);
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ОБНОВЛЕНИЕ ХЕША В ОБЪЕКТЕ ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Обновляем хеш пароля в объекте m_currentUser. Этот объект уже содержит
    // данные пользователя после успешного входа в loginUser().
    m_currentUser.setPasswordHash(newPasswordHash);
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: СОХРАНЕНИЕ НОВОГО ПАРОЛЯ В БАЗЕ ДАННЫХ
    // ========================================================================
    // Сохраняем обновленный хеш пароля в базе данных через метод updateUser().
    // Если сохранение не удалось, получаем текст ошибки из Database и
    // уведомляем об ошибке через сигнал errorOccurred().
    if (!m_database->updateUser(m_currentUser)) {
        setError("Ошибка при обновлении пароля: " + m_database->getLastError());
        emit errorOccurred(m_lastError);
        return false; // Ошибка при сохранении в БД
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: УВЕДОМЛЕНИЕ ОБ УСПЕШНОМ ИЗМЕНЕНИИ ПАРОЛЯ
    // ========================================================================
    // Выводим отладочное сообщение об успешном изменении пароля.
    // Примечание: счетчик неудачных попыток уже сброшен в loginUser(),
    // так как вход был успешным.
    qDebug() << "AuthService: Пароль изменен для пользователя:" << email;
    
    return true; // Пароль успешно изменен
}

// ============================================================================
// МЕТОД resetPassword
// ============================================================================
// Выполняет админский/восстановительный сброс пароля без проверки
// старого пароля. Используется при подтвержденном восстановлении.
// ============================================================================
bool AuthService::resetPassword(const QString &email, const QString &newPassword)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ОЧИСТКА ПРЕДЫДУЩИХ ОШИБОК
    // ========================================================================
    // Очищаем текст последней ошибки перед началом операции сброса пароля.
    clearError();
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВАЛИДАЦИЯ EMAIL
    // ========================================================================
    // Проверяем, что email не пустой. Это базовая проверка перед поиском
    // пользователя в базе данных.
    if (email.isEmpty()) 
    {
        setError("Email не может быть пустым");
        return false; // Email пустой
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ВАЛИДАЦИЯ НОВОГО ПАРОЛЯ
    // ========================================================================
    // Проверяем, что новый пароль соответствует требованиям безопасности:
    //   - Минимум 8 символов
    //   - Содержит заглавные и строчные буквы
    //   - Содержит цифры
    // Это предотвращает использование слабых паролей даже при сбросе.
    if (!User::isValidPassword(newPassword)) 
    {
        setError("Новый пароль не соответствует требованиям безопасности");
        return false; // Новый пароль не соответствует требованиям
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ПРОВЕРКА СУЩЕСТВОВАНИЯ ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Проверяем, существует ли пользователь с указанным email в базе данных.
    // Это позволяет быстро определить, есть ли такой пользователь, без
    // необходимости загружать полные данные пользователя.
    if (!m_database->userExists(email)) 
    {
        setError("Пользователь с таким email не найден");
        return false; // Пользователь не существует
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ЗАГРУЗКА ДАННЫХ ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Загружаем полные данные пользователя из базы данных для последующего
    // обновления хеша пароля. Проверяем, что пользователь валиден (id != -1).
    User user = m_database->findUserByEmail(email);
    if (!user.isValid()) 
    {
        setError("Пользователь не найден");
        return false; // Пользователь не найден или невалиден
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ХЕШИРОВАНИЕ НОВОГО ПАРОЛЯ
    // ========================================================================
    // Генерируем криптографический хеш нового пароля с использованием
    // алгоритма Stribog-256 и случайной соли. Результат сохраняется в формате
    // base64(salt:hash) для последующего хранения в базе данных.
    QString newPasswordHash = hashPassword(newPassword);
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: ОБНОВЛЕНИЕ ХЕША В ОБЪЕКТЕ ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Обновляем хеш пароля в объекте user перед сохранением в базу данных.
    user.setPasswordHash(newPasswordHash);
    
    // ========================================================================
    // ДЕЙСТВИЕ 8: СОХРАНЕНИЕ НОВОГО ПАРОЛЯ В БАЗЕ ДАННЫХ
    // ========================================================================
    // Сохраняем обновленный хеш пароля в базе данных через метод updateUser().
    // Если сохранение не удалось, получаем текст ошибки из Database и
    // уведомляем об ошибке через сигнал errorOccurred().
    if (!m_database->updateUser(user)) 
    {
        setError("Ошибка при сбросе пароля: " + m_database->getLastError());
        emit errorOccurred(m_lastError);
        return false; // Ошибка при сохранении в БД
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 9: УВЕДОМЛЕНИЕ ОБ УСПЕШНОМ СБРОСЕ ПАРОЛЯ
    // ========================================================================
    // Выводим отладочное сообщение об успешном сбросе пароля.
    // Примечание: этот метод не требует входа пользователя, поэтому
    // счетчик неудачных попыток не сбрасывается автоматически.
    qDebug() << "AuthService: Пароль сброшен для пользователя:" << email;
    
    return true; // Пароль успешно сброшен
}

// ============================================================================
// МЕТОД updateCurrentUser
// ============================================================================
// Синхронизирует объект текущего пользователя с новыми данными
// (например, при изменении профиля в UI).
// ============================================================================
void AuthService::updateCurrentUser(const User &user)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА ВАЛИДНОСТИ ДАННЫХ
    // ========================================================================
    // Проверяем, что переданный объект User валиден (id != -1) и что
    // пользователь в данный момент авторизован (m_isLoggedIn == true).
    // Это предотвращает обновление данных неавторизованного пользователя
    // или использование невалидных данных.
    if (user.isValid() && m_isLoggedIn) 
    {
        // ====================================================================
        // ПОДДЕЙСТВИЕ 1.1: ОБНОВЛЕНИЕ ДАННЫХ ПОЛЬЗОВАТЕЛЯ
        // ====================================================================
        // Обновляем объект m_currentUser новыми данными. Это синхронизирует
        // состояние сервиса с изменениями, внесенными в UI (например,
        // изменение email, роли или других полей пользователя).
        m_currentUser = user;
        qDebug() << "AuthService: Обновлен текущий пользователь:" << user.getEmail();
    } 
    else 
    {
        // ====================================================================
        // ПОДДЕЙСТВИЕ 1.2: ОБРАБОТКА НЕВАЛИДНЫХ ДАННЫХ
        // ====================================================================
        // Выводим предупреждение, если попытка обновления выполнена с
        // невалидными данными или когда пользователь не авторизован.
        // Это помогает выявить ошибки в логике приложения.
        qWarning() << "AuthService: Попытка обновить невалидного пользователя или пользователь не залогинен";
    }
}

// ============================================================================
// МЕТОД logout
// ============================================================================
// Сбрасывает состояние авторизации, уведомляя слушателей через сигнал.
// ============================================================================
void AuthService::logout()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА СОСТОЯНИЯ АВТОРИЗАЦИИ
    // ========================================================================
    // Проверяем, что пользователь действительно авторизован перед выполнением
    // выхода. Если пользователь не авторизован, нет необходимости выполнять
    // операции выхода.
    if (m_isLoggedIn) 
    {
        // Сохраняем email и userId для последующего использования, так как
        // m_currentUser будет очищен
        QString email = m_currentUser.getEmail();
        int userId = m_currentUser.getId();
        
        // ====================================================================
        // ДЕЙСТВИЕ 2: ОЧИСТКА ТОКЕНА СЕССИИ
        // ====================================================================
        // Очищаем токен текущей сессии в памяти. Это предотвращает использование
        // старого токена после выхода из системы.
        m_currentSessionToken.clear();
        
        // ====================================================================
        // ДЕЙСТВИЕ 3: УДАЛЕНИЕ СЕССИЙ ИЗ БАЗЫ ДАННЫХ
        // ====================================================================
        // Удаляем все сессии пользователя из базы данных, чтобы предотвратить
        // возможность использования сохраненных сессий после выхода.
        // Это выполняется только если userId валиден (id > 0).
        if (userId > 0) 
        {
            QSqlDatabase *db = getDbConnection();
            if (db && db->isOpen()) 
            {
                {
                QSqlQuery query(*db);
                query.prepare("DELETE FROM sessions WHERE user_id = ?");
                query.addBindValue(userId);
                    if (query.exec()) 
                    {
                        qDebug() << "AuthService: Сессии успешно удалены для пользователя" << userId;
                }
                    query.finish(); // Явно завершаем запрос
                    // query уничтожится при выходе из блока
                }
                
                closeDbConnection(db);
            }
        }
        
        // ====================================================================
        // ДЕЙСТВИЕ 4: СБРОС СОСТОЯНИЯ АВТОРИЗАЦИИ
        // ====================================================================
        // Очищаем объект текущего пользователя (создаем пустой User с id = -1)
        // и устанавливаем флаг m_isLoggedIn в false. Это означает, что
        // пользователь больше не авторизован в системе.
        m_currentUser = User();
        m_isLoggedIn = false;
        
        // ====================================================================
        // ДЕЙСТВИЕ 5: УВЕДОМЛЕНИЕ О ВЫХОДЕ
        // ====================================================================
        // Выводим отладочное сообщение и испускаем сигнал userLoggedOut(),
        // чтобы UI и другие компоненты могли отреагировать на выход пользователя
        // (например, закрыть окно, очистить кэш и т.д.).
        qDebug() << "AuthService: Пользователь вышел из системы:" << email;
        emit userLoggedOut();
    }
}

// ============================================================================
// МЕТОД restoreFromSession
// ============================================================================
// Пытается поднять состояние сервиса из сохраненной ранее сессии,
// проверяя срок действия токена и корректность пользователя.
// ============================================================================
bool AuthService::restoreFromSession()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ОЧИСТКА ПРЕДЫДУЩИХ ОШИБОК
    // ========================================================================
    // Очищаем текст последней ошибки перед началом восстановления сессии.
    clearError();
    
    qDebug() << "AuthService: Попытка восстановить сессию из базы данных...";
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ОТКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Создаем временное соединение с базой данных для работы с таблицей sessions.
    // Это необходимо для загрузки данных сессии из базы данных.
    QSqlDatabase *db = getDbConnection();
    if (!db || !db->isOpen()) 
    {
        setError("Не удалось открыть соединение с базой данных для восстановления сессии");
        return false; // Не удалось открыть соединение
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПОИСК ПОСЛЕДНЕЙ СЕССИИ В БАЗЕ ДАННЫХ
    // ========================================================================
    // Ищем последнюю созданную сессию в базе данных (ORDER BY created_at DESC LIMIT 1).
    // Это позволяет восстановить состояние из самой свежей сессии, независимо от того,
    // истекла она или нет. Проверка истечения выполняется позже.
    QString token;
    int userId = 0;
    QString userEmail;
    qint64 createdAtSecs = 0;
    qint64 expiresAtSecs = 0;
    
    {
    QSqlQuery query(*db);
    query.prepare("SELECT token, user_id, user_email, created_at, expires_at FROM sessions ORDER BY created_at DESC LIMIT 1");
    
        if (!query.exec() || !query.next()) 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 3.1: СЕССИИ НЕ НАЙДЕНЫ
            // ====================================================================
            // В базе данных нет ни одной сессии - это нормально при первом запуске
            // приложения или после полной очистки сессий.
            qDebug() << "AuthService: В базе данных не найдено ни одной сессии";
            query.finish(); // Явно завершаем запрос
            // query уничтожится при выходе из блока
            closeDbConnection(db);
            return false; // Нет сессий для восстановления
        }
        
        // ====================================================================
        // ПОДДЕЙСТВИЕ 3.2: ИЗВЛЕЧЕНИЕ ДАННЫХ СЕССИИ
        // ====================================================================
        // Извлекаем все данные сессии из результата запроса:
        //   - token: токен сессии
        //   - user_id: идентификатор пользователя
        //   - user_email: email пользователя
        //   - created_at: время создания (Unix timestamp)
        //   - expires_at: время истечения (Unix timestamp)
        token = query.value(0).toString();
        userId = query.value(1).toInt();
        userEmail = query.value(2).toString();
        createdAtSecs = query.value(3).toLongLong();
        expiresAtSecs = query.value(4).toLongLong();
        query.finish(); // Явно завершаем запрос
        // query уничтожится при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: СОХРАНЕНИЕ ТОКЕНА СЕССИИ
    // ========================================================================
    // Сохраняем токен найденной сессии в m_currentSessionToken для последующего
    // использования при проверке истечения сессии.
    m_currentSessionToken = token;
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ЗАКРЫТИЕ ПЕРВОГО СОЕДИНЕНИЯ
    // ========================================================================
    // Закрываем первое соединение после загрузки данных сессии. Это освобождает
    // ресурсы перед выполнением проверок валидности сессии.
    closeDbConnection(db);
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ПРЕОБРАЗОВАНИЕ ВРЕМЕННЫХ МЕТОК
    // ========================================================================
    // Преобразуем Unix timestamp в объекты QDateTime для удобной работы
    // с датами и временем. Также получаем текущее время для сравнения.
    QDateTime createdAt = QDateTime::fromSecsSinceEpoch(createdAtSecs);
    QDateTime expiresAt = QDateTime::fromSecsSinceEpoch(expiresAtSecs);
    QDateTime currentTime = QDateTime::currentDateTime();
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: ПРОВЕРКА ИСТЕЧЕНИЯ СЕССИИ ПО ВРЕМЕНИ EXPIRES_AT
    // ========================================================================
    // Проверяем, не истекла ли сессия по времени expires_at. Если текущее время
    // больше или равно времени истечения, сессия считается недействительной.
    if (currentTime >= expiresAt) {
        // ====================================================================
        // ПОДДЕЙСТВИЕ 7.1: УДАЛЕНИЕ ИСТЕКШЕЙ СЕССИИ
        // ====================================================================
        // Сессия истекла - удаляем её из базы данных, чтобы освободить место
        // и предотвратить попытки восстановления истекших сессий в будущем.
        qDebug() << "AuthService: Сессия истекла. Создана:" << createdAt << ", Истекает:" << expiresAt << ", Текущее:" << currentTime;
        QSqlDatabase *db2 = getDbConnection();
        if (db2 && db2->isOpen()) 
        {
            {
            QSqlQuery deleteQuery(*db2);
            deleteQuery.prepare("DELETE FROM sessions WHERE token = ?");
            deleteQuery.addBindValue(token);
            deleteQuery.exec();
                deleteQuery.finish(); // Явно завершаем запрос
                // deleteQuery уничтожится при выходе из блока
            }
            
            closeDbConnection(db2);
        }
        return false; // Сессия истекла
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 8: ДОПОЛНИТЕЛЬНАЯ ПРОВЕРКА ВОЗРАСТА СЕССИИ
    // ========================================================================
    // Выполняем дополнительную проверку: убеждаемся, что сессия не старше
    // 24 часов от времени создания. Это защита на случай, если expires_at
    // был установлен неправильно или изменен вручную в базе данных.
    const int SESSION_DURATION_SECONDS = 86400; // 24 часа
    qint64 secondsSinceCreation = createdAt.secsTo(currentTime);
    if (secondsSinceCreation >= SESSION_DURATION_SECONDS) 
    {
        // ====================================================================
        // ПОДДЕЙСТВИЕ 8.1: УДАЛЕНИЕ СТАРОЙ СЕССИИ
        // ====================================================================
        // Сессия старше 24 часов - удаляем её из базы данных, даже если
        // expires_at еще не истек. Это гарантирует, что сессии не могут
        // существовать дольше 24 часов.
        qDebug() << "AuthService: Сессия слишком старая. Создана:" << createdAt << ", Возраст:" << secondsSinceCreation << "секунд";
        QSqlDatabase *db2 = getDbConnection();
        if (db2 && db2->isOpen()) 
        {
            {
            QSqlQuery deleteQuery(*db2);
            deleteQuery.prepare("DELETE FROM sessions WHERE token = ?");
            deleteQuery.addBindValue(token);
            deleteQuery.exec();
                deleteQuery.finish(); // Явно завершаем запрос
                // deleteQuery уничтожится при выходе из блока
            }
            
            closeDbConnection(db2);
        }
        return false; // Сессия слишком старая
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 9: ЗАГРУЗКА ДАННЫХ ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Загружаем данные пользователя из базы данных по email, полученному из сессии.
    // Проверяем, что пользователь существует и его ID совпадает с ID из сессии.
    // Это гарантирует целостность данных и предотвращает восстановление сессии
    // для несуществующего или другого пользователя.
    User user = m_database->findUserByEmail(userEmail);
    if (!user.isValid() || user.getId() != userId) 
    {
        setError("Пользователь не найден или ID не совпадает для восстановления сессии");
        return false; // Пользователь не найден или ID не совпадает
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 10: ПРОВЕРКА АКТИВНОСТИ ПОЛЬЗОВАТЕЛЯ
    // ========================================================================
    // Проверяем, не заблокирован ли пользователь администратором.
    // Заблокированные пользователи не могут восстановить сессию, даже если
    // сессия технически валидна.
    if (!user.isActive()) 
    {
        setError("Пользователь не активен, невозможно восстановить сессию");
        return false; // Пользователь заблокирован
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 11: ВОССТАНОВЛЕНИЕ СОСТОЯНИЯ АВТОРИЗАЦИИ
    // ========================================================================
    // Все проверки пройдены - восстанавливаем состояние авторизации:
    //   - Сохраняем данные пользователя в m_currentUser
    //   - Устанавливаем флаг m_isLoggedIn в true
    // Это означает, что пользователь успешно авторизован через восстановленную сессию.
    m_currentUser = user;
    m_isLoggedIn = true;
    
    // ========================================================================
    // ДЕЙСТВИЕ 12: УВЕДОМЛЕНИЕ ОБ УСПЕШНОМ ВОССТАНОВЛЕНИИ
    // ========================================================================
    // Выводим отладочное сообщение и испускаем сигнал userLoggedIn(),
    // чтобы UI и другие компоненты могли отреагировать на успешное восстановление
    // сессии (например, показать главное окно приложения).
    qDebug() << "AuthService: Восстановлена сессия для пользователя" << userEmail << "из базы данных";
    emit userLoggedIn(user);
    
    return true; // Сессия успешно восстановлена
}

// ============================================================================
// МЕТОД checkSessionExpiration
// ============================================================================
// Проверяет, не истекла ли текущая сессия, и очищает состояние при
// необходимости.
// ============================================================================
bool AuthService::checkSessionExpiration()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА НАЛИЧИЯ АКТИВНОЙ СЕССИИ
    // ========================================================================
    // Проверяем, что пользователь авторизован и данные пользователя валидны.
    // Если пользователь не авторизован, нет активной сессии для проверки.
    // В этом случае возвращаем true (сессия "не истекла", так как её нет).
    if (!m_isLoggedIn || !m_currentUser.isValid()) 
    {
        return true; // Нет активной сессии - считаем, что "не истекла" (нет сессии)
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПРОВЕРКА НАЛИЧИЯ ТОКЕНА СЕССИИ
    // ========================================================================
    // Проверяем, что токен текущей сессии сохранен в m_currentSessionToken.
    // Без токена невозможно проверить истечение сессии в базе данных.
    // Если токена нет, считаем сессию валидной (не можем проверить).
    if (m_currentSessionToken.isEmpty()) {
        setError("Нет токена сессии, невозможно проверить истечение");
        return true; // Считаем, что сессия валидна (не можем проверить)
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ОТКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Создаем временное соединение с базой данных для проверки сессии.
    // Если соединение не удалось открыть, считаем сессию валидной (не можем проверить).
    QSqlDatabase *db = getDbConnection();
    if (!db || !db->isOpen()) 
    {
        setError("Не удалось открыть соединение с базой данных для проверки сессии");
        return true; // Не можем проверить - считаем, что сессия валидна
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ЗАГРУЗКА ДАННЫХ СЕССИИ ИЗ БАЗЫ ДАННЫХ
    // ========================================================================
    // Загружаем данные конкретной сессии по токену из базы данных.
    // Проверяем именно эту сессию (по токену), а не любую сессию пользователя,
    // чтобы гарантировать проверку правильной сессии.
    bool sessionExpired = false;
    QDateTime currentTime = QDateTime::currentDateTime();
    const int SESSION_DURATION_SECONDS = 86400; // 24 часа
    
    {
        // Используем блок области видимости для явного уничтожения запросов перед закрытием соединения
        QSqlQuery query(*db);
        query.prepare("SELECT created_at, expires_at FROM sessions WHERE token = ?");
        query.addBindValue(m_currentSessionToken);
        
        if (query.exec() && query.next()) 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 4.1: ИЗВЛЕЧЕНИЕ ДАННЫХ СЕССИИ
            // ====================================================================
            // Сессия найдена в базе данных - извлекаем время создания и истечения.
        qint64 createdAtSecs = query.value(0).toLongLong();
        qint64 expiresAtSecs = query.value(1).toLongLong();
        
        QDateTime createdAt = QDateTime::fromSecsSinceEpoch(createdAtSecs);
        QDateTime expiresAt = QDateTime::fromSecsSinceEpoch(expiresAtSecs);
        
            // ====================================================================
            // ПОДДЕЙСТВИЕ 4.2: ПРОВЕРКА ИСТЕЧЕНИЯ ПО ВРЕМЕНИ EXPIRES_AT
            // ====================================================================
            // Проверяем, не истекла ли сессия по времени expires_at.
            // Если текущее время больше или равно времени истечения, сессия истекла.
            if (currentTime >= expiresAt) 
            {
            sessionExpired = true;
                qDebug() << "AuthService: Сессия истекла. Создана:" << createdAt << ", Истекает:" << expiresAt << ", Текущее:" << currentTime;
        }
        
            // ====================================================================
            // ПОДДЕЙСТВИЕ 4.3: ДОПОЛНИТЕЛЬНАЯ ПРОВЕРКА ВОЗРАСТА СЕССИИ
            // ====================================================================
            // Выполняем дополнительную проверку: убеждаемся, что сессия не старше
            // 24 часов от времени создания. Это защита на случай, если expires_at
            // был установлен неправильно или изменен вручную.
        qint64 secondsSinceCreation = createdAt.secsTo(currentTime);
            if (secondsSinceCreation >= SESSION_DURATION_SECONDS) 
            {
            sessionExpired = true;
                qDebug() << "AuthService: Сессия слишком старая. Создана:" << createdAt << ", Возраст:" << secondsSinceCreation << "секунд";
            }
            // Убрали спам-сообщение о валидной сессии - выводим только при проблемах
        } 
        else 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 4.4: СЕССИЯ НЕ НАЙДЕНА В БАЗЕ ДАННЫХ
            // ====================================================================
            // Сессия не найдена в базе данных - это может произойти, если:
            //   - Сессия была удалена из другого экземпляра приложения
            //   - Сессия была удалена администратором
            //   - Произошла ошибка при сохранении сессии
            // В любом случае считаем сессию истекшей.
            sessionExpired = true;
            qDebug() << "AuthService: Токен сессии" << m_currentSessionToken.left(16) << "... не найден в базе данных, сессия истекла";
        }
        query.finish(); // Явно завершаем запрос
        // query уничтожится при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: УДАЛЕНИЕ ИСТЕКШЕЙ СЕССИИ
    // ========================================================================
    // Если сессия истекла, удаляем её из базы данных и очищаем токен в памяти.
    // Это выполняется в отдельном блоке после уничтожения первого запроса.
        if (sessionExpired) {
        {
            QSqlQuery deleteQuery(*db);
            deleteQuery.prepare("DELETE FROM sessions WHERE token = ?");
            deleteQuery.addBindValue(m_currentSessionToken);
            deleteQuery.exec();
            deleteQuery.finish(); // Явно завершаем запрос
            // deleteQuery уничтожится при выходе из блока
        }
        m_currentSessionToken.clear(); // Очищаем токен в памяти
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ЗАКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Закрываем временное соединение с базой данных после завершения всех
    // операций. Это освобождает ресурсы и предотвращает утечки соединений.
    closeDbConnection(db);
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: ВЫХОД ИЗ СИСТЕМЫ ПРИ ИСТЕЧЕНИИ СЕССИИ
    // ========================================================================
    // Если сессия истекла, выполняем выход из системы:
    //   - Очищаем данные пользователя
    //   - Устанавливаем флаг m_isLoggedIn в false
    //   - Испускаем сигнал userLoggedOut() для уведомления UI
    if (sessionExpired) 
    {
        QString email = m_currentUser.getEmail();
        m_currentUser = User();
        m_isLoggedIn = false;
        
        qDebug() << "AuthService: Сессия истекла для пользователя" << email << "- выход из системы";
        emit userLoggedOut();
    }
    
    return !sessionExpired; // Возвращаем true, если сессия валидна (не истекла)
}

// ============================================================================
// МЕТОД cleanupExpiredSessions
// ============================================================================
// Удаляет просроченные записи из таблицы sessions, чтобы БД не росла
// бесконтрольно.
// ============================================================================
void AuthService::cleanupExpiredSessions()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: НАЧАЛО ОЧИСТКИ
    // ========================================================================
    // Выводим отладочное сообщение о начале процесса очистки истекших сессий.
    // Этот метод вызывается периодически для предотвращения роста базы данных.
    qDebug() << "AuthService: Очистка просроченных сессий из базы данных...";
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ОТКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Создаем временное соединение с базой данных для выполнения операций
    // удаления истекших сессий.
    QSqlDatabase *db = getDbConnection();
    if (!db || !db->isOpen()) 
    {
        setError("Не удалось открыть соединение с базой данных для очистки просроченных сессий");
        return; // Не удалось открыть соединение
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПОДГОТОВКА ДАННЫХ ДЛЯ ОЧИСТКИ
    // ========================================================================
    // Получаем текущее время и определяем константу длительности сессии
    // (24 часа = 86400 секунд) для проверки возраста сессий.
    QDateTime currentTime = QDateTime::currentDateTime();
    const int SESSION_DURATION_SECONDS = 86400; // 24 часа
    
    // Счетчики удаленных сессий для статистики
    int deletedByExpiry = 0;
    int deletedByAge = 0;
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: УДАЛЕНИЕ СЕССИЙ ПО ВРЕМЕНИ ИСТЕЧЕНИЯ
    // ========================================================================
    // Удаляем все сессии, у которых время истечения (expires_at) меньше или
    // равно текущему времени. Это основной способ определения истекших сессий.
    {
    QSqlQuery deleteExpiredQuery(*db);
    deleteExpiredQuery.prepare("DELETE FROM sessions WHERE expires_at <= ?");
    deleteExpiredQuery.addBindValue(currentTime.toSecsSinceEpoch());
    
        if (deleteExpiredQuery.exec()) 
        {
        deletedByExpiry = deleteExpiredQuery.numRowsAffected();
    }
        deleteExpiredQuery.finish(); // Явно завершаем запрос
        
        // ====================================================================
        // ДЕЙСТВИЕ 5: УДАЛЕНИЕ СТАРЫХ СЕССИЙ ПО ВОЗРАСТУ
        // ====================================================================
        // Удаляем все сессии, которые старше 24 часов от времени создания,
        // независимо от значения expires_at. Это защита на случай, если
        // expires_at был установлен неправильно или изменен вручную в БД.
        // Используем SQL функцию strftime('%s', 'now') для получения текущего
        // времени в секундах с эпохи Unix.
    QSqlQuery deleteOldQuery(*db);
    deleteOldQuery.prepare("DELETE FROM sessions WHERE (strftime('%s', 'now') - created_at) >= ?");
    deleteOldQuery.addBindValue(SESSION_DURATION_SECONDS);
    
        if (deleteOldQuery.exec()) 
        {
        deletedByAge = deleteOldQuery.numRowsAffected();
    }
        deleteOldQuery.finish(); // Явно завершаем запрос
        // Оба запроса уничтожатся при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ЗАКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Закрываем временное соединение с базой данных после завершения всех
    // операций удаления. Это освобождает ресурсы.
    closeDbConnection(db);
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: ВЫВОД СТАТИСТИКИ ОЧИСТКИ
    // ========================================================================
    // Выводим отладочное сообщение с количеством удаленных сессий.
    // Разделяем статистику по двум критериям удаления (по expires_at и по возрасту)
    // для лучшего понимания процесса очистки.
    int totalDeleted = deletedByExpiry + deletedByAge;
    if (totalDeleted > 0) 
    {
        qDebug() << "AuthService: Очищено" << totalDeleted << "просроченных сессий из базы данных (по истечению:" << deletedByExpiry << ", по возрасту:" << deletedByAge << ")";
    } 
    else 
    {
        qDebug() << "AuthService: Нет просроченных сессий для очистки";
    }
}

// ============================================================================
// МЕТОД getUserSessions
// ============================================================================
// Возвращает список активных сессий конкретного пользователя для UI.
// ============================================================================
QList<QMap<QString, QVariant>> AuthService::getUserSessions(int userId)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ИНИЦИАЛИЗАЦИЯ РЕЗУЛЬТАТА
    // ========================================================================
    // Создаем пустой список для хранения сессий пользователя.
    // Каждая сессия будет представлена как QMap с ключами: token, user_id,
    // user_email, created_at, expires_at.
    QList<QMap<QString, QVariant>> sessions;
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВАЛИДАЦИЯ ПАРАМЕТРА USER_ID
    // ========================================================================
    // Проверяем, что userId валиден (больше 0). Если userId невалиден,
    // возвращаем пустой список, так как невозможно найти сессии для
    // несуществующего пользователя.
    if (userId <= 0) 
    {
        return sessions; // userId невалиден
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ОТКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Создаем временное соединение с базой данных для выполнения запроса
    // на получение сессий пользователя.
    QSqlDatabase *db = getDbConnection();
    if (!db || !db->isOpen()) 
    {
        setError("Не удалось открыть соединение с базой данных для получения сессий пользователя");
        return sessions; // Не удалось открыть соединение
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ВЫПОЛНЕНИЕ ЗАПРОСА НА ПОЛУЧЕНИЕ СЕССИЙ
    // ========================================================================
    // Запрашиваем все активные (не истекшие) сессии указанного пользователя
    // из базы данных. Сессии сортируются по времени создания (от новых к старым).
    QDateTime currentTime = QDateTime::currentDateTime();
    {
    QSqlQuery query(*db);
    query.prepare("SELECT token, user_id, user_email, created_at, expires_at FROM sessions WHERE user_id = ? AND expires_at > ? ORDER BY created_at DESC");
    query.addBindValue(userId);
    query.addBindValue(currentTime.toSecsSinceEpoch());
    
        if (!query.exec()) 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 4.1: ОШИБКА ПРИ ВЫПОЛНЕНИИ ЗАПРОСА
            // ====================================================================
            // Запрос не выполнен - выводим предупреждение с текстом ошибки и
            // возвращаем пустой список.
            setError("Не удалось получить сессии пользователя: " + query.lastError().text());
            query.finish(); // Явно завершаем запрос
            closeDbConnection(db);
            return sessions; // Ошибка при выполнении запроса
    }
    
        // ====================================================================
        // ПОДДЕЙСТВИЕ 4.2: ОБРАБОТКА РЕЗУЛЬТАТОВ ЗАПРОСА
        // ====================================================================
        // Перебираем все строки результата запроса и формируем список сессий.
        // Каждая сессия преобразуется в QMap для удобного доступа к данным
        // в UI (например, через session["token"], session["created_at"] и т.д.).
        while (query.next()) 
        {
        QMap<QString, QVariant> session;
        session["token"] = query.value("token").toString();
        session["user_id"] = query.value("user_id").toInt();
        session["user_email"] = query.value("user_email").toString();
        session["created_at"] = QDateTime::fromSecsSinceEpoch(query.value("created_at").toLongLong());
        session["expires_at"] = QDateTime::fromSecsSinceEpoch(query.value("expires_at").toLongLong());
        sessions.append(session);
    }
        query.finish(); // Явно завершаем запрос
        // query уничтожится при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ЗАКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Закрываем временное соединение с базой данных после завершения всех
    // операций. Это освобождает ресурсы.
    closeDbConnection(db);
    
    return sessions; // Возвращаем список сессий пользователя
}

