// ============================================================================
// МЕТОД terminateSession
// ============================================================================
// Удаляет конкретную сессию по токену, используется для ручного выхода
// или админского кика.
// ============================================================================
bool AuthService::terminateSession(const QString &token)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ВАЛИДАЦИЯ ТОКЕНА
    // ========================================================================
    // Проверяем, что токен не пустой. Пустой токен не может быть использован
    // для поиска и удаления сессии в базе данных.
    if (token.isEmpty()) 
    {
        m_lastError = "Токен сессии не может быть пустым";
        return false; // Токен пустой
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ОТКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Создаем временное соединение с базой данных для выполнения операции
    // удаления сессии.
    QSqlDatabase *db = getDbConnection();
    if (!db || !db->isOpen()) 
    {
        setError("Не удалось открыть соединение с базой данных для удаления сессии");
        m_lastError = "Не удалось открыть базу данных";
        return false; // Не удалось открыть соединение
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: УДАЛЕНИЕ СЕССИИ ИЗ БАЗЫ ДАННЫХ
    // ========================================================================
    // Удаляем сессию с указанным токеном из базы данных. Если сессия не найдена,
    // операция все равно считается успешной (нет ошибки), так как цель
    // (отсутствие сессии) достигнута.
    bool success = false;
    {
    QSqlQuery query(*db);
    query.prepare("DELETE FROM sessions WHERE token = ?");
    query.addBindValue(token);
    
        success = query.exec();
        if (!success) 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 3.1: ОШИБКА ПРИ УДАЛЕНИИ
            // ====================================================================
            // Не удалось выполнить запрос на удаление - сохраняем текст ошибки
            // для последующего отображения пользователю.
        m_lastError = "Не удалось завершить сессию: " + query.lastError().text();
        } 
        else 
        {
            // ====================================================================
            // ПОДДЕЙСТВИЕ 3.2: УСПЕШНОЕ УДАЛЕНИЕ
            // ====================================================================
            // Сессия успешно удалена - выводим отладочное сообщение.
            // Показываем только первые 16 символов токена для безопасности.
            qDebug() << "AuthService: Сессия успешно удалена:" << token.left(16) << "...";
    }
        query.finish(); // Явно завершаем запрос
        // query уничтожится при выходе из блока
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ЗАКРЫТИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Закрываем временное соединение с базой данных после завершения операции
    // удаления. Это освобождает ресурсы.
    closeDbConnection(db);
    
    return success; // Возвращаем результат операции (true при успехе)
}

// ============================================================================
// МЕТОД closeDbConnection
// ============================================================================
// Завершает временное соединение с SQLite, дожидаясь освобождения
// ресурсов, прежде чем удалить connectionName.
// ============================================================================
void AuthService::closeDbConnection(QSqlDatabase *db)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА ВАЛИДНОСТИ УКАЗАТЕЛЯ
    // ========================================================================
    // Проверяем, что указатель на объект QSqlDatabase не является nullptr.
    // Если указатель невалиден, нет необходимости выполнять операции закрытия.
    if (!db) 
    {
        return; // Указатель невалиден, выход из метода
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: СОХРАНЕНИЕ ИМЕНИ СОЕДИНЕНИЯ
    // ========================================================================
    // Сохраняем имя соединения (connectionName) перед закрытием, так как
    // оно понадобится для удаления соединения из пула Qt после уничтожения
    // объекта QSqlDatabase.
    const QString connectionName = db->connectionName();
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ЗАКРЫТИЕ СОЕДИНЕНИЯ
    // ========================================================================
    // Закрываем соединение с базой данных. Это освобождает ресурсы драйвера
    // SQLite, но соединение еще остается в пуле Qt под именем connectionName.
    db->close();
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ОБРАБОТКА СОБЫТИЙ ДЛЯ ОСВОБОЖДЕНИЯ РЕСУРСОВ
    // ========================================================================
    // Обрабатываем события Qt несколько раз, чтобы дать драйверу SQLite время
    // завершить все отложенные операции и освободить ресурсы, связанные с
    // соединением. Используем ExcludeUserInputEvents, чтобы не блокировать
    // пользовательский интерфейс.
    for (int i = 0; i < 5; ++i) 
    {
        QCoreApplication::processEvents(QEventLoop::ExcludeUserInputEvents);
    }

    // ========================================================================
    // ДЕЙСТВИЕ 5: УНИЧТОЖЕНИЕ ОБЪЕКТА QSQLDATABASE
    // ========================================================================
    // Уничтожаем объект QSqlDatabase до удаления connectionName из пула Qt.
    // Это гарантирует, что не останется активных ссылок на connectionName,
    // что предотвращает предупреждения Qt о том, что соединение все еще используется.
    delete db;
    db = nullptr;
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ДОПОЛНИТЕЛЬНАЯ ОБРАБОТКА СОБЫТИЙ
    // ========================================================================
    // Выполняем еще несколько итераций обработки событий на случай отложенных
    // операций драйвера SQLite, которые могут быть связаны с уничтожением
    // объекта QSqlDatabase.
    for (int i = 0; i < 3; ++i) 
    {
        QCoreApplication::processEvents(QEventLoop::ExcludeUserInputEvents);
    }

    // ========================================================================
    // ДЕЙСТВИЕ 7: УДАЛЕНИЕ СОЕДИНЕНИЯ ИЗ ПУЛА QT
    // ========================================================================
    // Удаляем connectionName из пула Qt, если соединение все еще зарегистрировано.
    // Это финальный шаг, который полностью освобождает ресурсы, связанные
    // с соединением. Проверка QSqlDatabase::contains() предотвращает ошибки,
    // если соединение уже было удалено.
    if (QSqlDatabase::contains(connectionName)) 
    {
        QSqlDatabase::removeDatabase(connectionName);
}
}

// ============================================================================
// МЕТОД getDbConnection
// ============================================================================
// Создает уникальное подключение к SQLite для операций с таблицей
// сессий. Вызывает вызывающего освобождать соединение через closeDbConnection.
// ============================================================================
QSqlDatabase* AuthService::getDbConnection() const
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ГЕНЕРАЦИЯ УНИКАЛЬНОГО ИМЕНИ СОЕДИНЕНИЯ
    // ========================================================================
    // Генерируем уникальное имя соединения, используя статический счетчик.
    // Каждое новое соединение получает уникальное имя (auth_db_1, auth_db_2, ...),
    // что позволяет создавать множественные временные соединения без конфликтов.
    static int connectionCounter = 0;
    QString connectionName = QString("auth_db_%1").arg(++connectionCounter);
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: СОЗДАНИЕ СОЕДИНЕНИЯ С БАЗОЙ ДАННЫХ
    // ========================================================================
    // Создаем новое соединение с SQLite, используя сгенерированное имя.
    // Соединение регистрируется в пуле Qt под этим именем.
    QSqlDatabase db = QSqlDatabase::addDatabase("QSQLITE", connectionName);
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ОПРЕДЕЛЕНИЕ ПУТИ К БАЗЕ ДАННЫХ
    // ========================================================================
    // Определяем путь к базе данных пользователей (3fa_users.db) аналогично
    // методу Database::connect(). Это необходимо для корректной работы как
    // в режиме разработки (бинарник в build/), так и в macOS bundle
    // (бинарник в 3FA.app/Contents/MacOS/).
    QString appDir = QCoreApplication::applicationDirPath();
    QDir baseDir(appDir);
    
    // ========================================================================
    // ПОДДЕЙСТВИЕ 3.1: ОБРАБОТКА MACOS BUNDLE
    // ========================================================================
    // Если приложение запущено из macOS bundle, путь к бинарнику содержит
    // "/Contents/MacOS". В этом случае нужно подняться на 4 уровня вверх
    // (../../../../) для получения корневой директории проекта.
    if (appDir.contains("/Contents/MacOS")) 
    {
        baseDir = QDir(baseDir.absoluteFilePath("../../../../"));
    } 
    else 
    {
        // ====================================================================
        // ПОДДЕЙСТВИЕ 3.2: ОБРАБОТКА ОБЫЧНОГО РЕЖИМА РАЗРАБОТКИ
        // ====================================================================
        // В режиме разработки бинарник обычно находится в build/.
        // Проверяем наличие CMakeLists.txt в родительской директории для
        // подтверждения, что это корневая директория проекта.
        QDir tryBuildParent(baseDir.absoluteFilePath(".."));
        if (tryBuildParent.exists("CMakeLists.txt")) 
        {
            baseDir = tryBuildParent;
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: УСТАНОВКА ПУТИ К БАЗЕ ДАННЫХ
    // ========================================================================
    // Формируем полный путь к базе данных пользователей (databases/3fa_users.db)
    // относительно корневой директории проекта и устанавливаем его для соединения.
    QString dbPath = baseDir.absoluteFilePath("databases/3fa_users.db");
    db.setDatabaseName(dbPath);
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ОТКРЫТИЕ СОЕДИНЕНИЯ
    // ========================================================================
    // Открываем соединение с базой данных. Если открытие не удалось, удаляем
    // соединение из пула Qt и возвращаем nullptr.
    if (!db.open()) 
    {
        qWarning() << "AuthService: Не удалось открыть базу данных:" << db.lastError().text();
        QSqlDatabase::removeDatabase(connectionName);
        return nullptr; // Не удалось открыть соединение
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: СОЗДАНИЕ УКАЗАТЕЛЯ НА СОЕДИНЕНИЕ
    // ========================================================================
    // Создаем указатель на объект QSqlDatabase, используя QSqlDatabase::database()
    // для получения соединения по имени. Это позволяет вызывающему коду
    // использовать соединение, которое будет правильно закрыто через closeDbConnection().
    QSqlDatabase* dbPtr = new QSqlDatabase(QSqlDatabase::database(connectionName));
    return dbPtr; // Возвращаем указатель на соединение
}

// ============================================================================
// МЕТОД hashPassword
// ============================================================================
// Генерирует соль, вычисляет хеш Stribog-256 и возвращает результат
// в удобном виде SALT:HASH (base64).
// ============================================================================
QString AuthService::hashPassword(const QString &password)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ГЕНЕРАЦИЯ СЛУЧАЙНОЙ СОЛИ
    // ========================================================================
    // Генерируем криптографически стойкую случайную соль, используя
    // QRandomGenerator::global()->generate64() для получения 64-битного
    // случайного числа. Соль преобразуется в строку для последующего
    // объединения с паролем. Использование соли предотвращает атаки
    // по радужным таблицам (rainbow tables) и обеспечивает уникальность
    // хеша даже для одинаковых паролей.
    QByteArray salt = QByteArray::number(QRandomGenerator::global()->generate64());
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПОДГОТОВКА ДАННЫХ ДЛЯ ХЕШИРОВАНИЯ
    // ========================================================================
    // Объединяем пароль (в UTF-8 кодировке) и соль для последующего
    // хеширования. Порядок важен: пароль + соль. Это гарантирует, что
    // даже при одинаковых паролях хеш будет разным из-за уникальной соли.
    QByteArray dataToHash = password.toUtf8() + salt;
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ВЫЧИСЛЕНИЕ ХЕША STRIBOG-256
    // ========================================================================
    // Вычисляем криптографический хеш от объединенных данных (пароль + соль)
    // с использованием алгоритма Stribog-256 (ГОСТ Р 34.11-2012).
    // Stribog-256 генерирует 256-битный (32 байта) хеш, который обеспечивает
    // криптографическую стойкость и соответствует российским стандартам.
    QByteArray hashResult = StribogHash::hash256(dataToHash);
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ФОРМИРОВАНИЕ РЕЗУЛЬТАТА
    // ========================================================================
    // Формируем результат в формате "salt:hash" и кодируем его в base64
    // для удобного хранения в базе данных. Разделитель ":" позволяет
    // впоследствии извлечь соль и хеш при проверке пароля.
    QByteArray result = salt + ":" + hashResult;
    return result.toBase64(); // Возвращаем результат в формате base64
}

// ============================================================================
// МЕТОД verifyPassword
// ============================================================================
// Раскодирует сохраненный SALT:HASH, пересчитывает Stribog-256 и
// сравнивает результаты.
// ============================================================================
bool AuthService::verifyPassword(const QString &password, const QString &hash)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ДЕКОДИРОВАНИЕ BASE64
    // ========================================================================
    // Декодируем сохраненный хеш из формата base64 обратно в бинарные данные.
    // Хеш был сохранен в формате base64(salt:hash) при регистрации или
    // изменении пароля.
    QByteArray decoded = QByteArray::fromBase64(hash.toUtf8());
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ИЗВЛЕЧЕНИЕ СОЛИ И ХЕША
    // ========================================================================
    // Разделяем декодированные данные на соль и хеш, используя разделитель ":".
    // Если разделитель не найден, это означает, что формат хеша неверный,
    // и пароль не может быть проверен.
    int separatorIndex = decoded.indexOf(':');
    if (separatorIndex == -1) 
    {
        return false; // Неверный формат хеша (нет разделителя)
    }
    
    // Извлекаем соль (все символы до разделителя) и сохраненный хеш
    // (все символы после разделителя).
    QByteArray salt = decoded.left(separatorIndex);
    QByteArray storedHash = decoded.mid(separatorIndex + 1);
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ВЫЧИСЛЕНИЕ ХЕША ДЛЯ ВВЕДЕННОГО ПАРОЛЯ
    // ========================================================================
    // Вычисляем хеш для введенного пароля, используя ту же соль, что была
    // использована при создании сохраненного хеша. Порядок объединения
    // должен быть таким же: пароль + соль.
    QByteArray dataToHash = password.toUtf8() + salt;
    QByteArray calculatedHash = StribogHash::hash256(dataToHash);
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: СРАВНЕНИЕ ХЕШЕЙ
    // ========================================================================
    // Сравниваем вычисленный хеш с сохраненным хешем. Если хеши совпадают,
    // пароль верный. Используется константное время сравнения (QByteArray::operator==)
    // для предотвращения атак по времени выполнения (timing attacks).
    return calculatedHash == storedHash; // Возвращаем true, если пароль верный
}

// ============================================================================
// МЕТОД validateRegistrationData
// ============================================================================
// Проверяет корректность email/пароля при регистрации с выдачей
// локализованных сообщений об ошибках.
// ============================================================================
bool AuthService::validateRegistrationData(const QString &email, const QString &password)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ВАЛИДАЦИЯ EMAIL
    // ========================================================================
    // Проверяем корректность формата email с использованием метода
    // User::isValidEmail(). Email должен содержать символ @ и точку,
    // иметь корректную структуру (например, user@example.com).
    // Если email невалиден, сохраняем ошибку и возвращаем false.
    if (!User::isValidEmail(email)) 
    {
        setError("Некорректный формат email");
        return false; // Email невалиден
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВАЛИДАЦИЯ ПАРОЛЯ
    // ========================================================================
    // Проверяем, что пароль соответствует требованиям безопасности с использованием
    // метода User::isValidPassword(). Пароль должен:
    //   - Содержать минимум 8 символов
    //   - Содержать хотя бы одну заглавную букву
    //   - Содержать хотя бы одну строчную букву
    //   - Содержать хотя бы одну цифру
    // Если пароль невалиден, сохраняем детальное сообщение об ошибке и возвращаем false.
    if (!User::isValidPassword(password)) 
    {
        setError("Пароль должен содержать минимум 8 символов, включая заглавные и строчные буквы, а также цифры");
        return false; // Пароль невалиден
    }
    
    return true; // Все проверки пройдены, данные валидны
}

// ============================================================================
// МЕТОД validateLoginData
// ============================================================================
// Минимальные проверки перед попыткой входа (пустые поля и т.п.).
// ============================================================================
bool AuthService::validateLoginData(const QString &email, const QString &password)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА EMAIL НА ПУСТОТУ
    // ========================================================================
    // Выполняем минимальную проверку: email не должен быть пустым.
    // Более детальная проверка формата email не требуется при входе,
    // так как пользователь уже зарегистрирован и формат был проверен
    // при регистрации. Если email пустой, сохраняем ошибку и возвращаем false.
    if (email.isEmpty()) 
    {
        setError("Email не может быть пустым");
        return false; // Email пустой
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПРОВЕРКА ПАРОЛЯ НА ПУСТОТУ
    // ========================================================================
    // Выполняем минимальную проверку: пароль не должен быть пустым.
    // Более детальная проверка требований безопасности не требуется при входе,
    // так как пароль уже соответствует требованиям (был проверен при регистрации).
    // Если пароль пустой, сохраняем ошибку и возвращаем false.
    if (password.isEmpty()) 
    {
        setError("Пароль не может быть пустым");
        return false; // Пароль пустой
    }
    
    return true; // Все проверки пройдены, данные валидны
}

// ============================================================================
// МЕТОД setError
// ============================================================================
// Унифицированно сохраняет текст ошибки и пишет его в журнал отладки.
// ============================================================================
void AuthService::setError(const QString &error)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: СОХРАНЕНИЕ ТЕКСТА ОШИБКИ
    // ========================================================================
    // Сохраняем текст ошибки в поле m_lastError для последующего получения
    // через метод getLastError(). Это позволяет UI и другим компонентам
    // получить детальную информацию об ошибке для отображения пользователю.
    m_lastError = error;
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВЫВОД ОШИБКИ В ЖУРНАЛ ОТЛАДКИ
    // ========================================================================
    // Выводим текст ошибки в журнал отладки через qDebug() для помощи
    // при разработке и отладке. Это позволяет разработчикам видеть
    // все ошибки, возникающие в процессе работы сервиса аутентификации.
    qDebug() << "AuthService Error:" << error;
}
