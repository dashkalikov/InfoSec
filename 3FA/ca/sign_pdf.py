#!/usr/bin/env python3
# ============================================================================
# СКРИПТ SIGN_PDF.PY - ПОДПИСАНИЕ PDF ДОКУМЕНТОВ С ЭЦП
# ============================================================================
# Этот скрипт подписывает PDF документы цифровой подписью с использованием
# библиотеки pyHanko и электронной цифровой подписи (ЭЦП). Поддерживает
# видимые и невидимые подписи, встраивание цепочки сертификатов, временные
# метки (TSA) и извлечение метаданных из сертификата.
#
# НАЗНАЧЕНИЕ:
# - Подписание PDF документов цифровой подписью для обеспечения целостности
# - Встраивание цепочки сертификатов в PDF для проверки подписи
# - Добавление временных меток (TSA) для доказательства времени подписания
# - Извлечение и отображение метаданных сертификата в подписи
#
# АЛГОРИТМ РАБОТЫ:
# 1. Парсинг аргументов командной строки
# 2. Проверка существования входных файлов (PDF, сертификат, ключ)
# 3. Настройка путей к библиотекам Python (site-packages)
# 4. Импорт необходимых библиотек (pyhanko, cryptography)
# 5. Валидация PDF файла (проверка размера и маркера %%EOF)
# 6. Определение количества страниц в PDF
# 7. Загрузка подписанта с цепочкой сертификатов (если указан root-cert)
# 8. Извлечение метаданных из сертификата (CN, отпечаток, серийный номер)
# 9. Формирование метаданных подписи (reason, location, contact_info)
# 10. Настройка DSS (Document Security Store) для встраивания корневого CA
# 11. Создание спецификации поля подписи (видимое или невидимое)
# 12. Подписание PDF (синхронно или асинхронно с временной меткой)
#
# ПРОТОКОЛ ИСПОЛЬЗОВАНИЯ:
# Базовое использование:
#   python3 sign_pdf.py --input in.pdf --output out.pdf --cert signer.crt --key signer.key
#
# С дополнительными параметрами:
#   python3 sign_pdf.py --input in.pdf --output out.pdf --cert signer.crt --key signer.key \
#     --root-cert root.crt --reason "Подписание документа" --location "3FA Приложение" \
#     --visible --x 50 --y 50 --width 250 --height 120
#
# С временной меткой (TSA):
#   python3 sign_pdf.py --input in.pdf --output out.pdf --cert signer.crt --key signer.key \
#     --tsa-url http://timestamp.server/rfc3161
#
# КОДЫ ВОЗВРАТА:
# 0  - Успешное выполнение
# 2  - Ошибка: входной файл не найден
# 90 - Ошибка: pyhanko не установлен
# 91 - Ошибка: aiohttp не установлен (для TSA) или не удалось загрузить ключ/сертификат
# 92 - Ошибка: ошибка подписания PDF
# 93 - Ошибка: входной PDF слишком мал
# 94 - Ошибка: входной PDF не содержит маркер %%EOF
# ============================================================================

# ============================================================================
# ИМПОРТЫ СТАНДАРТНОЙ БИБЛИОТЕКИ
# ============================================================================
import argparse  # Парсинг аргументов командной строки
import sys       # Системные функции (stderr, exit, path)
import site      # Работа с site-packages для поиска установленных библиотек
from pathlib import Path  # Работа с путями к файлам (кроссплатформенно)


# ============================================================================
# ФУНКЦИЯ main - ГЛАВНАЯ ФУНКЦИЯ СКРИПТА
# ============================================================================
# Основная функция для подписания PDF документов цифровой подписью.
# Обрабатывает аргументы командной строки, валидирует входные файлы,
# загружает сертификат и ключ, извлекает метаданные, формирует подпись
# и сохраняет подписанный PDF.
#
# АЛГОРИТМ:
# 1. Парсинг аргументов командной строки
# 2. Проверка существования входных файлов
# 3. Настройка путей к библиотекам Python
# 4. Импорт необходимых библиотек
# 5. Валидация PDF файла
# 6. Определение количества страниц
# 7. Загрузка подписанта с цепочкой сертификатов
# 8. Извлечение метаданных из сертификата
# 9. Формирование метаданных подписи
# 10. Настройка DSS для встраивания корневого CA
# 11. Создание спецификации поля подписи
# 12. Подписание PDF
#
# ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
#   int - код возврата (0 при успехе, >0 при ошибке)
# ============================================================================
def main() -> int:
    # ========================================================================
    # ДЕЙСТВИЕ 1: ПАРСИНГ АРГУМЕНТОВ КОМАНДНОЙ СТРОКИ
    # ========================================================================
    # Создаем парсер аргументов командной строки
    # argparse.ArgumentParser предоставляет удобный интерфейс для обработки
    # аргументов командной строки с автоматической генерацией справки
    parser = argparse.ArgumentParser(description="Подписание PDF с использованием pyHanko.")
    
    # ========================================================================
    # ОБЯЗАТЕЛЬНЫЕ АРГУМЕНТЫ
    # ========================================================================
    # Эти аргументы должны быть указаны при запуске скрипта
    # required=True означает, что аргумент обязателен для указания
    
    # --input: путь к входному PDF файлу для подписания
    #   Формат: строка с путем к файлу (абсолютный или относительный)
    #   Пример: --input /path/to/document.pdf
    parser.add_argument("--input", required=True, help="Путь к входному PDF файлу.")
    
    # --output: путь для сохранения подписанного PDF файла
    #   Формат: строка с путем к файлу (абсолютный или относительный)
    #   Файл будет создан или перезаписан, если существует
    #   Пример: --output /path/to/signed_document.pdf
    parser.add_argument("--output", required=True, help="Путь для сохранения подписанного PDF файла.")
    
    # --cert: путь к сертификату подписанта в формате PEM
    #   Формат: строка с путем к файлу сертификата (PEM - текстовый формат Base64)
    #   Сертификат должен содержать публичный ключ подписанта
    #   Пример: --cert /path/to/signer.crt
    parser.add_argument("--cert", required=True, help="Сертификат подписанта в формате PEM.")
    
    # --key: путь к приватному ключу подписанта в формате PEM
    #   Формат: строка с путем к файлу приватного ключа (PEM - текстовый формат Base64)
    #   Приватный ключ используется для создания цифровой подписи
    #   Пример: --key /path/to/signer.key
    parser.add_argument("--key", required=True, help="Приватный ключ подписанта в формате PEM.")
    
    # ========================================================================
    # ОПЦИОНАЛЬНЫЕ АРГУМЕНТЫ
    # ========================================================================
    # Эти аргументы могут быть указаны для дополнительной настройки подписи
    # Если не указаны, используются значения по умолчанию
    
    # --root-cert: путь к корневому CA сертификату в формате PEM
    #   Формат: строка с путем к файлу корневого сертификата
    #   Назначение: встраивание корневого CA в PDF для проверки подписи без
    #               необходимости загружать промежуточные сертификаты
    #   Если указан, будет встроен в DSS (Document Security Store) PDF
    #   Пример: --root-cert /path/to/root_ca.crt
    parser.add_argument("--root-cert", help="Корневой CA сертификат в формате PEM (для встраивания в PDF).")
    
    # --tsa-url: URL сервера временных меток (TSA - Time Stamping Authority)
    #   Формат: строка с HTTP/HTTPS URL сервера TSA (RFC 3161)
    #   Назначение: добавление временной метки к подписи для доказательства
    #               времени подписания документа
    #   Требует установки библиотеки aiohttp для асинхронных HTTP запросов
    #   Пример: --tsa-url http://timestamp.server/rfc3161
    parser.add_argument("--tsa-url", help="URL TSA (Time Stamping Authority) для добавления временной метки к подписи (RFC 3161).")
    
    # --reason: причина подписания документа
    #   Формат: строка с текстом причины
    #   Назначение: отображается в свойствах подписи PDF читалками
    #   Значение по умолчанию: "" (пустая строка, будет использовано "Подписание документа")
    #   Пример: --reason "Одобрение документа"
    parser.add_argument("--reason", default="", help="Причина подписания.")
    
    # --location: место подписания документа
    #   Формат: строка с текстом местоположения
    #   Назначение: отображается в свойствах подписи PDF читалками
    #   Значение по умолчанию: "" (пустая строка, будет использовано "3FA Приложение")
    #   Пример: --location "Москва, офис"
    parser.add_argument("--location", default="", help="Место подписания.")
    
    # --field: имя поля подписи в PDF
    #   Формат: строка с именем поля
    #   Назначение: идентификатор поля подписи в PDF документе
    #   Значение по умолчанию: "Signature1"
    #   Если поле с таким именем уже существует, будет использовано существующее
    #   Пример: --field "MySignature"
    parser.add_argument("--field", default="Signature1", help="Имя поля подписи для создания/использования.")
    
    # --visible: флаг создания видимой подписи на последней странице
    #   Формат: флаг (не требует значения, просто --visible)
    #   Назначение: создает визуальное поле подписи на последней странице PDF
    #   action="store_true" означает, что при наличии флага значение будет True
    #   Если флаг не указан, подпись будет невидимой (но присутствующей в документе)
    #   Пример: --visible
    parser.add_argument("--visible", action="store_true", help="Создать видимую подпись на последней странице.")
    
    # --x: X координата видимой подписи (расстояние от левого края страницы)
    #   Формат: число с плавающей точкой (в точках PDF, 72 точки = 1 дюйм)
    #   Назначение: горизонтальная позиция левого нижнего угла рамки подписи
    #   Значение по умолчанию: 50.0 точек (≈0.7 дюйма от левого края)
    #   Используется только если указан флаг --visible
    #   Пример: --x 100.0
    parser.add_argument("--x", type=float, default=50.0, help="X позиция для видимой подписи (по умолчанию: 50).")
    
    # --y: Y координата видимой подписи (расстояние от нижнего края страницы)
    #   Формат: число с плавающей точкой (в точках PDF, 72 точки = 1 дюйм)
    #   Назначение: вертикальная позиция левого нижнего угла рамки подписи
    #   Значение по умолчанию: 50.0 точек (≈0.7 дюйма от нижнего края)
    #   Используется только если указан флаг --visible
    #   Минимальное значение: 50.0 (для предотвращения перекрытия текста)
    #   Пример: --y 100.0
    parser.add_argument("--y", type=float, default=50.0, help="Y позиция для видимой подписи (по умолчанию: 50).")
    
    # --width: ширина рамки видимой подписи
    #   Формат: число с плавающей точкой (в точках PDF, 72 точки = 1 дюйм)
    #   Назначение: ширина прямоугольной рамки подписи на странице
    #   Значение по умолчанию: 250.0 точек (≈3.5 дюйма)
    #   Используется только если указан флаг --visible
    #   Пример: --width 300.0
    parser.add_argument("--width", type=float, default=250.0, help="Ширина рамки подписи (по умолчанию: 250).")
    
    # --height: высота рамки видимой подписи
    #   Формат: число с плавающей точкой (в точках PDF, 72 точки = 1 дюйм)
    #   Назначение: высота прямоугольной рамки подписи на странице
    #   Значение по умолчанию: 120.0 точек (≈1.7 дюйма)
    #   Используется только если указан флаг --visible
    #   Пример: --height 150.0
    parser.add_argument("--height", type=float, default=120.0, help="Высота рамки подписи (по умолчанию: 120).")
    
    # Парсим аргументы командной строки
    # args - объект с атрибутами для каждого аргумента
    args = parser.parse_args()

    # ========================================================================
    # ДЕЙСТВИЕ 2: ПРЕОБРАЗОВАНИЕ АРГУМЕНТОВ В ПУТИ
    # ========================================================================
    # Преобразуем строковые пути в объекты Path для удобной работы с файлами
    # Path предоставляет кроссплатформенные методы для работы с путями
    input_path = Path(args.input)      # Путь к входному PDF файлу
    output_path = Path(args.output)    # Путь для сохранения подписанного PDF
    cert_path = Path(args.cert)        # Путь к сертификату подписанта (PEM формат)
    key_path = Path(args.key)          # Путь к приватному ключу подписанта (PEM формат)
    
    # root_cert_path - путь к корневому CA сертификату (опционально)
    # Если аргумент не указан, устанавливаем None
    root_cert_path = Path(args.root_cert) if args.root_cert else None

    # ========================================================================
    # ДЕЙСТВИЕ 3: ПРОВЕРКА СУЩЕСТВОВАНИЯ ВХОДНЫХ ФАЙЛОВ
    # ========================================================================
    # Проверяем наличие всех необходимых файлов перед началом обработки
    # Это позволяет быстро выявить ошибки без выполнения длительных операций
    
    # Проверка входного PDF файла
    if not input_path.exists():
        sys.stderr.write(f"Входной PDF файл не найден: {input_path}\n")
        return 2
    
    # Проверка сертификата подписанта
    if not cert_path.exists():
        sys.stderr.write(f"Сертификат не найден: {cert_path}\n")
        return 2
    
    # Проверка приватного ключа
    if not key_path.exists():
        sys.stderr.write(f"Приватный ключ не найден: {key_path}\n")
        return 2

    # ========================================================================
    # ДЕЙСТВИЕ 4: НАСТРОЙКА ПУТЕЙ К БИБЛИОТЕКАМ PYTHON
    # ========================================================================
    # Обеспечиваем доступность user site-packages (важно при запуске из
    # урезанного окружения). Также проверяем стандартные пути установки на macOS/Linux
    # Это необходимо, так как pyhanko может быть установлен в user site-packages
    
    # Получаем путь к user site-packages
    # site.getusersitepackages() возвращает путь к директории, где пользователь
    # устанавливает пакеты через pip install --user
    user_site = site.getusersitepackages()
    
    # Добавляем user site-packages в sys.path, если он существует и еще не добавлен
    # sys.path - список путей, где Python ищет модули при импорте
    if user_site and user_site not in sys.path:
        sys.path.insert(0, user_site)
    
    # Добавляем альтернативные пути для macOS
    # На macOS библиотеки могут быть установлены в Library/Python/{version}/lib/python/site-packages
    home = Path.home()  # Домашняя директория пользователя
    
    # Проверяем стандартные пути для разных версий Python на macOS
    # Перебираем версии от новой к старой для приоритета более новых версий
    for ver in ['3.14', '3.13', '3.12', '3.11', '3.10', '3.9']:
        # Формируем путь к site-packages для конкретной версии Python
        alt_path = home / f'Library/Python/{ver}/lib/python/site-packages'
        
        # Добавляем путь, если он существует и еще не добавлен
        if alt_path.exists() and str(alt_path) not in sys.path:
            sys.path.insert(0, str(alt_path))

    # ========================================================================
    # ДЕЙСТВИЕ 5: ИМПОРТ ОСНОВНЫХ БИБЛИОТЕК
    # ========================================================================
    # Импортируем необходимые библиотеки для работы с PDF и цифровыми подписями
    # Импорт выполняется в try-except для обработки ошибок отсутствия библиотек
    try:
        # pyhanko.sign.signers - модуль для создания подписантов и подписания PDF
        # signers содержит классы SimpleSigner и функции sign_pdf, async_sign_pdf
        from pyhanko.sign import signers, fields
        
        # IncrementalPdfFileWriter - класс для инкрементальной записи в PDF
        # Позволяет добавлять подпись к существующему PDF без перезаписи всего файла
        from pyhanko.pdf_utils.incremental_writer import IncrementalPdfFileWriter
        
        # PdfSignatureMetadata - класс для метаданных подписи
        # Содержит информацию о подписи: reason, location, name, contact_info и т.д.
        from pyhanko.sign.signers.pdf_signer import PdfSignatureMetadata
        
        # serialization - модуль для сериализации криптографических объектов
        # Используется для преобразования сертификата в DER формат
        from cryptography.hazmat.primitives import serialization
        
    except ImportError as exc:
        # Если библиотека не установлена, выводим сообщение об ошибке
        sys.stderr.write(
            "pyhanko не установлен или отсутствует зависимость. "
            "Установите: 'python3 -m pip install pyhanko'.\n"
            f"Ошибка импорта: {exc}\n"
        )
        return 90
    
    # ========================================================================
    # ДЕЙСТВИЕ 6: УСЛОВНЫЙ ИМПОРТ АСИНХРОННЫХ БИБЛИОТЕК
    # ========================================================================
    # Импортируем асинхронные библиотеки только если указан TSA URL
    # Эти импорты условные и могут быть недоступны, если aiohttp не установлен
    aiohttp_available = False  # Флаг доступности aiohttp
    asyncio_available = False  # Флаг доступности asyncio
    
    # Проверяем, указан ли TSA URL (временная метка)
    if args.tsa_url:
        try:
            # asyncio - библиотека для асинхронного программирования
            # Необходима для выполнения асинхронных HTTP запросов к TSA серверу
            import asyncio  # type: ignore
            
            # aiohttp - библиотека для асинхронных HTTP запросов
            # Используется для отправки запросов к TSA серверу для получения временной метки
            import aiohttp  # type: ignore
            
            # Устанавливаем флаги доступности
            aiohttp_available = True
            asyncio_available = True
            
        except ImportError as exc:
            # Если библиотеки не установлены, выводим сообщение об ошибке
            sys.stderr.write(
                "aiohttp требуется для поддержки временных меток, но не установлен. "
                "Установите: 'python3 -m pip install aiohttp'.\n"
                f"Ошибка импорта: {exc}\n"
            )
            return 91

    # ========================================================================
    # ДЕЙСТВИЕ 7: ОБРАБОТКА PDF ФАЙЛА
    # ========================================================================
    # Основной блок обработки PDF файла и создания подписи
    # Весь код обернут в try-except для обработки ошибок подписания
    try:
        # ========================================================================
        # ДЕЙСТВИЕ 7.1: ВАЛИДАЦИЯ PDF ФАЙЛА
        # ========================================================================
        # Открываем входной PDF файл в бинарном режиме для чтения
        # with statement гарантирует закрытие файла после использования
        with input_path.open("rb") as inf:
            # Проверка размера файла
            # Перемещаемся в конец файла для определения размера
            inf.seek(0, 2)  # 2 = SEEK_END (конец файла)
            file_size = inf.tell()  # Получаем текущую позицию (размер файла)
            
            # PDF файл должен быть минимум 100 байт
            # Меньший размер указывает на поврежденный или некорректный файл
            if file_size < 100:
                sys.stderr.write(f"Входной PDF слишком мал ({file_size} байт)\n")
                return 93
            
            # Проверка маркера %%EOF
            # PDF файлы должны заканчиваться маркером %%EOF
            # Проверяем последние 1024 байта файла (или весь файл, если он меньше)
            check_size = min(1024, file_size)
            
            # Перемещаемся к началу проверяемой области
            # max(0, file_size - check_size) гарантирует неотрицательную позицию
            inf.seek(max(0, file_size - check_size), 0)  # 0 = SEEK_SET (начало)
            
            # Читаем проверяемую область файла
            tail_data = inf.read(check_size)
            
            # Проверяем наличие маркера %%EOF в конце файла
            # b"%%EOF" - байтовая строка с маркером
            if b"%%EOF" not in tail_data:
                sys.stderr.write("Входной PDF не содержит маркер %%EOF\n")
                return 94
            
            # Сбрасываем позицию в начало файла для дальнейшей обработки
            inf.seek(0, 0)  # 0 = SEEK_SET (начало файла)
            
            # ========================================================================
            # ДЕЙСТВИЕ 7.2: ОПРЕДЕЛЕНИЕ КОЛИЧЕСТВА СТРАНИЦ
            # ========================================================================
            # Получаем количество страниц перед созданием writer
            # Необходимо для видимых подписей (нужно знать, на какой странице размещать)
            
            # PdfFileReader - класс для чтения PDF файла
            # Позволяет извлекать информацию о документе (количество страниц, метаданные и т.д.)
            from pyhanko.pdf_utils.reader import PdfFileReader
            
            # Создаем reader для чтения информации о PDF
            reader_temp = PdfFileReader(inf)
            
            # Получаем количество страниц - пробуем несколько методов
            try:
                # Метод 1: использование свойства pages
                # reader_temp.pages - список страниц документа
                num_pages = len(reader_temp.pages)
                
            except (AttributeError, TypeError):
                # Если метод 1 не сработал, пробуем метод 2
                try:
                    # Метод 2: доступ через корневую структуру документа
                    # reader_temp.root - корневой объект PDF документа
                    # ['/Pages'] - объект страниц
                    # ['/Count'] - количество страниц
                    num_pages = reader_temp.root['/Pages']['/Count']
                    
                except (AttributeError, KeyError, TypeError):
                    # Если оба метода не сработали, используем значение по умолчанию
                    # Предполагаем, что документ состоит из одной страницы
                    num_pages = 1
            
            # Снова сбрасываем позицию в начало для создания writer
            inf.seek(0, 0)  # 0 = SEEK_SET (начало файла)
            
            # ========================================================================
            # ДЕЙСТВИЕ 7.3: СОЗДАНИЕ WRITER ДЛЯ ИНКРЕМЕНТАЛЬНОЙ ЗАПИСИ
            # ========================================================================
            # IncrementalPdfFileWriter создает writer для добавления подписи к PDF
            # без перезаписи всего файла. Это сохраняет оригинальное содержимое
            # и позволяет добавлять подпись как инкрементальное обновление
            writer = IncrementalPdfFileWriter(inf)

            # ========================================================================
            # ДЕЙСТВИЕ 7.3.1: УСТАНОВКА PDF МЕТАДАННЫХ (Author, Creator)
            # ========================================================================
            # Устанавливаем Author в метаданных PDF документа = "3FA-Signer"
            # Это будет видно в свойствах документа PDF (File -> Properties)
            try:
                from pyhanko.pdf_utils import generic
                # Получаем или создаём словарь Info
                info_dict = writer.trailer.get('/Info')
                if info_dict is None:
                    info_dict = generic.DictionaryObject()
                    writer.trailer['/Info'] = writer.add_object(info_dict).reference
                else:
                    info_dict = info_dict.get_object()
                
                # Устанавливаем Author = "3FA-Signer"
                info_dict[generic.NameObject('/Author')] = generic.TextStringObject('3FA-Signer')
                # Устанавливаем Creator = "3FA Application"
                info_dict[generic.NameObject('/Creator')] = generic.TextStringObject('3FA Application')
                # Устанавливаем Producer
                info_dict[generic.NameObject('/Producer')] = generic.TextStringObject('3FA Digital Signature System')
                
                sys.stderr.write("PDF метаданные установлены: Author=3FA-Signer, Creator=3FA Application\n")
            except Exception as e:
                sys.stderr.write(f"Предупреждение: Не удалось установить PDF метаданные: {e}\n")

            # ========================================================================
            # ДЕЙСТВИЕ 7.4: ЗАГРУЗКА ПОДПИСАНТА С ЦЕПОЧКОЙ СЕРТИФИКАТОВ
            # ========================================================================
            # Загружаем подписанта (signer) с сертификатом и ключом
            # Если указан root-cert, загружаем с цепочкой сертификатов для встраивания в PDF
            
            signer = None  # Инициализируем переменную для подписанта
            
            # Проверяем, указан ли корневой сертификат
            if root_cert_path and root_cert_path.exists():
                try:
                    # Загружаем подписанта с цепочкой сертификатов, включая root CA
                    # Это позволяет встроить полную цепочку сертификатов в PDF
                    # для проверки подписи без необходимости загружать промежуточные CA
                    signer = signers.SimpleSigner.load(
                        str(key_path),                        # Путь к приватному ключу
                        str(cert_path),                       # Путь к сертификату подписанта
                        ca_chain_files=[str(root_cert_path)]  # Список файлов цепочки CA (root CA)
                    )
                    sys.stderr.write(f"Подписант загружен с цепочкой корневого CA: {root_cert_path}\n")
                    
                except Exception as e:
                    # Если загрузка с цепочкой не удалась, выводим предупреждение
                    sys.stderr.write(f"Предупреждение: Не удалось загрузить с цепочкой сертификатов: {e}\n")
                    # Откатываемся к простой загрузке без цепочки
                    signer = signers.SimpleSigner.load(str(key_path), str(cert_path))
            else:
                # Если root-cert не указан, загружаем подписанта без цепочки
                signer = signers.SimpleSigner.load(str(key_path), str(cert_path))
            
            # Проверяем успешность загрузки подписанта
            if signer is None:
                sys.stderr.write("Не удалось загрузить ключ подписи/сертификат.\n")
                return 91

            # ========================================================================
            # ДЕЙСТВИЕ 7.5: ИЗВЛЕЧЕНИЕ МЕТАДАННЫХ ИЗ СЕРТИФИКАТА
            # ========================================================================
            # Извлекаем информацию из сертификата для отображения в метаданных подписи
            # Инициализируем переменные значениями по умолчанию
            signer_name = "3FA-Signer"                    # Имя подписанта
            cert_fingerprint = ""                     # Отпечаток сертификата (SHA-256)
            cert_serial = ""                          # Серийный номер сертификата
            issuer_name = "3FA Certificate Authority" # Имя центра сертификации (по умолчанию)
            cert_not_before = ""                      # Дата начала действия сертификата
            cert_not_after = ""                       # Дата окончания действия сертификата
            cert = None                               # Объект сертификата
            
            try:
                # Импортируем необходимые модули для работы с сертификатами
                from cryptography import x509  # Модуль для работы с X.509 сертификатами
                import hashlib                 # Модуль для вычисления хешей (SHA-256)
                
                # Открываем файл сертификата в бинарном режиме
                with cert_path.open("rb") as cf:
                    # Читаем данные сертификата
                    cert_data = cf.read()
                    
                    # Загружаем сертификат из PEM формата
                    # x509.load_pem_x509_certificate() парсит PEM строку и создает объект сертификата
                    cert = x509.load_pem_x509_certificate(cert_data)
                    
                    # Извлечение Common Name (CN) из subject
                    # subject - субъект сертификата (владелец сертификата)
                    subject = cert.subject
                    
                    # Получаем атрибуты с OID COMMON_NAME из subject
                    # x509.NameOID.COMMON_NAME - идентификатор атрибута Common Name
                    cn_attrs = subject.get_attributes_for_oid(x509.NameOID.COMMON_NAME)
                    
                    # Если CN найден, используем его как имя подписанта
                    if cn_attrs:
                        signer_name = cn_attrs[0].value
                    
                    # Вычисление отпечатка сертификата (SHA-256)
                    # cert.public_bytes() преобразует сертификат в DER формат (байты)
                    # serialization.Encoding.DER - формат кодирования (DER - бинарный формат)
                    cert_der = cert.public_bytes(serialization.Encoding.DER)
                    
                    # Вычисляем SHA-256 хеш от DER представления сертификата
                    # hashlib.sha256() создает объект хеша SHA-256
                    # .hexdigest() возвращает хеш в виде шестнадцатеричной строки
                    # [:32] берем первые 32 символа (16 байт = 32 hex символа)
                    # .upper() преобразуем в верхний регистр
                    fingerprint = hashlib.sha256(cert_der).hexdigest()[:32].upper()
                    
                    # Форматируем отпечаток для читаемости: разбиваем на группы по 4 символа
                    # ' '.join() объединяет группы пробелами
                    # range(0, 32, 4) создает индексы: 0, 4, 8, 12, 16, 20, 24, 28
                    # fingerprint[i:i+4] извлекает группу из 4 символов
                    cert_fingerprint = ' '.join(fingerprint[i:i+4] for i in range(0, 32, 4))
                    
                    # Извлечение серийного номера сертификата
                    # cert.serial_number - серийный номер сертификата (целое число)
                    serial_num = cert.serial_number
                    
                    # Форматируем серийный номер в hex с ведущими нулями
                    # f"{serial_num:08X}" - форматирует число в 8-значное hex представление
                    # 08X означает: 8 символов, с ведущими нулями, в верхнем регистре
                    # Например: 5 -> "00000005", 255 -> "000000FF"
                    cert_serial = f"{serial_num:08X}"
                    
                    # Извлечение имени центра сертификации (issuer)
                    # issuer - издатель сертификата (центр сертификации, который выпустил сертификат)
                    issuer = cert.issuer
                    
                    # Получаем CN из issuer
                    issuer_cn_attrs = issuer.get_attributes_for_oid(x509.NameOID.COMMON_NAME)
                    
                    # Если CN найден, используем его как имя центра сертификации
                    if issuer_cn_attrs:
                        issuer_name = issuer_cn_attrs[0].value
                    
                    # Извлечение дат действия сертификата
                    # Проверяем наличие UTC версий для избежания предупреждений об устаревших методах
                    # not_valid_before_utc - дата начала действия (UTC)
                    # not_valid_after_utc - дата окончания действия (UTC)
                    # Если UTC версии недоступны, используем обычные версии
                    not_before = cert.not_valid_before_utc if hasattr(cert, 'not_valid_before_utc') else cert.not_valid_before
                    not_after = cert.not_valid_after_utc if hasattr(cert, 'not_valid_after_utc') else cert.not_valid_after
                    
                    # Форматируем даты в строку формата "YYYY-MM-DD"
                    # strftime() форматирует datetime объект в строку
                    cert_not_before = not_before.strftime("%Y-%m-%d")
                    cert_not_after = not_after.strftime("%Y-%m-%d")
                    
            except Exception as e:
                # Если чтение сертификата не удалось, используем значения по умолчанию
                # Выводим предупреждение, но продолжаем работу
                sys.stderr.write(f"Предупреждение: не удалось прочитать детали сертификата: {e}\n")
            
            # ========================================================================
            # ДЕЙСТВИЕ 7.6: ФОРМИРОВАНИЕ РУСИФИЦИРОВАННЫХ МЕТАДАННЫХ
            # ========================================================================
            # Создаем русифицированные метаданные подписи
            # Если аргументы не указаны, используем значения по умолчанию
            reason_ru = args.reason if args.reason else "Подписание документа"
            location_ru = args.location if args.location else "3FA Приложение"
            
            # ========================================================================
            # ДЕЙСТВИЕ 7.7: СОЗДАНИЕ ЧИТАЕМОГО ИМЕНИ ПОЛЯ ПОДПИСИ
            # ========================================================================
            # Создаем читаемое имя поля подписи с информацией о сертификате
            readable_name = signer_name  # Начинаем с имени подписанта
            
            # Если отпечаток доступен, добавляем информацию о сертификате
            if cert_fingerprint:
                # Форматируем имя с информацией о сертификате
                readable_name = f"{signer_name}"
                
                # Добавляем серийный номер, если доступен
                if cert_serial:
                    readable_name += f"\nСерия: {cert_serial}"
                
                # Добавляем усеченный отпечаток для отображения
                # [:20] берем первые 20 символов отпечатка для компактности
                readable_name += f"\nОтпечаток: {cert_fingerprint[:20]}..."
                
                # Выводим информацию о сертификате в stderr для отладки
                sys.stderr.write(f"\n=== Данные ЭЦП извлечены ===\n")
                sys.stderr.write(f"Подписант: {signer_name}\n")
                sys.stderr.write(f"Серийный номер: {cert_serial}\n")
                sys.stderr.write(f"Отпечаток (SHA-256): {cert_fingerprint}\n")
                sys.stderr.write(f"Центр сертификации: {issuer_name}\n")
                sys.stderr.write(f"Действителен: {cert_not_before} - {cert_not_after}\n")
            
            # ========================================================================
            # ДЕЙСТВИЕ 7.8: ФОРМИРОВАНИЕ ПОЛЯ REASON С ДЕТАЛЯМИ
            # ========================================================================
            # Поле reason (причина подписания) включает отпечаток и серийный номер
            reason_with_details = reason_ru  # Начинаем с базовой причины
            
            # Если отпечаток доступен, добавляем детали сертификата
            if cert_fingerprint:
                reason_with_details = f"{reason_ru}"
                
                # Добавляем серийный номер сертификата
                if cert_serial:
                    reason_with_details += f" | Серия сертификата: {cert_serial}"
                
                # Добавляем полный отпечаток SHA-256
                reason_with_details += f" | Отпечаток SHA-256: {cert_fingerprint}"
            
            # ========================================================================
            # ДЕЙСТВИЕ 7.9: ФОРМИРОВАНИЕ ПОЛЯ LOCATION С ДЕТАЛЯМИ
            # ========================================================================
            # Поле location (место подписания) включает имя CA и даты действия
            location_with_details = location_ru  # Начинаем с базового местоположения
            
            # Если имя центра сертификации доступно, добавляем детали
            if issuer_name:
                location_with_details = f"{location_ru}"
                
                # Добавляем даты действия сертификата
                if cert_not_before and cert_not_after:
                    location_with_details += f" | Действителен: {cert_not_before} - {cert_not_after}"
                
                # Добавляем имя центра сертификации
                location_with_details += f" | CA: {issuer_name}"
            
            # ========================================================================
            # ДЕЙСТВИЕ 7.10: ФОРМИРОВАНИЕ ПОЛЯ CONTACT_INFO
            # ========================================================================
            # Поле contact_info содержит полные данные сертификата для проверки
            # Это поле будет видно в свойствах/деталях подписи в PDF читалках
            contact_info = None  # Инициализируем как None
            
            # Если отпечаток доступен, создаем детальную информацию
            if cert_fingerprint:
                # Форматируем contact_info со всеми криптографическими данными
                contact_info = "=== ДАННЫЕ ЭЦП ===\n"
                contact_info += f"Отпечаток сертификата (SHA-256):\n{cert_fingerprint}\n"
                
                # Добавляем серийный номер, если доступен
                if cert_serial:
                    contact_info += f"\nСерийный номер сертификата: {cert_serial}\n"
                
                # Добавляем срок действия сертификата
                if cert_not_before and cert_not_after:
                    contact_info += f"Срок действия: {cert_not_before} - {cert_not_after}\n"
                
                # Добавляем имя центра сертификации
                if issuer_name:
                    contact_info += f"Центр сертификации: {issuer_name}\n"
                
                contact_info += "=== КОНЕЦ ДАННЫХ ЭЦП ==="
            
            # ========================================================================
            # ДЕЙСТВИЕ 7.11: НАСТРОЙКА DSS ДЛЯ ВСТРАИВАНИЯ КОРНЕВОГО CA
            # ========================================================================
            # Настраиваем DSS (Document Security Store) для встраивания корневого CA сертификата
            # DSS позволяет встроить цепочку сертификатов в PDF для проверки подписи
            dss_settings = None  # Инициализируем как None
            
            # Если корневой сертификат указан и существует, настраиваем DSS
            if root_cert_path and root_cert_path.exists():
                try:
                    # DSSContentSettings - класс для настройки DSS в PDF
                    from pyhanko.sign.signers.pdf_signer import DSSContentSettings
                    
                    # Создаем настройки DSS для встраивания корневого сертификата
                    dss_settings = DSSContentSettings(
                        include_vri=True,        # Включать VRI (Validation-Related Information)
                        skip_if_unneeded=False,  # Всегда включать DSS (не пропускать)
                    )
                    
                    sys.stderr.write(f"Корневой CA сертификат будет встроен в PDF DSS: {root_cert_path}\n")
                    
                except Exception as e:
                    # Если настройка DSS не удалась, выводим предупреждение
                    sys.stderr.write(f"Предупреждение: Не удалось настроить параметры DSS: {e}\n")

            # ========================================================================
            # ДЕЙСТВИЕ 7.12: СОЗДАНИЕ МЕТАДАННЫХ ПОДПИСИ
            # ========================================================================
            # PdfSignatureMetadata - класс для метаданных подписи PDF
            # Содержит всю информацию, которая будет отображаться в свойствах подписи
            metadata = PdfSignatureMetadata(
                field_name=args.field,                    # Имя поля подписи
                reason=reason_with_details or None,       # Причина подписания (с деталями сертификата)
                location=location_with_details or None,   # Место подписания (с деталями CA)
                name=signer_name,                         # Имя подписанта
                contact_info=contact_info,                # Контактная информация (полные данные ЭЦП)
                dss_settings=dss_settings,                # Настройки DSS для встраивания корневого CA
            )

            # ========================================================================
            # ДЕЙСТВИЕ 7.13: СОЗДАНИЕ СПЕЦИФИКАЦИИ ПОЛЯ ПОДПИСИ
            # ========================================================================
            # Настраиваем спецификацию поля подписи (видимое или невидимое)
            if args.visible:
                # ========================================================================
                # ВИДИМАЯ ПОДПИСЬ
                # ========================================================================
                # Вычисляем позицию для подписи внизу последней страницы
                # Координаты PDF: (0,0) - левый нижний угол
                # Для A4: ширина=595, высота=842 точек (72 точки на дюйм)
                # Размещаем в левом нижнем углу, чтобы не перекрывать текст
                # По умолчанию y=50 размещает подпись близко к низу (50 точек от низа)
                
                # Определяем последнюю страницу (индекс начинается с 0)
                last_page = max(0, num_pages - 1)
                
                # Позиционируем подпись внизу: Y координата от низа страницы
                # Используем args.y как расстояние от низа, обеспечиваем минимальный отступ
                # Это предотвращает перекрытие подписью текстового содержимого
                signature_y = max(50.0, args.y)  # Минимум 50 точек от низа
                
                # Создаем видимую подпись с координатами рамки на последней странице
                # Формат рамки: (x1, y1, x2, y2), где (x1, y1) - левый нижний угол
                box = (args.x, signature_y, args.x + args.width, signature_y + args.height)
                
                # SigFieldSpec - спецификация поля подписи
                field_spec = fields.SigFieldSpec(
                    sig_field_name=args.field,           # Имя поля подписи
                    on_page=last_page,                   # Номер страницы (индекс с 0)
                    box=box,                             # Координаты рамки подписи
                    readable_field_name=readable_name,   # Читаемое имя (отображается в метке поля)
                    visible_sig_settings=fields.VisibleSigSettings(
                        rotate_with_page=True,           # Поворачивать подпись вместе со страницей
                        scale_with_page_zoom=True,       # Масштабировать подпись при зуме страницы
                        print_signature=True             # Печатать подпись при печати документа
                    )
                )
                
                # Выводим информацию о страницах для отладки
                sys.stderr.write(f"PDF содержит {num_pages} страниц(ы), подпись размещается на странице {last_page + 1}\n")
                sys.stderr.write(f"Рамка подписи: x={args.x}, y={signature_y}, ширина={args.width}, высота={args.height}\n")
            else:
                # ========================================================================
                # НЕВИДИМАЯ ПОДПИСЬ (ПО УМОЛЧАНИЮ)
                # ========================================================================
                # Создаем спецификацию для невидимой подписи
                # Невидимая подпись не отображается на странице, но присутствует в документе
                field_spec = fields.SigFieldSpec(sig_field_name=args.field)

            # ========================================================================
            # ДЕЙСТВИЕ 7.14: ПОДПИСАНИЕ PDF С ВРЕМЕННОЙ МЕТКОЙ ИЛИ БЕЗ
            # ========================================================================
            # Подписываем PDF синхронно или асинхронно (в зависимости от наличия TSA URL)
            if args.tsa_url and aiohttp_available and asyncio_available:
                # ========================================================================
                # АСИНХРОННОЕ ПОДПИСАНИЕ С ВРЕМЕННОЙ МЕТКОЙ
                # ========================================================================
                # Используем асинхронное подписание с временной меткой от TSA сервера
                try:
                    # AIOHttpTimeStamper - класс для получения временных меток через HTTP
                    from pyhanko.sign.timestamps.aiohttp_client import AIOHttpTimeStamper
                    
                    # Асинхронная функция для подписания с временной меткой
                    async def sign_with_timestamp():
                        # Создаем HTTP сессию для запросов к TSA серверу
                        async with aiohttp.ClientSession() as session:
                            # Создаем timestamper для получения временных меток
                            timestamper = AIOHttpTimeStamper(
                                args.tsa_url,    # URL TSA сервера (RFC 3161)
                                session=session  # HTTP сессия для запросов
                            )
                            
                            # Открываем выходной файл для записи подписанного PDF
                            with output_path.open("wb") as outf:
                                # Асинхронно подписываем PDF с временной меткой
                                await signers.async_sign_pdf(
                                    writer,                      # Writer для инкрементальной записи
                                    signature_meta=metadata,     # Метаданные подписи
                                    signer=signer,               # Подписант (сертификат + ключ)
                                    timestamper=timestamper,     # Timestamper для временной метки
                                    new_field_spec=field_spec,   # Спецификация поля подписи
                                    existing_fields_only=False,  # Создавать новое поле (не использовать существующее)
                                    in_place=False,              # Не модифицировать исходный файл
                                    output=outf,                 # Выходной файл для записи
                                )
                    
                    sys.stderr.write(f"Подписание PDF с временной меткой от TSA: {args.tsa_url}\n")
                    
                    # Если указан корневой сертификат, выводим информацию
                    if root_cert_path and root_cert_path.exists():
                        sys.stderr.write(f"PDF будет подписан с встраиванием сертификата и временной меткой\n")
                    
                    # Запускаем асинхронную функцию подписания
                    # asyncio.run() создает event loop и выполняет асинхронную функцию
                    asyncio.run(sign_with_timestamp())
                    
                    sys.stderr.write("PDF успешно подписан с временной меткой\n")
                    
                except Exception as e:
                    # Если подписание с временной меткой не удалось, выводим ошибку
                    sys.stderr.write(f"Не удалось подписать с временной меткой: {e}\n")
                    # Откатываемся к подписанию без временной метки
                    sys.stderr.write("Переход к подписанию без временной метки\n")
                    
                    # Открываем выходной файл для записи
                    with output_path.open("wb") as outf:
                        # Синхронно подписываем PDF без временной метки
                        signers.sign_pdf(
                            writer,                      # Writer для инкрементальной записи
                            signature_meta=metadata,     # Метаданные подписи
                            signer=signer,               # Подписант (сертификат + ключ)
                            new_field_spec=field_spec,   # Спецификация поля подписи
                            existing_fields_only=False,  # Создавать новое поле
                            in_place=False,              # Не модифицировать исходный файл
                            output=outf,                 # Выходной файл для записи
                        )
            else:
                # ========================================================================
                # СИНХРОННОЕ ПОДПИСАНИЕ БЕЗ ВРЕМЕННОЙ МЕТКИ
                # ========================================================================
                # Используем синхронное подписание без временной метки
                # Встраивание сертификата все еще работает через metadata и signer
                if root_cert_path and root_cert_path.exists():
                    sys.stderr.write("PDF будет подписан с встраиванием сертификата (без временной метки)\n")
                
                # Открываем выходной файл для записи
                with output_path.open("wb") as outf:
                    # Синхронно подписываем PDF
                    signers.sign_pdf(
                        writer,                      # Writer для инкрементальной записи
                        signature_meta=metadata,     # Метаданные подписи
                        signer=signer,               # Подписант (сертификат + ключ)
                        new_field_spec=field_spec,   # Спецификация поля подписи
                        existing_fields_only=False,  # Создавать новое поле
                        in_place=False,              # Не модифицировать исходный файл
                        output=outf,                 # Выходной файл для записи
                    )
                    
    except Exception as exc:
        # ========================================================================
        # ОБРАБОТКА ОШИБОК ПОДПИСАНИЯ
        # ========================================================================
        # Перехватываем все исключения при подписании PDF
        sys.stderr.write(f"Ошибка подписания pyhanko: {exc}\n")
        
        # Импортируем traceback для вывода полного стека вызовов
        import traceback
        traceback.print_exc()
        
        return 92

    # Возвращаем код успешного выполнения
    return 0


