// ============================================================================
// ДЕСТРУКТОР ~CertificateWorker
// ============================================================================
// Останавливает рабочий поток и освобождает ресурсы.
// Автоматически вызывается при удалении объекта.
//
// АЛГОРИТМ:
// 1. Отправка сигнала остановки потока (stopWorker)
// 2. Ожидание завершения потока с таймаутом (5 секунд)
// 3. Принудительное завершение потока, если он не завершился вовремя
// ============================================================================
CertificateWorker::~CertificateWorker()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ОТПРАВКА СИГНАЛА ОСТАНОВКИ
    // ========================================================================
    // Отправляем сигнал остановки рабочему потоку
    // Устанавливает флаг m_shouldStop = true и пробуждает поток для завершения
    // Это позволяет потоку корректно завершить текущую задачу и выйти из цикла
    stopWorker();
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ОЖИДАНИЕ ЗАВЕРШЕНИЯ ПОТОКА
    // ========================================================================
    // Ждем завершения потока с таймаутом (5 секунд)
    // Проверяем, запущен ли поток еще (может быть уже остановлен)
    if (isRunning()) 
    {
        // Ждем до 5 секунд для корректного завершения потока
        // wait() возвращает true, если поток завершился, false - если истек таймаут
        if (!wait(5000)) 
        {
            // Поток не завершился в течение 5 секунд - это критическая ситуация
            // Возможно, поток завис или выполняет длительную операцию
            qWarning() << "CertificateWorker: Поток не завершился в течение 5 секунд, принудительное завершение";
            
            // Принудительно завершаем поток (вызывает terminate())
            // Это небезопасная операция, но необходима для предотвращения зависания приложения
            terminate();
            
            // Ждем еще секунду для завершения после принудительной остановки
            wait(1000);
        }
    }
    
    // Деструктор успешно завершен - все ресурсы освобождены
    qDebug() << "CertificateWorker: Деструктор завершен";
}


// ============================================================================
// МЕТОД startWorker - ЗАПУСК РАБОЧЕГО ПОТОКА
// ============================================================================
// Запускает рабочий поток для обработки задач с сертификатами.
// Начинает периодическое сканирование сертификатов и обработку очереди задач.
//
// АЛГОРИТМ:
// 1. Проверка, не запущен ли поток уже
// 2. Установка флагов состояния
// 3. Запуск потока через QThread::start()
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет
// ============================================================================
void CertificateWorker::startWorker()
{
    // Проверяем, не запущен ли поток уже
    if (m_running) 
    {
        // Поток уже запущен - выходим
        return;
    }
    
    // Устанавливаем флаги состояния и запускаем поток
    m_running = true;
    m_shouldStop = false;
    start(); // Запускаем поток (вызывает run() в отдельном потоке)
    qDebug() << "CertificateWorker: Воркер запущен";
}


// ============================================================================
// МЕТОД stopWorker - ОСТАНОВКА РАБОЧЕГО ПОТОКА
// ============================================================================
// Останавливает рабочий поток. Дожидается завершения текущей задачи
// и корректно завершает работу потока.
//
// АЛГОРИТМ:
// 1. Проверка состояния потока
// 2. Установка флага остановки
// 3. Пробуждение потока для завершения
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет
// ============================================================================
void CertificateWorker::stopWorker()
{
    // Проверяем, запущен ли поток и не запрошена ли уже остановка
    if (!m_running || m_shouldStop) 
    {
        return;
    }
    
    qDebug() << "CertificateWorker: Остановка воркера...";
    
    // Устанавливаем флаг остановки
    m_shouldStop = true;
    
    // ========================================================================
    // ПРОБУЖДЕНИЕ ПОТОКА ДЛЯ ЗАВЕРШЕНИЯ
    // ========================================================================
    // Пробуждаем поток для завершения (если он ждет в m_queueCondition)
    {
        QMutexLocker locker(&m_queueMutex);
        m_queueCondition.wakeAll(); // Пробуждаем все ожидающие потоки
    }
    
    qDebug() << "CertificateWorker: Сигнал остановки отправлен";
}


// ============================================================================
// МЕТОД isRunning - ПРОВЕРКА СОСТОЯНИЯ ПОТОКА
// ============================================================================
// Проверяет, запущен ли рабочий поток в данный момент.
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - поток запущен и работает
//   false - поток остановлен или запрошена остановка
// ============================================================================
bool CertificateWorker::isRunning() const
{
    // Поток считается запущенным, если m_running = true и не запрошена остановка
    return m_running && !m_shouldStop;
}


// ============================================================================
// МЕТОД addTask - ДОБАВЛЕНИЕ ЗАДАЧИ В ОЧЕРЕДЬ
// ============================================================================
// Добавляет задачу в очередь для асинхронной обработки.
// Задача будет обработана в рабочем потоке в порядке добавления (FIFO).
//
// АЛГОРИТМ:
// 1. Блокировка мьютекса очереди для потокобезопасности
// 2. Проверка, нет ли уже такой задачи в очереди
// 3. Проверка истории задач (не выполнена ли уже)
// 4. Добавление задачи в очередь
// 5. Пробуждение рабочего потока
// 6. Отправка сигнала taskAdded
//
// ПАРАМЕТРЫ:
//   task - задача для выполнения (CertificateTask)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет
//
// ПРИМЕЧАНИЕ:
//   Метод потокобезопасен - можно вызывать из любого потока
//   Для задач типа Issue проверка дубликатов идет по CN (serial всегда 0)
//   Для задач типа Renew и Revoke проверка дубликатов идет по serial
// ============================================================================
void CertificateWorker::addTask(const CertificateTask &task)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: БЛОКИРОВКА МЬЮТЕКСА ОЧЕРЕДИ
    // ========================================================================
    // Блокируем мьютекс для безопасного доступа к очереди задач
    // QMutexLocker автоматически разблокирует мьютекс при выходе из области видимости
    // Это гарантирует потокобезопасность при добавлении задачи из любого потока
    QMutexLocker locker(&m_queueMutex);
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПРОВЕРКА ДУБЛИКАТОВ В ОЧЕРЕДИ
    // ========================================================================
    // Проверяем, нет ли уже такой задачи в очереди
    // Это предотвращает добавление одинаковых задач и дублирование работы
    // 
    // ВАЖНО: Для разных типов задач используются разные критерии сравнения:
    // - Issue: сравниваем по CN (Common Name), так как serial всегда 0 для новых сертификатов
    // - Renew/Revoke: сравниваем по serial, так как это уникальный идентификатор существующего сертификата
    bool alreadyExists = false;
    
    // Перебираем все задачи в очереди для поиска дубликатов
    for (const auto &existingTask : m_taskQueue) 
    {
        // Сравниваем только задачи одного типа (Issue с Issue, Renew с Renew и т.д.)
        if (existingTask.type == task.type) 
        {
            // Если тип задачи Issue, то сравниваем по cn
            if (task.type == CertificateTaskType::Issue) 
            {
                // ========================================================================
                // СРАВНЕНИЕ ДЛЯ ЗАДАЧ ТИПА ISSUE
                // ========================================================================
                // Для Issue сравниваем по cn (serial всегда 0 для новых сертификатов)
                // CN (Common Name) - это уникальный идентификатор для нового сертификата
                // Например, нельзя выпустить два сертификата для одного и того же CN одновременно
                if (existingTask.cn == task.cn && !task.cn.isEmpty()) 
                {
                    // Устанавливаем флаг уже существующей задачи
                    alreadyExists = true;
                    // Прерываем цикл поиска дубликатов
                    break; // Найден дубликат, прекращаем поиск
                }
            } 
            // Если тип задачи не Issue, то сравниваем по serial
            else 
            {
                // ========================================================================
                // СРАВНЕНИЕ ДЛЯ ЗАДАЧ ТИПА RENEW И REVOKE
                // ========================================================================
                // Для Renew и Revoke сравниваем по serial
                // Serial - это уникальный серийный номер существующего сертификата
                // Например, нельзя обновить или отозвать один и тот же сертификат дважды одновременно
                if (existingTask.serial == task.serial) 
                {
                    // Устанавливаем флаг уже существующей задачи
                    alreadyExists = true;
                    // Прерываем цикл поиска дубликатов
                    break; // Найден дубликат, прекращаем поиск
                }
            }
        }
    }
    
    // Если дубликат найден, выходим из метода без добавления задачи
    if (alreadyExists) 
    {
        qDebug() << "CertificateWorker: Задача уже существует в очереди. Тип:" << static_cast<int>(task.type) 
                 << "Serial:" << task.serial << "CN:" << task.cn;
        return;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПРОВЕРКА ИСТОРИИ ЗАДАЧ
    // ========================================================================
    // Проверяем, не была ли задача уже выполнена ранее
    // Это предотвращает повторное выполнение уже завершенных задач
    // Например, если сертификат уже был выпущен для CN, не нужно выпускать его снова
    {
        // Блокируем мьютекс истории для безопасного доступа к списку выполненных задач
        QMutexLocker historyLocker(&m_historyMutex);
        
        // Перебираем все выполненные задачи для поиска дубликатов
        for (const auto &completedTask : m_completedTasks) 
        {
            // Проверяем только задачи того же типа со статусом Completed
            // Не проверяем Failed задачи, так как их можно повторить
            if (completedTask.type == task.type && completedTask.status == TaskStatus::Completed) 
            {
                // Если тип задачи Issue, то сравниваем по cn
                if (task.type == CertificateTaskType::Issue) 
                {
                    // ========================================================================
                    // ПРОВЕРКА ДЛЯ ЗАДАЧ ТИПА ISSUE
                    // ========================================================================
                    // Для Issue сравниваем по cn
                    // Если сертификат для этого CN уже был успешно выпущен, не добавляем задачу
                    if (completedTask.cn == task.cn && !task.cn.isEmpty()) 
                    {
                        qDebug() << "CertificateWorker: Задача уже выполнена ранее. Тип:" << static_cast<int>(task.type) 
                                 << "Serial:" << task.serial << "CN:" << task.cn;
                        return; // Задача уже выполнена, выходим без добавления
                    }
                } 

                else 
                {
                    // ========================================================================
                    // ПРОВЕРКА ДЛЯ ЗАДАЧ ТИПА RENEW И REVOKE
                    // ========================================================================
                    // Для Renew и Revoke сравниваем по serial
                    // Если операция для этого сертификата уже была успешно выполнена, не добавляем задачу
                    if (completedTask.serial == task.serial) 
                    {
                        qDebug() << "CertificateWorker: Задача уже выполнена ранее. Тип:" << static_cast<int>(task.type) 
                                 << "Serial:" << task.serial;
                        return; // Задача уже выполнена, выходим без добавления
                    }
                }
            }
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ДОБАВЛЕНИЕ ЗАДАЧИ В ОЧЕРЕДЬ
    // ========================================================================
    // Добавляем задачу в очередь (FIFO - First In, First Out)
    // Задачи будут обрабатываться в порядке добавления
    // Мьютекс m_queueMutex все еще заблокирован (locker активен)
    m_taskQueue.enqueue(task);
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ПРОБУЖДЕНИЕ РАБОЧЕГО ПОТОКА
    // ========================================================================
    // Пробуждаем поток для обработки задачи (если он ждет в m_queueCondition)
    // wakeAll() пробуждает все ожидающие потоки (в данном случае один рабочий поток)
    // Это необходимо, так как поток может быть в состоянии ожидания между сканированиями
    // После пробуждения поток проверит очередь и начнет обработку новой задачи
    m_queueCondition.wakeAll();
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ОТПРАВКА СИГНАЛА
    // ========================================================================
    // Отправляем сигнал о добавлении задачи
    // Сигнал taskAdded() может быть подключен к слотам в других частях приложения
    // для отслеживания добавления новых задач (например, для обновления UI)
    emit taskAdded(task);
    
    // Выводим отладочное сообщение о добавлении задачи
    qDebug() << "CertificateWorker: Задача добавлена в очередь. Тип:" << static_cast<int>(task.type) 
             << "Serial:" << task.serial << "CN:" << task.cn;
}


