// ============================================================================
// МЕТОД getPendingTasks - ПОЛУЧЕНИЕ СПИСКА ОЖИДАЮЩИХ ЗАДАЧ
// ============================================================================
// Возвращает список всех задач, ожидающих выполнения.
// Используется для отображения текущей очереди задач.
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   QList<CertificateTask> - список ожидающих задач
//
// ПРИМЕЧАНИЕ:
//   Метод потокобезопасен - использует мьютекс для доступа к очереди
//   Возвращается копия списка для безопасности (изменения не повлияют на оригинал)
//   Задачи возвращаются в порядке очереди (FIFO - First In, First Out)
// ============================================================================
QList<CertificateTask> CertificateWorker::getPendingTasks()
{
    // Блокируем мьютекс очереди для безопасного чтения
    // QMutexLocker автоматически разблокирует мьютекс при выходе из метода
    QMutexLocker locker(&m_queueMutex);
    
    // ========================================================================
    // СОЗДАНИЕ КОПИИ ОЧЕРЕДИ В ВИДЕ СПИСКА
    // ========================================================================
    // Создаем копию очереди в виде списка для возврата
    // QQueue не поддерживает прямой возврат, поэтому конвертируем в QList
    // Это позволяет безопасно работать с данными вне критической секции
    QList<CertificateTask> tasks;
    for (const auto &task : m_taskQueue) 
    {
        tasks.append(task);
    }
    
    // Возвращаем копию списка задач
    return tasks;
}


// ============================================================================
// МЕТОД run - ГЛАВНЫЙ ЦИКЛ РАБОЧЕГО ПОТОКА
// ============================================================================
// Главный метод рабочего потока. Выполняется в отдельном потоке после
// вызова startWorker(). Обрабатывает очередь задач и периодически
// сканирует сертификаты.
//
// АЛГОРИТМ:
// 1. Начальное сканирование сертификатов при старте
// 2. Обработка очереди задач после начального сканирования
// 3. Основной цикл:
//    a. Сканирование сертификатов в базе данных
//    b. Очистка старых отозванных сертификатов
//    c. Периодическая генерация CRL (каждые 5 сканирований)
//    d. Обработка очереди задач
//    e. Ожидание до следующего сканирования (с проверкой остановки каждые 5 сек)
// 4. Завершение работы потока
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет (выполняется до остановки потока)
//
// ПРИМЕЧАНИЕ:
//   Метод выполняется в отдельном потоке, созданном QThread
//   Все операции защищены проверками m_shouldStop для корректной остановки
// ============================================================================
void CertificateWorker::run()
{
    qDebug() << "CertificateWorker: Поток запущен";
    
    // ========================================================================
    // ДЕЙСТВИЕ 1: НАЧАЛЬНОЕ СКАНИРОВАНИЕ ПРИ СТАРТЕ
    // ========================================================================
    // Немедленное сканирование при старте для проверки наличия активных сертификатов
    // и создания задач на обновление/отзыв, если необходимо
    // Это позволяет сразу обработать критические ситуации (истекшие сертификаты)
    // без ожидания первого периодического сканирования
    if (!m_shouldStop) 
    {
        try 
        {
            qDebug() << "CertificateWorker: Начальное сканирование при старте...";
            
            // Выполняем сканирование сертификатов в базе данных
            // Метод создаст задачи на обновление/отзыв для сертификатов, требующих внимания
            scanCertificates();
            
            // Обрабатываем очередь задач сразу после начального сканирования
            // Это позволяет быстро обработать задачи, созданные при сканировании
            if (!m_shouldStop) 
            {
                processTaskQueue();
            }
        } 
        catch (...) 
        {
            // Перехватываем все исключения при начальном сканировании
            // Это предотвращает крах потока при ошибках инициализации
            qCritical() << "CertificateWorker: Ошибка при начальном сканировании";
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ОСНОВНОЙ ЦИКЛ РАБОТЫ ПОТОКА
    // ========================================================================
    // Основной цикл работы потока - выполняется до запроса остановки
    // Цикл выполняет периодические операции по управлению сертификатами
    while (!m_shouldStop) 
    {
        try 
        {
            // ========================================================================
            // ШАГ 1: СКАНИРОВАНИЕ СЕРТИФИКАТОВ
            // ========================================================================
            // Сканируем сертификаты в базе данных и создаем задачи на обновление/отзыв
            // Проверяем срок действия всех активных сертификатов
            // Создаем задачи для сертификатов, требующих обновления или отзыва
            if (!m_shouldStop) 
            {
                scanCertificates();
            }
            
            // ========================================================================
            // ШАГ 2: ОЧИСТКА СТАРЫХ ОТОЗВАННЫХ СЕРТИФИКАТОВ
            // ========================================================================
            // Удаляем старые отозванные сертификаты из базы данных
            // Это предотвращает рост размера базы данных и улучшает производительность
            // Удаляются только сертификаты, отозванные более m_deleteRevokedAfterDays дней назад
            if (!m_shouldStop) 
            {
                cleanupOldRevokedCertificates();
            }
            
            // ========================================================================
            // ШАГ 3: ПЕРИОДИЧЕСКАЯ ГЕНЕРАЦИЯ CRL
            // ========================================================================
            // Генерируем актуальный CRL периодически (каждые 5 сканирований = ~25 минут)
            // Это обеспечивает актуальность списка отозванных сертификатов
            // CRL используется для проверки статуса сертификатов при валидации
            // 
            // Используем статическую переменную для подсчета количества сканирований
            // Статическая переменная сохраняет значение между итерациями цикла
            static int scanCount = 0;
            scanCount++;
            
            // Генерируем CRL каждые 5 сканирований
            // При интервале сканирования 5 минут это означает генерацию каждые ~25 минут
            if (scanCount >= 5 && !m_shouldStop) 
            {
                generateCrl();
                scanCount = 0; // Сбрасываем счетчик после генерации
            }
            
            // ========================================================================
            // ШАГ 4: ОБРАБОТКА ОЧЕРЕДИ ЗАДАЧ
            // ========================================================================
            // Обрабатываем все задачи из очереди (выдача, обновление, отзыв)
            // Задачи обрабатываются последовательно в порядке добавления (FIFO)
            // Метод обработает все задачи в очереди до её опустошения
            if (!m_shouldStop) 
            {
                processTaskQueue();
            }
            
            // ========================================================================
            // ШАГ 5: ОЖИДАНИЕ ДО СЛЕДУЮЩЕГО СКАНИРОВАНИЯ
            // ========================================================================
            // Ждем до следующего сканирования или пробуждения для обработки задач
            // Проверяем остановку каждые 5 секунд для быстрой реакции на запрос остановки
            // Это позволяет быстро завершить поток при запросе остановки, не дожидаясь
            // полного интервала сканирования
            {
                // Блокируем мьютекс очереди для работы с условием ожидания
                QMutexLocker locker(&m_queueMutex);
                
                if (!m_shouldStop) 
                {
                    // ========================================================================
                    // РАСЧЕТ ВРЕМЕНИ ОЖИДАНИЯ
                    // ========================================================================
                    // Ждем полный интервал сканирования, но проверяем остановку каждые 5 секунд
                    // Это позволяет быстро реагировать на запрос остановки
                    // Конвертируем интервал из секунд в миллисекунды (wait() принимает миллисекунды)
                    int remainingTime = m_scanIntervalSeconds * 1000;
                    
                    // ========================================================================
                    // ЦИКЛ ОЖИДАНИЯ С ПЕРИОДИЧЕСКОЙ ПРОВЕРКОЙ
                    // ========================================================================
                    // Ожидаем частями по 5 секунд, чтобы периодически проверять флаг остановки
                    // Это обеспечивает быструю реакцию на запрос остановки (максимум 5 секунд задержки)
                    while (remainingTime > 0 && !m_shouldStop) 
                    {
                        // Определяем время ожидания: минимум из оставшегося времени и 5 секунд
                        int waitTime = qMin(remainingTime, 5000); // Проверяем каждые 5 секунд
                        
                        // ========================================================================
                        // ОЖИДАНИЕ В УСЛОВИИ ОЧЕРЕДИ
                        // ========================================================================
                        // Ожидаем в условии очереди (может быть пробужден при добавлении задачи)
                        // wait() автоматически разблокирует мьютекс и ждет, затем снова заблокирует
                        // Поток может быть пробужден:
                        // 1. По истечении времени waitTime
                        // 2. При вызове wakeAll() (например, при добавлении новой задачи)
                        // 3. При установке флага m_shouldStop = true
                        m_queueCondition.wait(&m_queueMutex, waitTime);
                        
                        // Уменьшаем оставшееся время на время ожидания
                        remainingTime -= waitTime;
                    }
                }
            }
        } 
        catch (...) 
        {
            // ========================================================================
            // ОБРАБОТКА КРИТИЧЕСКИХ ОШИБОК
            // ========================================================================
            // Перехватываем все необработанные исключения для предотвращения краха потока
            // Это критически важно, так как необработанное исключение в потоке может привести
            // к завершению всего приложения
            qCritical() << "CertificateWorker: Необработанное исключение в потоке";
            
            // Отправляем сигнал об ошибке для уведомления других частей приложения
            emit errorOccurred("Критическая ошибка в потоке воркера");
            
            // Выходим из цикла при критической ошибке
            // Это предотвращает бесконечные попытки выполнения при постоянных ошибках
            break;
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ЗАВЕРШЕНИЕ РАБОТЫ ПОТОКА
    // ========================================================================
    // При нормальном завершении не обрабатываем оставшиеся задачи
    // чтобы не задерживать закрытие приложения
    // Оставшиеся задачи будут обработаны при следующем запуске приложения
    qDebug() << "CertificateWorker: Завершение работы, оставшиеся задачи будут обработаны при следующем запуске";
    
    // Сбрасываем флаг запущенного потока
    // Это позволяет isRunning() вернуть false после завершения потока
    m_running = false;
    
    qDebug() << "CertificateWorker: Поток завершен";
}


// ============================================================================
// МЕТОД scanCertificates - СКАНИРОВАНИЕ СЕРТИФИКАТОВ В БАЗЕ ДАННЫХ
// ============================================================================
// Сканирует базу данных на наличие сертификатов, проверяет их срок действия
// и автоматически создает задачи на обновление или отзыв при необходимости.
//
// АЛГОРИТМ:
// 1. Проверка подключения к базе данных
// 2. Выбор всех активных сертификатов (status = 'valid')
// 3. Для каждого сертификата:
//    a. Отправка сигнала certificateScanned
//    b. Проверка необходимости обновления (shouldRenewCertificate)
//    c. Проверка необходимости отзыва (shouldRevokeCertificate)
//    d. Создание задач на обновление/отзыв при необходимости
// 4. Проверка CN без активных сертификатов и создание задач на выдачу
// 5. Вывод статистики сканирования
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет
// ============================================================================
void CertificateWorker::scanCertificates()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА ПОДКЛЮЧЕНИЯ К БАЗЕ ДАННЫХ
    // ========================================================================
    // Проверяем, что база данных подключена и доступна
    if (!m_database || !m_database->isConnected()) 
    {
        emit errorOccurred("База данных не подключена");
        return;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВЫБОР АКТИВНЫХ СЕРТИФИКАТОВ
    // ========================================================================
    // Выбираем все активные сертификаты из базы данных
    // Сортируем по серийному номеру для упорядоченной обработки
    QSqlQuery query = m_database->select
    (
        "SELECT serial, subject, not_before, not_after, status FROM certs WHERE status = 'valid' ORDER BY serial"
    );
    
    // Счетчики для статистики
    int scannedCount = 0;         // количество просмотренных сертификатов
    int renewTasksAdded = 0;      // количество созданных задач на обновление
    int revokeTasksAdded = 0;     // количество созданных задач на отзыв
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ОБРАБОТКА КАЖДОГО СЕРТИФИКАТА
    // ========================================================================
    // Перебираем все активные сертификаты и проверяем их срок действия
    // Перебираем все найденные активные сертификаты из базы данных
    while (query.next()) 
    {
        // ========================================================================
        // ИЗВЛЕЧЕНИЕ ДАННЫХ СЕРТИФИКАТА ИЗ РЕЗУЛЬТАТА ЗАПРОСА
        // ========================================================================
        // Получаем запись из результата SQL запроса
        QSqlRecord record = query.record();
        
        // Извлекаем серийный номер сертификата (уникальный идентификатор)
        long serial = record.value("serial").toLongLong();
        
        // Извлекаем subject (Distinguished Name) сертификата
        // Например: "/CN=example.com/O=Organization"
        QString subject = record.value("subject").toString();
        
        // Извлекаем дату истечения сертификата (timestamp в секундах с эпохи Unix)
        qint64 notAfterTimestamp = record.value("not_after").toLongLong();
        
        // Преобразуем timestamp в QDateTime для удобной работы с датой
        QDateTime notAfter = QDateTime::fromSecsSinceEpoch(notAfterTimestamp);
        
        // Извлекаем текущий статус сертификата ("valid", "revoked" и т.д.)
        QString status = record.value("status").toString();
        
        // Увеличиваем счетчик просмотренных сертификатов
        scannedCount++;
        
        // ========================================================================
        // ОТПРАВКА СИГНАЛА О НАЙДЕННОМ СЕРТИФИКАТЕ
        // ========================================================================
        // Отправляем сигнал о найденном сертификате
        // Сигнал может быть подключен к слотам для обновления UI или логирования
        emit certificateScanned(serial, subject, notAfter);
        
        // ========================================================================
        // ПРОВЕРКА СТАТУСА СЕРТИФИКАТА
        // ========================================================================
        // Пропускаем уже отозванные сертификаты
        // Отозванные сертификаты не требуют обновления или повторного отзыва
        if (status != "valid") 
        {
            continue; // Переходим к следующему сертификату
        }
        
        // ========================================================================
        // ПРОВЕРКА НЕОБХОДИМОСТИ ОБНОВЛЕНИЯ
        // ========================================================================
        // Проверяем, нужно ли продлить сертификат (истекает в ближайшее время)
        // Метод shouldRenewCertificate() проверяет, находится ли текущая дата
        // в диапазоне между порогом обновления и датой истечения
        if (shouldRenewCertificate(notAfter)) 
        {
            // Создаем задачу на обновление сертификата
            CertificateTask task;
            task.type = CertificateTaskType::Renew;      // Тип задачи - обновление
            task.serial = serial;                        // Серийный номер существующего сертификата
            task.subject = subject;                      // Subject сертификата
            task.expirationDate = notAfter;              // Дата истечения текущего сертификата
            task.status = TaskStatus::Pending;           // Статус - ожидает выполнения
            
            // Добавляем задачу в очередь для обработки
            addTask(task);
            renewTasksAdded++; // Увеличиваем счетчик созданных задач на обновление
            
            qDebug() << "CertificateWorker: Найден сертификат для продления. Serial:" << serial << "Истекает:" << notAfter.toString();
        }
        
        // ========================================================================
        // ПРОВЕРКА НЕОБХОДИМОСТИ ОТЗЫВА
        // ========================================================================
        // Проверяем, нужно ли отозвать сертификат (просрочен)
        // Метод shouldRevokeCertificate() проверяет, истек ли срок действия сертификата
        // с учетом параметра m_revokeAfterDays (может быть отложенный отзыв)
        if (shouldRevokeCertificate(notAfter)) 
        {
            // Создаем задачу на отзыв сертификата
            CertificateTask task;
            task.type = CertificateTaskType::Revoke;      // Тип задачи - отзыв
            task.serial = serial;                         // Серийный номер сертификата для отзыва
            task.subject = subject;                       // Subject сертификата
            task.expirationDate = notAfter;               // Дата истечения сертификата
            task.status = TaskStatus::Pending;            // Статус - ожидает выполнения
            
            // Добавляем задачу в очередь для обработки
            addTask(task);
            revokeTasksAdded++; // Увеличиваем счетчик созданных задач на отзыв
            
            qDebug() << "CertificateWorker: Найден сертификат для отзыва. Serial:" << serial << "Истек:" << notAfter.toString();
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ПРОВЕРКА CN БЕЗ АКТИВНЫХ СЕРТИФИКАТОВ
    // ========================================================================
    // Проверяем, есть ли CN (Common Name) без активных сертификатов
    // Это необходимо для автоматического выпуска сертификатов для пользователей,
    // у которых есть ключи или CSR, но нет действующего сертификата
    //
    // Проверяем все CN из таблиц keys, csr_pem и cert_pem (объединение всех источников)
    // Используем UNION для получения всех уникальных CN из всех источников
    // DISTINCT гарантирует, что каждый CN будет только один раз в результате
    QSqlQuery allCnQuery = m_database->select
    (
        "SELECT DISTINCT cn FROM keys WHERE key_type = 'user' "  // CN из таблицы ключей (только пользовательские)
        "UNION "                                                 // Объединение результатов
        "SELECT DISTINCT cn FROM csr_pem "                       // CN из таблицы CSR (Certificate Signing Request)
        "UNION "                                                 // Объединение результатов
        "SELECT DISTINCT cn FROM cert_pem"                       // CN из таблицы сертификатов (включая истекшие)
    );
    
    // Счетчик для статистики - количество созданных задач на выдачу новых сертификатов
    int issueTasksAdded = 0;
    
    // ========================================================================
    // ПЕРЕБОР ВСЕХ НАЙДЕННЫХ CN
    // ========================================================================
    // Перебираем все найденные CN для проверки наличия активных сертификатов
    while (allCnQuery.next()) 
    {
        // Извлекаем CN из результата запроса
        QString cn = allCnQuery.value("cn").toString();
        
        // ========================================================================
        // ФИЛЬТРАЦИЯ СИСТЕМНЫХ CN
        // ========================================================================
        // Пропускаем root и другие системные CN
        // root - это системный сертификат центра сертификации, не требует автоматической выдачи
        // Пустые CN также пропускаем, так как они некорректны
        if (cn == "root" || cn.isEmpty()) 
        {
            continue; // Переходим к следующему CN
        }
        
        // ========================================================================
        // ПРОВЕРКА НАЛИЧИЯ АКТИВНОГО СЕРТИФИКАТА ДЛЯ CN
        // ========================================================================
        // Проверяем, есть ли активный сертификат для этого CN
        // Ищем в таблице certs по subject, который содержит CN
        // Используем два паттерна поиска для учета разных форматов subject:
        // - "/CN=example.com" (формат с начальным слэшем)
        // - "CN=example.com" (формат без начального слэша)
        QVariantList checkParams;
        checkParams << QString("%/CN=%1%").arg(cn)  // Паттерн 1: "/CN=example.com" или "/CN=example.com/..."
                    << QString("%CN=%1%").arg(cn);  // Паттерн 2: "CN=example.com" или "CN=example.com/..."
        
        // Выполняем запрос для поиска активного сертификата
        // LIMIT 1 оптимизирует запрос - достаточно найти хотя бы один активный сертификат
        QSqlQuery checkQuery = m_database->select(
            "SELECT serial, status FROM certs WHERE (subject LIKE ? OR subject LIKE ?) AND status = 'valid' LIMIT 1",
            checkParams
        );
        
        // ========================================================================
        // СОЗДАНИЕ ЗАДАЧИ НА ВЫДАЧУ НОВОГО СЕРТИФИКАТА
        // ========================================================================
        // Если активный сертификат не найден (checkQuery.next() возвращает false),
        // значит для этого CN нет действующего сертификата - нужно выпустить новый
        if (!checkQuery.next()) 
        {
            qDebug() << "CertificateWorker: Найден CN без активного сертификата:" << cn;
            
            // Создаем задачу на выдачу нового сертификата
            CertificateTask task;
            task.type = CertificateTaskType::Issue;            // Тип задачи - выдача нового сертификата
            task.serial = 0;                                   // Serial будет назначен при выпуске сертификата
            task.subject = QString("/CN=%1").arg(cn);    // Формируем subject в формате "/CN=example.com"
            task.cn = cn;                                      // Сохраняем CN для идентификации задачи
            task.status = TaskStatus::Pending;                 // Статус - ожидает выполнения
            task.createdAt = QDateTime::currentDateTime();     // Время создания задачи
            
            // Добавляем задачу в очередь для обработки
            addTask(task);
            issueTasksAdded++; // Увеличиваем счетчик созданных задач на выдачу
            
            qDebug() << "CertificateWorker: Задача на выпуск нового сертификата добавлена для CN:" << cn;
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ВЫВОД СТАТИСТИКИ СКАНИРОВАНИЯ
    // ========================================================================
    // Всегда выводим результат сканирования для мониторинга работы воркера
    // Статистика включает:
    // - Количество просмотренных сертификатов
    // - Количество созданных задач на продление
    // - Количество созданных задач на отзыв
    // - Количество созданных задач на выдачу новых сертификатов
    qDebug() << "CertificateWorker: Сканирование завершено. Просмотрено сертификатов:" << scannedCount
                        << "| Задач на продление:" << renewTasksAdded
                        << "| Задач на отзыв:" << revokeTasksAdded
                        << "| Задач на выпуск:" << issueTasksAdded;
}


// ============================================================================
// МЕТОД shouldRenewCertificate - ПРОВЕРКА НЕОБХОДИМОСТИ ОБНОВЛЕНИЯ
// ============================================================================
// Проверяет, нужно ли обновить сертификат на основе даты истечения.
// Сертификат нужно обновить, если текущее время находится в диапазоне
// между порогом обновления (notAfter - m_renewBeforeDays) и датой истечения.
//
// ПАРАМЕТРЫ:
//   notAfter - дата истечения сертификата (QDateTime)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - сертификат нужно обновить (истекает в ближайшее время)
//   false - сертификат еще действителен
// ============================================================================
bool CertificateWorker::shouldRenewCertificate(const QDateTime &notAfter) const
{
    QDateTime now = QDateTime::currentDateTime();
    // Вычисляем порог обновления: дата истечения минус m_renewBeforeDays дней
    QDateTime renewThreshold = notAfter.addDays(-m_renewBeforeDays);
    // Сертификат нужно обновить, если текущее время >= порога и < даты истечения
    return now >= renewThreshold && now < notAfter;
}


// ============================================================================
// МЕТОД shouldRevokeCertificate - ПРОВЕРКА НЕОБХОДИМОСТИ ОТЗЫВА
// ============================================================================
// Проверяет, нужно ли отозвать сертификат на основе даты истечения.
// Сертификат нужно отозвать, если текущее время >= даты истечения + m_revokeAfterDays.
//
// ПАРАМЕТРЫ:
//   notAfter - дата истечения сертификата (QDateTime)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - сертификат нужно отозвать (просрочен)
//   false - сертификат еще действителен или уже отозван
// ============================================================================
bool CertificateWorker::shouldRevokeCertificate(const QDateTime &notAfter) const
{
    QDateTime now = QDateTime::currentDateTime();
    // Вычисляем порог отзыва: дата истечения плюс m_revokeAfterDays дней
    QDateTime revokeThreshold = notAfter.addDays(m_revokeAfterDays);
    // Сертификат нужно отозвать, если текущее время >= порога отзыва
    return now >= revokeThreshold;
}


// ============================================================================
// МЕТОД processTaskQueue - ОБРАБОТКА ОЧЕРЕДИ ЗАДАЧ
// ============================================================================
// Обрабатывает задачи из очереди последовательно. Вызывает соответствующие
// методы для каждого типа задачи (Issue, Renew, Revoke).
//
// АЛГОРИТМ:
// 1. Извлечение задачи из очереди (FIFO)
// 2. Обновление статуса задачи на Processing
// 3. Вызов соответствующего метода обработки в зависимости от типа задачи
// 4. Обновление статуса задачи (Completed или Failed)
// 5. Добавление задачи в историю (выполненных или неудачных)
// 6. Отправка сигналов о завершении задачи
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет
// ============================================================================
void CertificateWorker::processTaskQueue()
{
    // ========================================================================
    // ОСНОВНОЙ ЦИКЛ ОБРАБОТКИ ОЧЕРЕДИ
    // ========================================================================
    // Обрабатываем задачи из очереди до тех пор, пока очередь не пуста
    // или не запрошена остановка потока
    // Цикл выполняется последовательно - одна задача за раз
    while (!m_shouldStop) 
    {
        // Переменные для хранения задачи и флага наличия задачи
        CertificateTask task;
        bool hasTask = false;
        
        // ========================================================================
        // ДЕЙСТВИЕ 1: ИЗВЛЕЧЕНИЕ ЗАДАЧИ ИЗ ОЧЕРЕДИ
        // ========================================================================
        // Берем задачу из очереди (FIFO - First In, First Out)
        // Используем блок с мьютексом для безопасного доступа к очереди
        {
            // Блокируем мьютекс очереди для безопасного извлечения задачи
            QMutexLocker locker(&m_queueMutex);
            
            // Проверяем, есть ли задачи в очереди
            if (m_taskQueue.isEmpty()) 
            {
                // Очередь пуста, выходим из цикла
                // Это нормальное завершение обработки - все задачи обработаны
                break;
            }
            
            // Извлекаем первую задачу из очереди (FIFO - самая старая задача первой)
            // dequeue() удаляет задачу из очереди и возвращает её
            task = m_taskQueue.dequeue();
            hasTask = true; // Устанавливаем флаг, что задача извлечена
        }
        // Мьютекс автоматически разблокируется здесь при выходе из блока
        
        // ========================================================================
        // ПРОВЕРКА УСЛОВИЙ ДЛЯ ОБРАБОТКИ
        // ========================================================================
        // Проверяем, что задача была извлечена и не запрошена остановка
        // Это дополнительная проверка для безопасности
        if (!hasTask || m_shouldStop) 
        {
            // Нет задачи или запрошена остановка - выходим из цикла
            break;
        }
        
        // ========================================================================
        // ДЕЙСТВИЕ 2: ОБНОВЛЕНИЕ СТАТУСА НА ОБРАБОТКУ
        // ========================================================================
        // Обновляем статус задачи на Processing и отправляем сигнал
        // Это уведомляет другие части приложения о начале обработки задачи
        task.status = TaskStatus::Processing;
        
        // Отправляем сигнал о начале обработки задачи
        // Сигнал может быть подключен к слотам для обновления UI или логирования
        emit taskStarted(task);
        
        qDebug() << "CertificateWorker: Начало обработки задачи. Тип:" << static_cast<int>(task.type) << "Serial:" << task.serial;
        
        // Флаг успешности выполнения задачи
        bool success = false;
        
        // ========================================================================
        // ДЕЙСТВИЕ 3: ОБРАБОТКА ЗАДАЧИ В ЗАВИСИМОСТИ ОТ ТИПА
        // ========================================================================
        // Обрабатываем задачу в зависимости от типа
        // Копируем задачу для изменения (методы обработки могут изменять задачу)
        // Это позволяет сохранить оригинальную задачу, если обработка изменит её поля
        CertificateTask taskCopy = task;
        
        // Выбираем метод обработки в зависимости от типа задачи
        switch (task.type) 
        {
            case CertificateTaskType::Issue:
                // Выдача нового сертификата
                // Метод выполняет HTTP запрос к серверу minica для выпуска сертификата
                success = processIssueTask(taskCopy);
                break;
                
            case CertificateTaskType::Renew:
                // Обновление существующего сертификата
                // Метод вызывает внешний процесс minica для продления сертификата
                success = processRenewTask(taskCopy);
                break;
                
            case CertificateTaskType::Revoke:
                // Отзыв сертификата
                // Метод обновляет базу данных и генерирует CRL
                success = processRevokeTask(taskCopy);
                break;
        }
        
        // Обновляем оригинальную задачу результатами обработки
        // Это необходимо, так как методы обработки могут изменить поля задачи
        // (например, обновить serial, добавить errorMessage и т.д.)
        task = taskCopy;
        
        // ========================================================================
        // ДЕЙСТВИЕ 4: ОБНОВЛЕНИЕ СТАТУСА И ДОБАВЛЕНИЕ В ИСТОРИЮ
        // ========================================================================
        // Обновляем статус задачи и добавляем в соответствующую историю
        // Устанавливаем время обработки задачи
        task.processedAt = QDateTime::currentDateTime();
        
        if (success) 
        {
            // ========================================================================
            // УСПЕШНОЕ ЗАВЕРШЕНИЕ ЗАДАЧИ
            // ========================================================================
            // Задача выполнена успешно - обновляем статус и добавляем в историю выполненных
            task.status = TaskStatus::Completed;
            
            // Блокируем мьютекс истории для безопасного доступа
            {
                QMutexLocker locker(&m_historyMutex);
                
                // Добавляем задачу в список выполненных задач
                m_completedTasks.append(task);
                
                // Ограничиваем размер истории (последние 1000 задач)
                // Удаляем самые старые задачи, если история превышает лимит
                // Это предотвращает неограниченный рост памяти
                if (m_completedTasks.size() > 1000) 
                {
                    // Удаляем самую старую задачу (первую в списке)
                    m_completedTasks.removeFirst();
                }
            }
            // Мьютекс автоматически разблокируется здесь
            
            // Отправляем сигнал о успешном завершении задачи
            emit taskCompleted(task);
            
            qDebug() << "CertificateWorker: Задача завершена успешно. Serial:" << task.serial;
        } 
        else 
        {
            // ========================================================================
            // НЕУДАЧНОЕ ЗАВЕРШЕНИЕ ЗАДАЧИ
            // ========================================================================
            // Задача завершилась с ошибкой - обновляем статус и добавляем в историю неудачных
            task.status = TaskStatus::Failed;
            
            // Блокируем мьютекс истории для безопасного доступа
            {
                QMutexLocker locker(&m_historyMutex);
                
                // Добавляем задачу в список неудачных задач
                m_failedTasks.append(task);
                
                // Ограничиваем размер истории (последние 1000 задач)
                // Удаляем самые старые задачи, если история превышает лимит
                // Это предотвращает неограниченный рост памяти
                if (m_failedTasks.size() > 1000) 
                {
                    // Удаляем самую старую задачу (первую в списке)
                    m_failedTasks.removeFirst();
                }
            }
            // Мьютекс автоматически разблокируется здесь
            
            // Отправляем сигнал о неудачном завершении задачи
            emit taskFailed(task);
            
            qDebug() << "CertificateWorker: Задача завершена с ошибкой. Serial:" << task.serial << "Ошибка:" << task.errorMessage;
        }
    }
    // Цикл завершается, когда очередь пуста или запрошена остановка потока
}


// ============================================================================
// МЕТОД processIssueTask - ОБРАБОТКА ЗАДАЧИ НА ВЫДАЧУ СЕРТИФИКАТА
// ============================================================================
// Обрабатывает задачу на выдачу нового сертификата.
// Использует HTTP API minica для выпуска сертификата через сервер.
//
// АЛГОРИТМ:
// 1. Получение корневой директории проекта
// 2. Извлечение CN из subject или task.cn
// 3. Формирование HTTP запроса к серверу minica
// 4. Выполнение запроса с повторными попытками при ошибках подключения
// 5. Проверка успешности выпуска (статус код 200)
// 6. Верификация появления сертификата в базе данных
//
// ПАРАМЕТРЫ:
//   task - задача на выдачу сертификата (CertificateTask&)
//          Модифицируется в процессе выполнения (обновляется статус, ошибки)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - задача успешно выполнена (сертификат выпущен)
//   false - задача завершилась с ошибкой
//
// ПРИМЕЧАНИЕ:
//   Использует HTTP API endpoint /pdf-sign-embed для выпуска сертификата
//   Выполняет до 5 попыток при ошибках подключения
// ============================================================================
bool CertificateWorker::processIssueTask(CertificateTask &task)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПОЛУЧЕНИЕ КОРНЕВОЙ ДИРЕКТОРИИ
    // ========================================================================
    // Получаем корневую директорию проекта (может понадобиться для работы с файлами)
    QString rootDir = getRootDir();
    if (rootDir.isEmpty()) 
    {
        qWarning() << "CertificateWorker: Не удалось определить корневую директорию";
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ИЗВЛЕЧЕНИЕ CN ИЗ SUBJECT
    // ========================================================================
    // Извлекаем CN из subject или используем task.cn
    // CN (Common Name) - основной идентификатор сертификата
    // Используем task.cn, если он задан, иначе извлекаем из subject
    QString cn = task.cn.isEmpty() ? task.subject : task.cn;
    
    // ========================================================================
    // ПАРСИНГ РАЗЛИЧНЫХ ФОРМАТОВ SUBJECT
    // ========================================================================
    // Обрабатываем различные форматы subject для извлечения CN:
    // - "/CN=example.com" -> "example.com"
    // - "CN=example.com" -> "example.com"
    // - "CN=example.com/O=Org" -> "example.com"
    // - "/CN=example.com/O=Organization" -> "example.com"
    
    // Проверяем формат с начальным слэшем "/CN="
    if (cn.startsWith("/CN=")) 
    {
        // Убираем префикс "/CN=" (4 символа)
        cn = cn.mid(4);
    } 
    // Проверяем формат без начального слэша "CN="
    else if (cn.contains("CN=")) 
    {
        // Находим позицию начала "CN="
        int cnPos = cn.indexOf("CN=");
        // Извлекаем строку после "CN=" (3 символа)
        cn = cn.mid(cnPos + 3);
        
        // Убираем возможные суффиксы после CN (например, "/O=Org", "/C=RU")
        // Ищем первый слэш после CN, который указывает на следующий компонент DN
        int slashPos = cn.indexOf("/");
        if (slashPos >= 0) 
        {
            // Оставляем только часть до первого слэша (только CN)
            cn = cn.left(slashPos);
        }
    }
    
    // Проверяем, что CN был успешно извлечен
    if (cn.isEmpty()) 
    {
        qWarning() << "CertificateWorker: Не удалось извлечь CN для выпуска сертификата";
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ФОРМИРОВАНИЕ HTTP ЗАПРОСА
    // ========================================================================
    // Используем HTTP API minica для выпуска сертификата
    // Сервер должен быть запущен в MainWindow и слушать на указанном адресе и порту
    qDebug() << "CertificateWorker: Выпуск сертификата для CN:" << cn;
    
    // ========================================================================
    // КОНСТАНТЫ ДЛЯ ПОВТОРНЫХ ПОПЫТОК
    // ========================================================================
    // Настройки для обработки временных ошибок подключения
    const int maxRetries = 5;           // максимальное количество попыток (5 попыток)
    const int retryDelayMs = 2000;      // задержка между попытками (2 секунды)
    
    // ========================================================================
    // СОЗДАНИЕ МЕНЕДЖЕРА СЕТЕВЫХ ЗАПРОСОВ
    // ========================================================================
    // Создаем менеджер сетевых запросов для выполнения HTTP запросов
    // QNetworkAccessManager управляет сетевой сессией и обработкой запросов
    QNetworkAccessManager manager;
    
    // ========================================================================
    // ФОРМИРОВАНИЕ URL ДЛЯ ЗАПРОСА
    // ========================================================================
    // Формируем URL для запроса к серверу minica
    // Endpoint /pdf-sign-embed используется для выпуска сертификата
    // Используем адрес и порт из конфигурации (m_serverBindAddr, m_serverPort)
    QUrl url(QString("http://%1:%2/pdf-sign-embed").arg(m_serverBindAddr).arg(m_serverPort));
    
    // ========================================================================
    // ДОБАВЛЕНИЕ ПАРАМЕТРОВ ЗАПРОСА
    // ========================================================================
    // Добавляем параметры запроса в URL query string
    QUrlQuery query;
    query.addQueryItem("cn", cn);                                    // Common Name - основной идентификатор
    query.addQueryItem("san", QString("DNS:%1").arg(cn));      // Subject Alternative Name - альтернативное имя
    url.setQuery(query);                                                        // Устанавливаем query string в URL
    
    // ========================================================================
    // СОЗДАНИЕ СЕТЕВОГО ЗАПРОСА
    // ========================================================================
    // Создаем сетевой запрос с настроенными параметрами
    QNetworkRequest request(url);
    // Устанавливаем заголовок Content-Type для указания типа данных
    // application/octet-stream - бинарные данные (для POST запроса)
    request.setHeader(QNetworkRequest::ContentTypeHeader, "application/octet-stream");
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ВЫПОЛНЕНИЕ ЗАПРОСА С ПОВТОРНЫМИ ПОПЫТКАМИ
    // ========================================================================
    // Выполняем запрос с повторными попытками при ошибках подключения
    // Это необходимо для обработки временных проблем с сетью или сервером
    bool success = false;
    
    // Цикл повторных попыток - выполняем до maxRetries попыток
    for (int attempt = 0; attempt < maxRetries; ++attempt) 
    {
        // ========================================================================
        // ЗАДЕРЖКА ПЕРЕД ПОВТОРНОЙ ПОПЫТКОЙ
        // ========================================================================
        // Ждем перед повторной попыткой (кроме первой)
        // Это дает серверу время восстановиться после временных проблем
        if (attempt > 0) 
        {
            qDebug() << "CertificateWorker: Повторная попытка выпуска сертификата. Попытка:" << (attempt + 1) << "/" << maxRetries;
            // Ждем указанное время перед повторной попыткой
            QThread::msleep(retryDelayMs);
        }
        
        // ========================================================================
        // ВЫПОЛНЕНИЕ HTTP POST ЗАПРОСА
        // ========================================================================
        // Создаем цикл событий для синхронного выполнения асинхронного запроса
        // QNetworkAccessManager работает асинхронно, но нам нужно дождаться результата
        QEventLoop loop;
        
        // Выполняем POST запрос с пустым телом (данные передаются через query параметры)
        // manager.post() возвращает QNetworkReply* - объект для получения ответа
        QNetworkReply *reply = manager.post(request, QByteArray());
        
        // ========================================================================
        // НАСТРОЙКА ОБРАБОТКИ ЗАВЕРШЕНИЯ ЗАПРОСА
        // ========================================================================
        // Подключаем сигнал завершения запроса к выходу из цикла событий
        // Когда запрос завершится (успешно или с ошибкой), цикл событий завершится
        connect(reply, &QNetworkReply::finished, &loop, &QEventLoop::quit);
        
        // ========================================================================
        // УСТАНОВКА ТАЙМАУТА ДЛЯ ЗАПРОСА
        // ========================================================================
        // Устанавливаем таймаут для запроса (15 секунд - больше времени для обработки)
        // Если запрос не завершится за 15 секунд, цикл событий завершится принудительно
        // Это предотвращает бесконечное ожидание при зависании сервера
        QTimer::singleShot(15000, &loop, &QEventLoop::quit);
        
        // Запускаем цикл событий - ждем завершения запроса или таймаута
        loop.exec();
        
        // ========================================================================
        // ПРОВЕРКА РЕЗУЛЬТАТА ЗАПРОСА
        // ========================================================================
        // Проверяем статус код первым (может быть успех, даже если есть ошибка соединения)
        // HTTP статус код 200 означает успешное выполнение запроса
        int statusCode = reply->attribute(QNetworkRequest::HttpStatusCodeAttribute).toInt();
        
        if (statusCode == 200) 
        {
            // ========================================================================
            // УСПЕШНЫЙ ОТВЕТ ОТ СЕРВЕРА
            // ========================================================================
            // Читаем ответ полностью, чтобы убедиться, что данные получены
            // Ответ может содержать информацию о выпущенном сертификате
            QByteArray responseData = reply->readAll();
            qDebug() << "CertificateWorker: Сертификат успешно выпущен для CN:" << cn 
                     << "Размер ответа:" << responseData.size() << "байт";
            
            // ========================================================================
            // ВЕРИФИКАЦИЯ ПОЯВЛЕНИЯ СЕРТИФИКАТА В БАЗЕ ДАННЫХ
            // ========================================================================
            // Проверяем, что сертификат действительно появился в базе данных
            // Это дополнительная проверка успешности операции
            if (m_database && m_database->isConnected()) 
            {
                // Формируем параметры для поиска сертификата по CN
                QVariantList checkParams;
                checkParams << QString("%/CN=%1%").arg(cn)  // Паттерн 1: "/CN=example.com"
                           << QString("%CN=%1%").arg(cn);   // Паттерн 2: "CN=example.com"
                
                // Ищем сертификат в базе данных
                // ORDER BY serial DESC - берем самый новый сертификат (последний выпущенный)
                // LIMIT 1 - достаточно найти один активный сертификат
                QSqlQuery verifyQuery = m_database->select
                (
                    "SELECT serial, status FROM certs WHERE (subject LIKE ? OR subject LIKE ?) AND status = 'valid' ORDER BY serial DESC LIMIT 1",
                    checkParams
                );
                
                if (verifyQuery.next()) 
                {
                    // Сертификат найден в базе данных - операция успешна
                    long serial = verifyQuery.value("serial").toLongLong();
                    qDebug() << "CertificateWorker: Сертификат подтвержден в БД. Serial:" << serial << "CN:" << cn;
                } 
                else 
                {
                    // Сертификат не найден - возможно, еще не успел появиться в БД
                    // Это не критическая ошибка, так как сервер вернул 200
                    qWarning() << "CertificateWorker: Сертификат не найден в БД после выпуска. CN:" << cn;
                }
            }
            
            // Устанавливаем флаг успешности и выходим из цикла попыток
            success = true;
            reply->deleteLater(); // Освобождаем ресурсы ответа
            break; // Выходим из цикла попыток при успехе
        }
        
        // ========================================================================
        // ОБРАБОТКА ОШИБОК
        // ========================================================================
        // Если статус код не 200, проверяем тип ошибки
        if (reply->error() == QNetworkReply::NoError) 
        {
            // Нет ошибки сети, но статус код не 200 (например, 404, 500)
            // Это означает, что сервер ответил, но операция не выполнена
            qWarning() << "CertificateWorker: Ошибка при выпуске сертификата. Код:" << statusCode;
            // Не повторяем при таких ошибках - проблема на стороне сервера
            reply->deleteLater();
            break;
        } 
        else 
        {
            // Есть ошибка сети - возможно, временная проблема
            QString errorString = reply->errorString();
            qWarning() << "CertificateWorker: Ошибка при выпуске сертификата (попытка" << (attempt + 1) << "/" << maxRetries << "):" << errorString;
            
            // ========================================================================
            // ПРОВЕРКА ТИПА ОШИБКИ ДЛЯ ПОВТОРА
            // ========================================================================
            // Если это не ошибка подключения или закрытия соединения, не повторяем
            // Повторяем только при временных проблемах с сетью:
            // - ConnectionRefusedError - сервер недоступен (может быть временно)
            // - TimeoutError - таймаут запроса (может быть временная перегрузка)
            // - RemoteHostClosedError - сервер закрыл соединение (может быть временно)
            // Не повторяем при других ошибках (авторизация, неверный запрос и т.д.)
            if (reply->error() != QNetworkReply::ConnectionRefusedError && 
                reply->error() != QNetworkReply::TimeoutError &&
                reply->error() != QNetworkReply::RemoteHostClosedError) 
            {
                // Некритичная ошибка - не повторяем
                reply->deleteLater();
                break; // Выходим из цикла при некритичных ошибках
            }
        }
        
        // Освобождаем ресурсы ответа перед следующей попыткой
        reply->deleteLater();
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ПРОВЕРКА УСПЕШНОСТИ ВЫПОЛНЕНИЯ
    // ========================================================================
    if (!success) 
    {
        qWarning() << "CertificateWorker: Не удалось выпустить сертификат после" << maxRetries << "попыток";
    }
    
    return success;
}


// ============================================================================
// МЕТОД processRenewTask - ОБРАБОТКА ЗАДАЧИ НА ОБНОВЛЕНИЕ СЕРТИФИКАТА
// ============================================================================
// Обрабатывает задачу на обновление существующего сертификата.
// Использует внешний процесс minica для обновления сертификата.
//
// АЛГОРИТМ:
// 1. Проверка подключения к базе данных
// 2. Получение корневой директории проекта
// 3. Извлечение CN из subject
// 4. Получение старого сертификата из базы данных
// 5. Создание временного файла со старым сертификатом
// 6. Вызов minica renew через QProcess
// 7. Удаление временного файла
//
// ПАРАМЕТРЫ:
//   task - задача на обновление сертификата (CertificateTask&)
//          Модифицируется в процессе выполнения (обновляется статус, ошибки)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - задача успешно выполнена (сертификат обновлен)
//   false - задача завершилась с ошибкой
//
// ПРИМЕЧАНИЕ:
//   Использует команду minica renew для обновления сертификата
//   Новый сертификат сохраняется в ca/certs/{serial}_renewed.pem
// ============================================================================
bool CertificateWorker::processRenewTask(CertificateTask &task)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА ПОДКЛЮЧЕНИЯ К БАЗЕ ДАННЫХ
    // ========================================================================
    if (!m_database || !m_database->isConnected()) 
    {
        qWarning() << "CertificateWorker: База данных не подключена";
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПОЛУЧЕНИЕ КОРНЕВОЙ ДИРЕКТОРИИ
    // ========================================================================
    QString rootDir = getRootDir();
    if (rootDir.isEmpty()) 
    {
        qWarning() << "CertificateWorker: Не удалось определить корневую директорию";
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ИЗВЛЕЧЕНИЕ CN ИЗ SUBJECT
    // ========================================================================
    // Используем обертки БД для поиска старого сертификата
    // Извлекаем CN из subject для поиска сертификата в базе данных
    // CN необходим для поиска сертификата в таблице cert_pem
    QString cn = task.subject;
    
    // Парсим различные форматы subject для извлечения CN
    if (cn.startsWith("/CN=")) 
    {
        // Формат с начальным слэшем: "/CN=example.com"
        cn = cn.mid(4);         // Убираем "/CN=" (4 символа)
    } 
    else if (cn.contains("CN=")) 
    {
        // Формат без начального слэша: "CN=example.com" или "CN=example.com/O=Org"
        int cnPos = cn.indexOf("CN=");
        cn = cn.mid(cnPos + 3); // Убираем "CN=" (3 символа)
        
        // Убираем возможные суффиксы после CN (например, "/O=Org")
        int slashPos = cn.indexOf("/");
        if (slashPos >= 0) 
        {
            cn = cn.left(slashPos);    // Оставляем только CN до первого слэша
        }
    }
    
    // Проверяем, что CN был успешно извлечен
    if (cn.isEmpty()) 
    {
        qWarning() << "CertificateWorker: Не удалось извлечь CN для продления сертификата";
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ПОЛУЧЕНИЕ СТАРОГО СЕРТИФИКАТА ИЗ БАЗЫ ДАННЫХ
    // ========================================================================
    // Получаем старый сертификат из БД через обертки
    // Ищем сертификат по CN в таблице cert_pem
    QSqlQuery certQuery = m_database->select
    (
        "SELECT cert_pem FROM cert_pem WHERE cn = ?",
        QVariantList() << cn
    );
    
    if (!certQuery.next()) 
    {
        qWarning() << "CertificateWorker: Старый сертификат не найден в БД для CN:" << cn;
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: СОЗДАНИЕ ВРЕМЕННОГО ФАЙЛА СО СТАРЫМ СЕРТИФИКАТОМ
    // ========================================================================
    // Создаем временный файл со старым сертификатом для передачи в minica
    // minica renew требует путь к файлу старого сертификата
    // Используем системную временную директорию для хранения файла
    QString tempOldCertPath = QDir::tempPath() + "/old_cert_" + QString::number(task.serial) + ".pem";
    
    // Создаем файл для записи старого сертификата
    QFile tempOldFile(tempOldCertPath);
    if (!tempOldFile.open(QIODevice::WriteOnly)) 
    {
        qWarning() << "CertificateWorker: Не удалось создать временный файл старого сертификата";
        return false;
    }
    
    // Записываем PEM-кодированный сертификат в файл
    // cert_pem содержит сертификат в формате PEM (текстовый формат)
    tempOldFile.write(certQuery.value("cert_pem").toByteArray());
    tempOldFile.close(); // Закрываем файл после записи
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ФОРМИРОВАНИЕ ПУТИ ДЛЯ НОВОГО СЕРТИФИКАТА
    // ========================================================================
    // Создаем путь для нового сертификата
    // Новый сертификат будет сохранен в ca/certs/{serial}_renewed.pem
    fs::path rootPath = rootDir.toStdString();
    fs::path newCertPath = rootPath / "ca" / "certs" / (QString::number(task.serial) + "_renewed.pem").toStdString();
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: ВЫЗОВ MINICA RENEW ЧЕРЕЗ QPROCESS
    // ========================================================================
    // Вызываем minica renew через QProcess
    // cmd_renew использует центр сертификации (ca/private/root.key, ca/root.crt)
    // и обертки БД (dbInsertIssued через CaDatabase)
    QProcess renewProcess;
    
    // ========================================================================
    // ПОИСК ИСПОЛНЯЕМОГО ФАЙЛА MINICA
    // ========================================================================
    // Ищем путь к исполняемому файлу minica
    // Сначала проверяем в директории приложения
    QString minicaPath = QCoreApplication::applicationDirPath() + "/minica";
    if (!QFileInfo::exists(minicaPath)) 
    {
        // Если не найден, пытаемся найти в build директории (на уровень выше)
        minicaPath = QCoreApplication::applicationDirPath() + "/../minica";
    }
    
    // ========================================================================
    // ФОРМИРОВАНИЕ АРГУМЕНТОВ ДЛЯ КОМАНДЫ MINICA RENEW
    // ========================================================================
    // Формируем аргументы для команды minica renew
    // Команда: minica renew <rootDir> <oldCertPath> <newCertPath> <validityDays>
    QStringList arguments;
    arguments << "renew"                                    // команда обновления сертификата
              << rootDir                                    // корневая директория проекта (для доступа к CA ключам)
              << tempOldCertPath                            // путь к старому сертификату (временный файл)
              << QString::fromStdString(newCertPath.string()) // путь для нового сертификата (ca/certs/{serial}_renewed.pem)
              << "825";                                     // срок действия нового сертификата (825 дней ≈ 2.25 года)
    
    // ========================================================================
    // ЗАПУСК ПРОЦЕССА MINICA RENEW
    // ========================================================================
    // Запускаем процесс minica renew
    // Процесс выполнит обновление сертификата и сохранит новый сертификат в указанный путь
    renewProcess.start(minicaPath, arguments);
    
    // Ждем завершения процесса (до 30 секунд)
    // Обновление сертификата может занять время из-за криптографических операций
    if (!renewProcess.waitForFinished(30000)) 
    {
        qWarning() << "CertificateWorker: Процесс minica renew не завершился вовремя";
        // Удаляем временный файл при ошибке, чтобы не засорять временную директорию
        QFile::remove(tempOldCertPath);
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 8: ПРОВЕРКА РЕЗУЛЬТАТА ОБНОВЛЕНИЯ
    // ========================================================================
    bool success = false;
    if (renewProcess.exitCode() == 0) 
    {
        // Процесс завершился успешно (код возврата 0)
        qDebug() << "CertificateWorker: Сертификат успешно продлен. Serial:" << task.serial;
        success = true;
    } 
    else 
    {
        // Процесс завершился с ошибкой
        QString errorOutput = renewProcess.readAllStandardError();
        qWarning() << "CertificateWorker: Ошибка при продлении сертификата:" << errorOutput;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 9: УДАЛЕНИЕ ВРЕМЕННОГО ФАЙЛА
    // ========================================================================
    // Удаляем временный файл со старым сертификатом
    QFile::remove(tempOldCertPath);
    
    return success;
}


// ============================================================================
// МЕТОД processRevokeTask - ОБРАБОТКА ЗАДАЧИ НА ОТЗЫВ СЕРТИФИКАТА
// ============================================================================
// Обрабатывает задачу на отзыв сертификата.
// Использует обертки базы данных для отзыва сертификата.
//
// АЛГОРИТМ:
// 1. Проверка подключения к базе данных
// 2. Проверка существования сертификата и его текущего статуса
// 3. Добавление записи в таблицу revoked (если еще не отозван)
// 4. Обновление статуса сертификата в таблице certs на 'revoked'
// 5. Генерация актуального CRL после отзыва
// 6. Автоматическое создание задачи на выдачу нового сертификата
//
// ПАРАМЕТРЫ:
//   task - задача на отзыв сертификата (CertificateTask&)
//          Модифицируется в процессе выполнения (обновляется статус, ошибки)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - задача успешно выполнена (сертификат отозван)
//   false - задача завершилась с ошибкой
//
// ПРИМЕЧАНИЕ:
//   После отзыва автоматически создается задача на выдачу нового сертификата
//   для того же CN, чтобы обеспечить непрерывность работы
// ============================================================================
bool CertificateWorker::processRevokeTask(CertificateTask &task)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА ПОДКЛЮЧЕНИЯ К БАЗЕ ДАННЫХ
    // ========================================================================
    if (!m_database || !m_database->isConnected()) 
    {
        qWarning() << "CertificateWorker: База данных не подключена";
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПРОВЕРКА СУЩЕСТВОВАНИЯ СЕРТИФИКАТА
    // ========================================================================
    // Используем обертки для работы с БД напрямую
    // Проверяем, что сертификат существует и имеет статус 'valid'
    QSqlQuery checkQuery = m_database->select
    (
        "SELECT status FROM certs WHERE serial = ?",
        QVariantList() << static_cast<qlonglong>(task.serial)
    );
    
    if (!checkQuery.next()) 
    {
        qWarning() << "CertificateWorker: Сертификат не найден в базе данных. Serial:" << task.serial;
        return false;
    }
    
    // ========================================================================
    // ПРОВЕРКА ТЕКУЩЕГО СТАТУСА СЕРТИФИКАТА
    // ========================================================================
    // Проверяем, не отозван ли сертификат уже
    // Если сертификат уже отозван, задача считается выполненной
    QString currentStatus = checkQuery.value("status").toString();
    if (currentStatus == "revoked") 
    {
        qDebug() << "CertificateWorker: Сертификат уже отозван. Serial:" << task.serial;
        // Уже отозван, считаем задачу выполненной (идемпотентность операции)
        return true;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ДОБАВЛЕНИЕ ЗАПИСИ В ТАБЛИЦУ REVOKED
    // ========================================================================
    // Отзываем сертификат через обертки БД
    // 1. Добавляем запись в таблицу revoked с причиной отзыва
    // Таблица revoked хранит информацию об отозванных сертификатах для CRL
    QVariantList revokedParams;
    revokedParams << static_cast<qlonglong>(task.serial)             // Серийный номер отозванного сертификата
                  << QString("expired")                           // Причина отзыва (истек срок действия)
                  << static_cast<qlonglong>(QDateTime::currentDateTime().toSecsSinceEpoch()); // Время отзыва (timestamp)
    
    // Используем INSERT OR REPLACE для идемпотентности (если запись уже есть, обновляем)
    if (!m_database->exec("INSERT OR REPLACE INTO revoked(serial,reason,revoked_at) VALUES(?,?,?)", revokedParams)) 
    {
        qWarning() << "CertificateWorker: Ошибка при добавлении записи в таблицу revoked:" << m_database->getLastError();
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ОБНОВЛЕНИЕ СТАТУСА В ТАБЛИЦЕ CERTS
    // ========================================================================
    // 2. Обновляем статус в таблице certs на 'revoked'
    QVariantList updateParams;
    updateParams << static_cast<qlonglong>(task.serial);
    if (!m_database->exec("UPDATE certs SET status='revoked' WHERE serial=?", updateParams)) 
    {
        qWarning() << "CertificateWorker: Ошибка при обновлении статуса сертификата:" << m_database->getLastError();
        return false;
    }
    
    qDebug() << "CertificateWorker: Сертификат успешно отозван через обертки БД. Serial:" << task.serial;
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ГЕНЕРАЦИЯ АКТУАЛЬНОГО CRL
    // ========================================================================
    // Генерируем актуальный CRL после отзыва сертификата
    // Это необходимо для того, чтобы отозванный сертификат был включен в список
    generateCrl();
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: АВТОМАТИЧЕСКОЕ СОЗДАНИЕ ЗАДАЧИ НА ВЫДАЧУ НОВОГО СЕРТИФИКАТА
    // ========================================================================
    // После отзыва автоматически выпускаем новый сертификат
    // Это обеспечивает непрерывность работы - пользователь не останется без сертификата
    // Извлекаем CN из subject для создания задачи на выдачу
    QString cn = task.subject;
    
    // Парсим различные форматы subject для извлечения CN
    if (cn.startsWith("/CN=")) 
    {
        // Формат с начальным слэшем: "/CN=example.com"
        cn = cn.mid(4);         // Убираем "/CN="
    } 
    // Проверяем формат без начального слэша "CN="
    else if (cn.contains("CN=")) 
    {
        // Формат без начального слэша: "CN=example.com" или "CN=example.com/O=Org"
        int cnPos = cn.indexOf("CN=");
        cn = cn.mid(cnPos + 3); // Убираем "CN="
        
        // Убираем возможные суффиксы после CN
        int slashPos = cn.indexOf("/");
        if (slashPos >= 0) 
        {
            cn = cn.left(slashPos);    // Оставляем только CN
        }
    }
    
    // Создаем задачу на выдачу нового сертификата, если CN был извлечен
    if (!cn.isEmpty()) 
    {
        qDebug() << "CertificateWorker: Автоматический выпуск нового сертификата для CN:" << cn;
        
        // Создаем задачу на выдачу нового сертификата
        CertificateTask issueTask;
        issueTask.type = CertificateTaskType::Issue;            // Тип задачи - выдача нового сертификата
        issueTask.serial = 0;                                   // Serial будет назначен при выпуске
        issueTask.subject = task.subject;                       // Используем тот же subject
        issueTask.cn = cn;                                      // CN для идентификации
        issueTask.status = TaskStatus::Pending;                 // Статус - ожидает выполнения
        issueTask.createdAt = QDateTime::currentDateTime();     // Время создания задачи
        
        // Добавляем задачу на выпуск нового сертификата в очередь
        // Задача будет обработана в следующем цикле обработки очереди
        addTask(issueTask);
        qDebug() << "CertificateWorker: Задача на выпуск нового сертификата добавлена для CN:" << cn;
    }
    
    return true;
}


// ============================================================================
// МЕТОД getRootDir - ПОЛУЧЕНИЕ КОРНЕВОЙ ДИРЕКТОРИИ
// ============================================================================
// Возвращает путь к корневой директории проекта для работы с файлами сертификатов.
// Определяет корневую директорию на основе расположения исполняемого файла.
//
// АЛГОРИТМ:
// 1. Получение директории исполняемого файла
// 2. Проверка, является ли это macOS bundle (содержит /Contents/MacOS)
// 3. Если bundle - переход на 4 уровня вверх
// 4. Если обычный бинарь - проверка наличия CMakeLists.txt в родительской директории
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   QString - путь к корневой директории проекта
//
// ПРИМЕЧАНИЕ:
//   Поддерживает как обычные бинарные сборки, так и macOS bundle
// ============================================================================
QString CertificateWorker::getRootDir() const
{
    // ========================================================================
    // ПОЛУЧЕНИЕ ДИРЕКТОРИИ ИСПОЛНЯЕМОГО ФАЙЛА
    // ========================================================================
    // Определяем корневую директорию проекта на основе расположения исполняемого файла
    // applicationDirPath() возвращает директорию, где находится исполняемый файл
    QString appDir = QCoreApplication::applicationDirPath();
    QDir baseDir(appDir);
    
    // ========================================================================
    // ОБРАБОТКА MACOS BUNDLE
    // ========================================================================
    // macOS bundle: <project>/build/3FA.app/Contents/MacOS
    // Структура bundle:
    //   3FA.app/
    //     Contents/
    //       MacOS/          <- здесь находится исполняемый файл
    //       Resources/
    //       Info.plist
    // Нужно подняться на 4 уровня вверх для получения корневой директории проекта:
    //   ../../../../  из MacOS -> 3FA.app -> build -> project root
    if (appDir.contains("/Contents/MacOS")) 
    {
        // Переходим на 4 уровня вверх от MacOS до корня проекта
        baseDir = QDir(baseDir.absoluteFilePath("../../../../"));
    } 
    else 
    {
        // ========================================================================
        // ОБЫЧНЫЙ СЛУЧАЙ: БИНАРЬ В BUILD/
        // ========================================================================
        // Обычный случай: бинарь в build/
        // Структура: <project>/build/3FA
        // Проверяем наличие CMakeLists.txt в родительской директории
        // CMakeLists.txt всегда находится в корне проекта
        QDir tryBuildParent(baseDir.absoluteFilePath(".."));
        if (tryBuildParent.exists("CMakeLists.txt")) 
        {
            // Найден CMakeLists.txt - это корневая директория проекта
            baseDir = tryBuildParent;
        }
        // Если CMakeLists.txt не найден, возвращаем текущую директорию
    }
    
    // Возвращаем абсолютный путь к корневой директории проекта
    return baseDir.absolutePath();
}


// ============================================================================
// МЕТОД cleanupOldRevokedCertificates - ОЧИСТКА СТАРЫХ ОТОЗВАННЫХ СЕРТИФИКАТОВ
// ============================================================================
// Удаляет старые отозванные сертификаты из базы данных и файловой системы
// после истечения срока хранения (m_deleteRevokedAfterDays дней).
//
// АЛГОРИТМ:
// 1. Проверка подключения к базе данных
// 2. Вычисление порога удаления (текущее время - m_deleteRevokedAfterDays дней)
// 3. Поиск отозванных сертификатов, отозванных до порога
// 4. Для каждого найденного сертификата:
//    a. Извлечение CN из subject
//    b. Удаление из таблицы revoked
//    c. Удаление из таблицы certs
//    d. Удаление из таблицы cert_pem (если есть CN)
// 5. Вывод статистики удаления
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет
//
// ПРИМЕЧАНИЕ:
//   Используется для очистки базы данных от старых отозванных сертификатов
//   Вызывается периодически в основном цикле рабочего потока
// ============================================================================
void CertificateWorker::cleanupOldRevokedCertificates()
{
    // Проверяем подключение к базе данных
    if (!m_database || !m_database->isConnected()) 
    {
        return;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 1: ВЫЧИСЛЕНИЕ ПОРОГА УДАЛЕНИЯ
    // ========================================================================
    // Получаем текущее время и вычисляем порог удаления
    // Сертификаты, отозванные до этого порога, будут удалены
    // Это позволяет хранить отозванные сертификаты определенное время
    // (например, для аудита или восстановления), а затем удалять их
    QDateTime now = QDateTime::currentDateTime();
    qint64 nowTimestamp = now.toSecsSinceEpoch();
    
    // Вычисляем порог удаления: текущее время минус количество дней хранения
    // 86400 секунд = 1 день (24 часа * 60 минут * 60 секунд)
    qint64 deleteThreshold = nowTimestamp - (m_deleteRevokedAfterDays * 86400LL);
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПОИСК СТАРЫХ ОТОЗВАННЫХ СЕРТИФИКАТОВ
    // ========================================================================
    // Находим отозванные сертификаты, которые были отозваны более m_deleteRevokedAfterDays дней назад
    // Используем LEFT JOIN для получения subject из таблицы certs
    // LEFT JOIN позволяет получить данные даже если сертификат уже удален из certs
    QSqlQuery query = m_database->select
    (
        "SELECT r.serial, r.reason, r.revoked_at, c.subject "
        "FROM revoked r "
        "LEFT JOIN certs c ON r.serial = c.serial "
        "WHERE r.revoked_at < ?",  // revoked_at меньше порога удаления
        QVariantList() << static_cast<qlonglong>(deleteThreshold)
    );
    
    // Счетчик удаленных сертификатов
    int deletedCount = 0;
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: УДАЛЕНИЕ КАЖДОГО НАЙДЕННОГО СЕРТИФИКАТА
    // ========================================================================
    // Перебираем все найденные старые отозванные сертификаты
    while (query.next()) 
    {
        // Получаем запись из запроса
        QSqlRecord record = query.record();
        // Получаем серийный номер сертификата
        long serial = record.value("serial").toLongLong();
        // Получаем subject сертификата
        QString subject = record.value("subject").toString();
        
        qDebug() << "CertificateWorker: Удаление старого отозванного сертификата. Serial:" << serial 
                 << "Subject:" << subject;
        
        // ========================================================================
        // ИЗВЛЕЧЕНИЕ CN ИЗ SUBJECT
        // ========================================================================
        // Извлекаем CN из subject для удаления из cert_pem
        // CN необходим для поиска и удаления записи в таблице cert_pem
        QString cn = subject;
        
        // Парсим различные форматы subject для извлечения CN
        if (cn.startsWith("/CN=")) 
        {
            // Формат с начальным слэшем: "/CN=example.com"
            cn = cn.mid(4);           // Убираем "/CN="
        } 
        // Проверяем формат без начального слэша "CN="
        else if (cn.contains("CN=")) 
        {
            // Формат без начального слэша: "CN=example.com" или "CN=example.com/O=Org"
            int cnPos = cn.indexOf("CN=");
            cn = cn.mid(cnPos + 3);   // Убираем "CN="
            
            // Убираем возможные суффиксы после CN
            int slashPos = cn.indexOf("/");
            if (slashPos >= 0) 
            {
                cn = cn.left(slashPos);      // Оставляем только CN
            }
        }
        
        // ========================================================================
        // УДАЛЕНИЕ ИЗ ТАБЛИЦЫ REVOKED
        // ========================================================================
        // Удаляем из таблицы revoked (основная таблица отозванных сертификатов)
        QVariantList deleteParams;
        deleteParams << static_cast<qlonglong>(serial);
        
        // Удаляем из таблицы revoked
        if (m_database->exec("DELETE FROM revoked WHERE serial = ?", deleteParams)) 
        {
            deletedCount++; // Увеличиваем счетчик успешно удаленных сертификатов
            qDebug() << "CertificateWorker: Отозванный сертификат удален из базы данных. Serial:" << serial;
        } 
        // Если удаление не удалось, выводим ошибку
        else 
        {
            qWarning() << "CertificateWorker: Ошибка при удалении отозванного сертификата. Serial:" << serial;
        }
        
        // ========================================================================
        // УДАЛЕНИЕ ИЗ ТАБЛИЦЫ CERTS
        // ========================================================================
        // Также удаляем из таблицы certs, если он там есть
        // Это очистка остаточных данных о сертификате
        // Используем тот же deleteParams (serial)
        m_database->exec("DELETE FROM certs WHERE serial = ?", deleteParams);
        
        // ========================================================================
        // УДАЛЕНИЕ ИЗ ТАБЛИЦЫ CERT_PEM
        // ========================================================================
        // Удаляем из таблицы cert_pem, если есть CN
        // cert_pem хранит PEM-кодированные сертификаты по CN
        if (!cn.isEmpty()) 
        {
            QVariantList deleteCertPemParams;
            deleteCertPemParams << cn;
            m_database->exec("DELETE FROM cert_pem WHERE cn = ?", deleteCertPemParams);
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ВЫВОД СТАТИСТИКИ
    // ========================================================================
    if (deletedCount > 0) 
    {
        qDebug() << "CertificateWorker: Удалено старых отозванных сертификатов:" << deletedCount;
    }
}


// ============================================================================
// МЕТОД generateCrl - ГЕНЕРАЦИЯ CRL (CERTIFICATE REVOCATION LIST)
// ============================================================================
// Генерирует список отозванных сертификатов (CRL) на основе данных из базы.
// Использует внешний процесс minica для генерации CRL.
//
// АЛГОРИТМ:
// 1. Проверка подключения к базе данных
// 2. Получение корневой директории проекта
// 3. Поиск исполняемого файла minica
// 4. Формирование аргументов для команды minica gen-crl
// 5. Запуск процесса генерации CRL
// 6. Проверка результата генерации
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет
//
// ПРИМЕЧАНИЕ:
//   CRL будет сохранен в ca/crl.pem и доступен через HTTP endpoint GET /crl
//   CRL действителен 7 дней
//   Вызывается периодически в основном цикле рабочего потока (каждые 5 сканирований)
//   и после каждого отзыва сертификата
// ============================================================================
void CertificateWorker::generateCrl()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА ПОДКЛЮЧЕНИЯ К БАЗЕ ДАННЫХ
    // ========================================================================
    // Проверяем, что база данных подключена
    if (!m_database || !m_database->isConnected()) 
    {
        qWarning() << "CertificateWorker: База данных не подключена, невозможно сгенерировать CRL";
        return;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПОЛУЧЕНИЕ КОРНЕВОЙ ДИРЕКТОРИИ
    // ========================================================================
    QString rootDir = getRootDir();
    // Проверяем, что корневая директория определена
    if (rootDir.isEmpty()) 
    {
        qWarning() << "CertificateWorker: Не удалось определить корневую директорию для генерации CRL";
        return;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПОИСК ИСПОЛНЯЕМОГО ФАЙЛА MINICA
    // ========================================================================
    // Генерируем CRL через minica gen-crl
    // CRL будет сохранен в ca/crl.pem и доступен через HTTP endpoint GET /crl
    // CRL содержит список всех отозванных сертификатов из таблицы revoked
    QProcess crlProcess;
    
    // ========================================================================
    // ПОИСК ИСПОЛНЯЕМОГО ФАЙЛА MINICA
    // ========================================================================
    // Ищем путь к исполняемому файлу minica
    // Сначала проверяем в директории приложения
    QString minicaPath = QCoreApplication::applicationDirPath() + "/minica";
    if (!QFileInfo::exists(minicaPath)) 
    {
        // Если не найден, пытаемся найти в build директории (на уровень выше)
        minicaPath = QCoreApplication::applicationDirPath() + "/../minica";
    }
    
    // Проверяем, что minica найден
    if (!QFileInfo::exists(minicaPath)) 
    {
        qWarning() << "CertificateWorker: minica не найден для генерации CRL";
        return;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ФОРМИРОВАНИЕ АРГУМЕНТОВ ДЛЯ КОМАНДЫ MINICA GEN-CRL
    // ========================================================================
    // Формируем аргументы для команды minica gen-crl
    // Команда: minica gen-crl <rootDir> <crlPath> <validityDays>
    QStringList arguments;
    arguments << "gen-crl"                          // команда генерации CRL (Certificate Revocation List)
              << rootDir                            // корневая директория проекта (для доступа к CA ключам)
              << (rootDir + "/ca/crl.pem")          // путь для сохранения CRL (ca/crl.pem)
              << "7";                               // срок действия CRL (7 дней)
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: ЗАПУСК ПРОЦЕССА ГЕНЕРАЦИИ CRL
    // ========================================================================
    // Запускаем процесс minica gen-crl
    // Процесс прочитает все отозванные сертификаты из таблицы revoked через CaDatabase
    // и создаст подписанный CRL файл
    crlProcess.start(minicaPath, arguments);
    
    // Ждем завершения процесса (до 10 секунд)
    // Генерация CRL обычно занимает меньше времени, чем обновление сертификата
    if (!crlProcess.waitForFinished(10000)) 
    {
        qWarning() << "CertificateWorker: Процесс генерации CRL не завершился вовремя";
        return;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ПРОВЕРКА РЕЗУЛЬТАТА ГЕНЕРАЦИИ
    // ========================================================================
    if (crlProcess.exitCode() == 0) 
    {
        // Процесс завершился успешно (код возврата 0)
        qDebug() << "CertificateWorker: CRL успешно сгенерирован";
    } 
    else 
    {
        // Процесс завершился с ошибкой
        QString errorOutput = crlProcess.readAllStandardError();
        qWarning() << "CertificateWorker: Ошибка при генерации CRL:" << errorOutput;
    }
}