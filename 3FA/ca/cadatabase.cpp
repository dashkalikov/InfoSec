// ============================================================================
// МЕТОД executeQuery - ВНУТРЕННЕЕ ВЫПОЛНЕНИЕ ЗАПРОСА
// ============================================================================
// Внутренний метод для выполнения SQL запроса с параметрами.
// Используется методами exec() и select() для единообразной обработки запросов.
//
// АЛГОРИТМ:
// 1. Подготовка запроса с параметрами
// 2. Привязка параметров к запросу
// 3. Выполнение запроса
// 4. Обработка ошибок при неудаче
//
// ПАРАМЕТРЫ:
//   query - SQL запрос для выполнения (QString)
//   params - список параметров для подстановки в запрос (QVariantList)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - запрос выполнен успешно
//   false - ошибка выполнения
// ============================================================================
bool CaDatabase::executeQuery(const QString &query,
                              const QVariantList &params)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПОДГОТОВКА ЗАПРОСА С ПАРАМЕТРАМИ
    // ========================================================================
    // Подготавливаем запрос для безопасного выполнения с параметрами
    QSqlQuery sqlQuery = prepareQuery(query);
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПРИВЯЗКА ПАРАМЕТРОВ К ЗАПРОСУ
    // ========================================================================
    // Привязываем параметры к запросу
    // Параметры в запросе обозначаются как ? (плейсхолдеры)
    // bindValue(i, params[i]) заменяет i-й плейсхолдер на значение из params
    for (int i = 0; i < params.size(); ++i) 
    {
        sqlQuery.bindValue(i, params[i]);
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ВЫПОЛНЕНИЕ ЗАПРОСА И ОБРАБОТКА ОШИБОК
    // ========================================================================
    // Выполняем запрос
    if (!sqlQuery.exec()) 
    {
        // Сохраняем описание ошибки и отправляем сигнал
        m_lastError = sqlQuery.lastError().text();
        emit errorOccurred(m_lastError);
        return false;
    }
    
    return true;
}


// ============================================================================
// МЕТОД prepareQuery - ПОДГОТОВКА ЗАПРОСА С ПАРАМЕТРАМИ
// ============================================================================
// Подготавливает SQL запрос с параметрами для безопасного выполнения.
// Заменяет плейсхолдеры (?) на значения из списка параметров.
//
// ПАРАМЕТРЫ:
//   query - SQL запрос с плейсхолдерами (QString)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   QSqlQuery - подготовленный запрос (требует привязки параметров через bindValue)
//
// ПРИМЕЧАНИЕ:
//   Используется внутренними методами для подготовки запросов
// ============================================================================
QSqlQuery CaDatabase::prepareQuery(const QString &query)
{
    // Создаем объект запроса, привязанный к нашему соединению
    QSqlQuery sqlQuery(m_database);
    // Подготавливаем запрос для выполнения с параметрами
    // prepare() анализирует запрос и готовит его к выполнению
    sqlQuery.prepare(query);
    return sqlQuery;
}


// ============================================================================
// МЕТОД exec - ВЫПОЛНЕНИЕ ЗАПРОСА (INSERT/UPDATE/DELETE)
// ============================================================================
// Выполняет SQL запрос, который не возвращает данные (INSERT, UPDATE, DELETE).
// Поддерживает параметризованные запросы для защиты от SQL инъекций.
//
// АЛГОРИТМ:
// 1. Проверка состояния соединения (healthCheck)
// 2. Переподключение при необходимости (reconnect)
// 3. Выполнение запроса через executeQuery
//
// ПАРАМЕТРЫ:
//   query - SQL запрос для выполнения (QString)
//   params - список параметров для подстановки в запрос (QVariantList)
//           По умолчанию: пустой список
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - запрос выполнен успешно
//   false - ошибка выполнения (проверьте getLastError())
// ============================================================================
bool CaDatabase::exec(const QString &query,
                      const QVariantList &params)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА СОСТОЯНИЯ СОЕДИНЕНИЯ
    // ========================================================================
    // Автоматическая проверка соединения и переподключение при необходимости
    // healthCheck() выполняет простой запрос для проверки работоспособности
    if (!healthCheck()) 
    {
        // Соединение не работает, пытаемся переподключиться
        if (!reconnect()) 
        {
            // Переподключение не удалось
            return false;
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВЫПОЛНЕНИЕ ЗАПРОСА
    // ========================================================================
    // Выполняем запрос через внутренний метод executeQuery
    return executeQuery(query, params);
}


// ============================================================================
// МЕТОД select - ВЫПОЛНЕНИЕ SELECT ЗАПРОСА
// ============================================================================
// Выполняет SELECT запрос и возвращает объект QSqlQuery с результатами.
// Поддерживает параметризованные запросы для защиты от SQL инъекций.
//
// АЛГОРИТМ:
// 1. Проверка состояния соединения (healthCheck)
// 2. Переподключение при необходимости (reconnect)
// 3. Подготовка запроса с параметрами
// 4. Привязка параметров к запросу
// 5. Выполнение запроса
// 6. Обработка ошибок при неудаче
//
// ПАРАМЕТРЫ:
//   query - SQL SELECT запрос (QString)
//   params - список параметров для подстановки в запрос (QVariantList)
//           По умолчанию: пустой список
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   QSqlQuery - объект с результатами запроса (готов к использованию)
//              Используйте next() для перебора строк, value() для получения значений
//              При ошибке возвращается пустой QSqlQuery
// ============================================================================
QSqlQuery CaDatabase::select(const QString &query,
                             const QVariantList &params)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА СОСТОЯНИЯ СОЕДИНЕНИЯ
    // ========================================================================
    // Автоматическая проверка соединения и переподключение при необходимости
    // healthCheck() выполняет простой запрос для проверки работоспособности
    if (!healthCheck()) 
    {
        // Соединение не работает, пытаемся переподключиться
        if (!reconnect()) 
        {
            // Переподключение не удалось, возвращаем пустой запрос
            return QSqlQuery(m_database);
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПОДГОТОВКА ЗАПРОСА С ПАРАМЕТРАМИ
    // ========================================================================
    // Подготавливаем запрос для безопасного выполнения с параметрами
    QSqlQuery sqlQuery = prepareQuery(query);
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПРИВЯЗКА ПАРАМЕТРОВ К ЗАПРОСУ
    // ========================================================================
    // Привязываем параметры к запросу
    // Параметры в запросе обозначаются как ? (плейсхолдеры)
    for (int i = 0; i < params.size(); ++i) 
    {
        sqlQuery.bindValue(i, params[i]);
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: ВЫПОЛНЕНИЕ ЗАПРОСА И ОБРАБОТКА ОШИБОК
    // ========================================================================
    // Выполняем запрос
    if (!sqlQuery.exec()) 
    {
        // Сохраняем описание ошибки и отправляем сигнал
        m_lastError = sqlQuery.lastError().text();
        emit errorOccurred(m_lastError);
        // Возвращаем пустой QSqlQuery при ошибке
        return QSqlQuery(m_database);
    }
    
    // Возвращаем объект запроса с результатами
    // Используйте next() для перебора строк, value() для получения значений
    return sqlQuery;
}


// ============================================================================
// МЕТОД beginTransaction - НАЧАЛО ТРАНЗАКЦИИ
// ============================================================================
// Начинает транзакцию для группировки нескольких SQL операций.
// Все операции между beginTransaction() и commit()/rollback() выполняются
// атомарно (либо все успешно, либо все откатываются).
//
// АЛГОРИТМ:
// 1. Проверка состояния соединения (healthCheck)
// 2. Переподключение при необходимости (reconnect)
// 3. Выполнение команды BEGIN TRANSACTION
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - транзакция успешно начата
//   false - ошибка начала транзакции (проверьте getLastError())
//
// ПРИМЕЧАНИЕ:
//   Не забудьте вызвать commit() или rollback() после beginTransaction()
// ============================================================================
bool CaDatabase::beginTransaction()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА СОСТОЯНИЯ СОЕДИНЕНИЯ
    // ========================================================================
    // Проверяем работоспособность соединения перед началом транзакции
    if (!healthCheck()) 
    {
        // Соединение не работает, пытаемся переподключиться
        if (!reconnect()) 
        {
            // Переподключение не удалось
            return false;
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: НАЧАЛО ТРАНЗАКЦИИ
    // ========================================================================
    // Выполняем команду BEGIN TRANSACTION для начала транзакции
    // Все последующие операции будут выполняться в рамках этой транзакции
    QSqlQuery query(m_database);
    if (!query.exec("BEGIN TRANSACTION")) 
    {
        m_lastError = QString("Не удалось начать транзакцию: %1").arg(query.lastError().text());
        emit errorOccurred(m_lastError);
        return false;
    }

    return true;
}


// ============================================================================
// МЕТОД commit - ПОДТВЕРЖДЕНИЕ ТРАНЗАКЦИИ
// ============================================================================
// Подтверждает транзакцию, сохраняя все изменения в базе данных.
// Все операции, выполненные после beginTransaction(), становятся постоянными.
//
// АЛГОРИТМ:
// 1. Проверка наличия активного соединения
// 2. Выполнение команды COMMIT
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - транзакция успешно подтверждена
//   false - ошибка подтверждения (проверьте getLastError())
//
// ПРИМЕЧАНИЕ:
//   Вызывайте только после успешного beginTransaction()
// ============================================================================
bool CaDatabase::commit()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА НАЛИЧИЯ АКТИВНОГО СОЕДИНЕНИЯ
    // ========================================================================
    // Проверяем, что соединение установлено и открыто
    if (!isConnected()) 
    {
        m_lastError = "Соединение с базой данных не установлено";
        emit errorOccurred(m_lastError);
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПОДТВЕРЖДЕНИЕ ТРАНЗАКЦИИ
    // ========================================================================
    // Выполняем команду COMMIT для подтверждения транзакции
    // Все изменения, сделанные после beginTransaction(), сохраняются в БД
    QSqlQuery query(m_database);
    if (!query.exec("COMMIT")) 
    {
        m_lastError = QString("Не удалось подтвердить транзакцию: %1").arg(query.lastError().text());
        emit errorOccurred(m_lastError);
        return false;
    }

    return true;
}


// ============================================================================
// МЕТОД rollback - ОТКАТ ТРАНЗАКЦИИ
// ============================================================================
// Откатывает транзакцию, отменяя все изменения, сделанные после beginTransaction().
// База данных возвращается в состояние до начала транзакции.
//
// АЛГОРИТМ:
// 1. Проверка наличия активного соединения
// 2. Выполнение команды ROLLBACK
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - транзакция успешно откачена
//   false - ошибка отката (проверьте getLastError())
//
// ПРИМЕЧАНИЕ:
//   Вызывайте при ошибках или необходимости отменить изменения
// ============================================================================
bool CaDatabase::rollback()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА НАЛИЧИЯ АКТИВНОГО СОЕДИНЕНИЯ
    // ========================================================================
    // Проверяем, что соединение установлено и открыто
    if (!isConnected()) 
    {
        m_lastError = "Соединение с базой данных не установлено";
        emit errorOccurred(m_lastError);
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ОТКАТ ТРАНЗАКЦИИ
    // ========================================================================
    // Выполняем команду ROLLBACK для отката транзакции
    // Все изменения, сделанные после beginTransaction(), отменяются
    QSqlQuery query(m_database);
    if (!query.exec("ROLLBACK")) 
    {
        m_lastError = QString("Не удалось откатить транзакцию: %1").arg(query.lastError().text());
        emit errorOccurred(m_lastError);
        return false;
    }

    return true;
}


// ============================================================================
// МЕТОД execInTransaction - ВЫПОЛНЕНИЕ ЗАПРОСА В ТРАНЗАКЦИИ
// ============================================================================
// Выполняет SQL запрос в транзакции с автоматическим откатом при ошибке.
// Упрощает работу с транзакциями, автоматически управляя commit/rollback.
//
// АЛГОРИТМ:
// 1. Начало транзакции (beginTransaction)
// 2. Выполнение запроса (exec)
// 3. При успехе - подтверждение (commit)
// 4. При ошибке - откат (rollback)
//
// ПАРАМЕТРЫ:
//   query - SQL запрос для выполнения (QString)
//   params - список параметров для подстановки в запрос (QVariantList)
//           По умолчанию: пустой список
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - запрос выполнен успешно, транзакция подтверждена
//   false - ошибка выполнения, транзакция откачена
// ============================================================================
bool CaDatabase::execInTransaction(const QString &query,
                                   const QVariantList &params)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: НАЧАЛО ТРАНЗАКЦИИ
    // ========================================================================
    // Начинаем транзакцию для атомарного выполнения запроса
    if (!beginTransaction()) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВЫПОЛНЕНИЕ ЗАПРОСА
    // ========================================================================
    // Выполняем запрос в рамках транзакции
    if (!exec(query, params)) 
    {
        // Запрос не выполнен - откатываем транзакцию
        rollback(); // Автоматический откат при ошибке
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПОДТВЕРЖДЕНИЕ ТРАНЗАКЦИИ
    // ========================================================================
    // Запрос выполнен успешно - подтверждаем транзакцию
    if (!commit()) 
    {
        // Подтверждение не удалось - откатываем транзакцию
        rollback(); // Откат, если commit не удался
        return false;
    }
    
    return true;
}
