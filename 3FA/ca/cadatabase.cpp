#include "cadatabase.h"              // заголовочный файл класса
#include <QDebug>                    // класс для отладочного вывода (qDebug())
#include <QCoreApplication>          // базовый класс приложения Qt
#include <QFileInfo>                 // класс для получения информации о файлах (существование, размер, путь)

// ============================================================================
// КОНСТРУКТОР CaDatabase
// ============================================================================
// Создает экземпляр класса для работы с базой данных сертификатов.
// Инициализирует уникальное имя соединения для избежания конфликтов.
//
// АЛГОРИТМ:
// 1. Инициализация базового класса QObject
// 2. Генерация уникального имени соединения на основе указателя this
// 3. Удаление старого соединения с таким же именем (если существует)
//
// ПАРАМЕТРЫ:
//   parent - родительский объект для управления памятью (QObject*)
// ============================================================================
CaDatabase::CaDatabase(QObject *parent)
    : QObject(parent)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ГЕНЕРАЦИЯ УНИКАЛЬНОГО ИМЕНИ СОЕДИНЕНИЯ
    // ========================================================================
    // Уникальное имя соединения для CaDatabase
    // Используем указатель this для создания уникального имени, чтобы избежать конфликтов
    // если будет несколько экземпляров CaDatabase или других QSqlDatabase соединений.
    // reinterpret_cast<quintptr>(this) преобразует указатель в число для использования в строке
    m_connectionName = QString("CaDatabaseConnection_%1").arg(reinterpret_cast<quintptr>(this));
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: УДАЛЕНИЕ СТАРОГО СОЕДИНЕНИЯ
    // ========================================================================
    // Удаляем старое соединение, если оно существует, чтобы избежать ошибок
    // при повторном использовании того же имени соединения
    if (QSqlDatabase::contains(m_connectionName)) 
    {
        QSqlDatabase::removeDatabase(m_connectionName);
    }
}


// ============================================================================
// ДЕСТРУКТОР ~CaDatabase
// ============================================================================
// Закрывает соединение с базой данных при уничтожении объекта.
// Автоматически вызывается при удалении объекта.
//
// АЛГОРИТМ:
// 1. Вызов disconnect() для закрытия соединения и освобождения ресурсов
// ============================================================================
CaDatabase::~CaDatabase()
{
    // Закрываем соединение с базой данных и освобождаем ресурсы
    disconnect();
}


// ============================================================================
// МЕТОД connect - ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ
// ============================================================================
// Открывает соединение с SQLite базой данных. Создает директорию для базы
// данных, если она не существует. Генерирует уникальное имя соединения.
//
// АЛГОРИТМ:
// 1. Проверка доступности драйвера SQLite
// 2. Создание объекта подключения с уникальным именем
// 3. Определение абсолютного пути к базе данных
// 4. Создание директории для базы данных (если не существует)
// 5. Установка имени базы данных и открытие соединения
// 6. Инициализация таблиц базы данных
//
// ПАРАМЕТРЫ:
//   databasePath - путь к файлу базы данных (QString)
//                 По умолчанию: "databases/ca.db"
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - соединение успешно установлено
//   false - ошибка подключения (проверьте getLastError())
// ============================================================================
bool CaDatabase::connect(const QString &databasePath)
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА ДОСТУПНОСТИ ДРАЙВЕРА SQLITE
    // ========================================================================
    // Проверяем доступность драйвера SQLite
    // QSQLITE - встроенный драйвер Qt для работы с SQLite базами данных
    if (!QSqlDatabase::isDriverAvailable("QSQLITE")) 
    {
        m_lastError = "Драйвер SQLite (QSQLITE) недоступен. Убедитесь, что Qt собран с поддержкой SQLite.";
        emit errorOccurred(m_lastError);
        qCritical() << m_lastError;
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: СОЗДАНИЕ ОБЪЕКТА ПОДКЛЮЧЕНИЯ
    // ========================================================================
    // Используем SQLite драйвер с уникальным именем соединения
    // addDatabase() создает новое подключение с указанным именем
    // Если соединение с таким именем уже существует, оно будет переиспользовано
    m_database = QSqlDatabase::addDatabase("QSQLITE", m_connectionName);
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ОПРЕДЕЛЕНИЕ АБСОЛЮТНОГО ПУТИ К БАЗЕ ДАННЫХ
    // ========================================================================
    // Определяем путь к базе данных так, чтобы использовать файл из папки
    // databases в корне проекта. Обрабатываем относительные пути и разные
    // сценарии запуска (обычный бинарь, macOS bundle).
    QString dbPath = databasePath;
    
    // Если путь относительный, преобразуем его в абсолютный
    if (QDir::isRelativePath(dbPath)) 
    {
        // Получаем директорию, из которой запущено приложение
        QString appDir = QCoreApplication::applicationDirPath();
        QDir baseDir(appDir);
        
        // ========================================================================
        // ОБРАБОТКА: MACOS BUNDLE
        // ========================================================================
        // macOS bundle: <project>/build/3FA.app/Contents/MacOS
        // Нужно подняться на 4 уровня вверх до корня проекта
        if (appDir.contains("/Contents/MacOS")) 
        {
            // Поднимаемся до корня проекта: ../../../../ от Contents/MacOS
            baseDir = QDir(baseDir.absoluteFilePath("../../../../"));
        } 
        
        else 
        {
            // ========================================================================
            // ОБРАБОТКА: ОБЫЧНЫЙ БИНАРЬ
            // ========================================================================
            // Обычный случай: бинарь в build/ → поднимаемся на один уровень
            // к корню проекта, если виден CMakeLists.txt
            QDir tryBuildParent(baseDir.absoluteFilePath(".."));
            if (tryBuildParent.exists("CMakeLists.txt")) 
            {
                // Если CMakeLists.txt найден на уровень выше, это корень проекта
                baseDir = tryBuildParent;
            }
            // Иначе используем текущую директорию приложения
        }
        
        // Формируем абсолютный путь к базе данных
        dbPath = baseDir.absoluteFilePath(databasePath);
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: СОЗДАНИЕ ДИРЕКТОРИИ ДЛЯ БАЗЫ ДАННЫХ
    // ========================================================================
    // Создаем папку databases, если её нет
    // Это необходимо, так как SQLite не создает директории автоматически
    QFileInfo dbFileInfo(dbPath);
    QDir dbDir = dbFileInfo.absoluteDir();
    
    if (!dbDir.exists()) 
    {
        // mkpath(".") создает все необходимые директории в пути
        // Возвращает true при успехе, false при ошибке
        if (!dbDir.mkpath(".")) 
        {
            m_lastError = QString("Не удалось создать папку для базы данных: %1").arg(dbDir.absolutePath());
            emit errorOccurred(m_lastError);
            qCritical() << m_lastError;
            return false;
        }
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: УСТАНОВКА ИМЕНИ БАЗЫ ДАННЫХ И ОТКРЫТИЕ СОЕДИНЕНИЯ
    // ========================================================================
    // Устанавливаем имя файла базы данных
    m_database.setDatabaseName(dbPath);
    // Сохраняем путь для переподключения
    m_databasePath = dbPath;
    
    qDebug() << "Подключение к CA SQLite:";
    qDebug() << "  База данных:" << dbPath;
    
    // Открываем соединение с базой данных
    // open() создает файл базы данных, если его еще нет
    if (!m_database.open()) 
    {
        m_lastError = QString("Не удалось подключиться к SQLite: %1").arg(m_database.lastError().text());
        emit errorOccurred(m_lastError);
        return false;
    }
    
    qDebug() << "База данных CA SQLite подключена успешно";
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: ИНИЦИАЛИЗАЦИЯ ТАБЛИЦ БАЗЫ ДАННЫХ
    // ========================================================================
    // Создаем все необходимые таблицы, если они еще не существуют
    // initializeTables() также создает индексы для оптимизации запросов
    return initializeTables();
}


// ============================================================================
// МЕТОД disconnect - ОТКЛЮЧЕНИЕ ОТ БАЗЫ ДАННЫХ
// ============================================================================
// Закрывает соединение с базой данных. Освобождает ресурсы и очищает
// имя соединения. Не выбрасывает исключений, безопасно вызывать даже
// если соединение уже закрыто.
//
// АЛГОРИТМ:
// 1. Закрытие соединения, если оно открыто
// 2. Удаление соединения из пула Qt (только если оно закрыто)
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   Нет
// ============================================================================
void CaDatabase::disconnect()
{
    if (!QSqlDatabase::contains(m_connectionName)) 
    {
        return;
    }
    
    if (m_database.isValid() && m_database.isOpen()) 
    {
        m_database.close();
        qDebug() << "База данных CA отключена";
    }

    // Освобождаем ссылку m_database на соединение, чтобы removeDatabase
    // не считал, что подключение еще кем‑то используется
    m_database = QSqlDatabase();

    // К этому моменту ни одного живого QSqlDatabase с таким connectionName нет
    QSqlDatabase::removeDatabase(m_connectionName);
}


// ============================================================================
// МЕТОД isConnected - ПРОВЕРКА ПОДКЛЮЧЕНИЯ
// ============================================================================
// Проверяет, установлено ли активное соединение с базой данных.
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - соединение активно
//   false - соединение не установлено или закрыто
// ============================================================================
bool CaDatabase::isConnected() const
{
    // Проверяем, открыто ли соединение с базой данных
    return m_database.isOpen();
}


// ============================================================================
// МЕТОД reconnect - ПЕРЕПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ
// ============================================================================
// Переподключается к базе данных, используя сохраненный путь.
// Полезно при потере соединения или необходимости обновить подключение.
//
// АЛГОРИТМ:
// 1. Отключение от текущего соединения (если есть)
// 2. Проверка наличия сохраненного пути к базе данных
// 3. Подключение к базе данных по сохраненному пути
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - переподключение успешно
//   false - ошибка переподключения (проверьте getLastError())
// ============================================================================
bool CaDatabase::reconnect()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ОТКЛЮЧЕНИЕ ОТ ТЕКУЩЕГО СОЕДИНЕНИЯ
    // ========================================================================
    // Закрываем текущее соединение, если оно открыто
    disconnect();
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ПРОВЕРКА НАЛИЧИЯ СОХРАНЕННОГО ПУТИ
    // ========================================================================
    // Проверяем, что путь к базе данных был сохранен при предыдущем подключении
    if (m_databasePath.isEmpty()) 
    {
        m_lastError = "Путь к базе данных не сохранен. Используйте connect() для первоначального подключения.";
        emit errorOccurred(m_lastError);
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ
    // ========================================================================
    // Подключаемся к базе данных по сохраненному пути
    return connect(m_databasePath);
}


// ============================================================================
// МЕТОД healthCheck - ПРОВЕРКА СОСТОЯНИЯ СОЕДИНЕНИЯ
// ============================================================================
// Выполняет простой SQL запрос для проверки работоспособности соединения.
// Используется для диагностики проблем с подключением.
//
// АЛГОРИТМ:
// 1. Проверка наличия активного соединения
// 2. Выполнение простого запроса (SELECT 1)
// 3. Проверка успешности выполнения и наличия результата
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - соединение работает корректно
//   false - соединение не работает или недоступно
//
// ПРИМЕЧАНИЕ:
//   Не использует select() для избежания рекурсии (select() вызывает healthCheck())
// ============================================================================
bool CaDatabase::healthCheck()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: ПРОВЕРКА НАЛИЧИЯ АКТИВНОГО СОЕДИНЕНИЯ
    // ========================================================================
    // Проверяем, что соединение установлено и открыто
    if (!isConnected()) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: ВЫПОЛНЕНИЕ ПРОСТОГО ЗАПРОСА
    // ========================================================================
    // Выполняем простой запрос для проверки соединения
    // SELECT 1 - минимальный запрос, который всегда возвращает одну строку с значением 1
    // Не используем select() для избежания рекурсии (select() вызывает healthCheck())
    QSqlQuery query(m_database);
    if (!query.exec("SELECT 1")) 
    {
        // Запрос не выполнен - соединение не работает
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: ПРОВЕРКА НАЛИЧИЯ РЕЗУЛЬТАТА
    // ========================================================================
    // Проверяем, что запрос вернул результат
    // next() перемещает курсор на первую строку результата
    return query.next();
}


// ============================================================================
// МЕТОД initializeTables - СОЗДАНИЕ ТАБЛИЦ БАЗЫ ДАННЫХ
// ============================================================================
// Создает все необходимые таблицы в базе данных, если они еще не существуют.
// Определяет структуру базы данных для хранения сертификатов и операций.
//
// АЛГОРИТМ:
// 1. Создание таблицы certs (сертификаты)
// 2. Создание таблицы revoked (отозванные сертификаты)
// 3. Создание таблицы keys (зашифрованные ключи)
// 4. Создание таблицы master_keys (мастер-ключ)
// 5. Создание таблицы cert_pem (сертификаты в формате PEM)
// 6. Создание таблицы csr_pem (запросы на сертификаты в формате PEM)
// 7. Создание таблицы root_cert (корневой сертификат)
// 8. Миграция: добавление колонки checksum в root_cert (если нужно)
// 9. Создание таблицы audit_log (журнал аудита)
// 10. Создание таблицы serial_number (счетчик серийных номеров)
// 11. Создание индексов для оптимизации запросов
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   true - таблицы успешно созданы или уже существуют
//   false - ошибка при создании таблиц (проверьте getLastError())
// ============================================================================
bool CaDatabase::initializeTables()
{
    // ========================================================================
    // ДЕЙСТВИЕ 1: СОЗДАНИЕ ТАБЛИЦЫ CERTS (СЕРТИФИКАТЫ)
    // ========================================================================
    // Таблица для хранения информации о сертификатах:
    // - serial: серийный номер (PRIMARY KEY)
    // - subject: субъект сертификата (например, CN=example.com)
    // - not_before: дата начала действия (Unix timestamp)
    // - not_after: дата окончания действия (Unix timestamp)
    // - status: статус сертификата (active, expired, revoked)
    QString createCertsTable = R"(
        CREATE TABLE IF NOT EXISTS certs(
            serial INTEGER PRIMARY KEY, 
            subject TEXT, 
            not_before INTEGER, 
            not_after INTEGER, 
            status TEXT
        )
    )";
    
    if (!exec(createCertsTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 2: СОЗДАНИЕ ТАБЛИЦЫ REVOKED (ОТОЗВАННЫЕ СЕРТИФИКАТЫ)
    // ========================================================================
    // Таблица для хранения информации об отозванных сертификатах:
    // - serial: серийный номер отозванного сертификата (PRIMARY KEY)
    // - reason: причина отзыва (например, "key compromise", "superseded")
    // - revoked_at: дата отзыва (Unix timestamp)
    QString createRevokedTable = R"(
        CREATE TABLE IF NOT EXISTS revoked(
            serial INTEGER PRIMARY KEY, 
            reason TEXT, 
            revoked_at INTEGER
        )
    )";
    
    if (!exec(createRevokedTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 3: СОЗДАНИЕ ТАБЛИЦЫ KEYS (ЗАШИФРОВАННЫЕ КЛЮЧИ)
    // ========================================================================
    // Таблица для хранения зашифрованных приватных ключей:
    // - cn: Common Name (PRIMARY KEY) - идентификатор ключа
    // - key_type: тип ключа (например, "RSA", "EC")
    // - encrypted_key: зашифрованный приватный ключ (BLOB)
    // - iv: вектор инициализации для шифрования (BLOB)
    // - tag: тег аутентификации для проверки целостности (BLOB)
    QString createKeysTable = R"(
        CREATE TABLE IF NOT EXISTS keys(
            cn TEXT PRIMARY KEY, 
            key_type TEXT, 
            encrypted_key BLOB, 
            iv BLOB, 
            tag BLOB
        )
    )";
    
    if (!exec(createKeysTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 4: СОЗДАНИЕ ТАБЛИЦЫ MASTER_KEYS (МАСТЕР-КЛЮЧ)
    // ========================================================================
    // Таблица для хранения мастер-ключа, используемого для шифрования приватных ключей:
    // - id: идентификатор (PRIMARY KEY, CHECK(id=1)) - только одна запись
    // - master_key: зашифрованный мастер-ключ (BLOB)
    // CHECK(id=1) гарантирует, что в таблице может быть только одна запись
    QString createMasterKeysTable = R"(
        CREATE TABLE IF NOT EXISTS master_keys(
            id INTEGER PRIMARY KEY CHECK(id=1), 
            master_key BLOB
        )
    )";
    
    if (!exec(createMasterKeysTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 5: СОЗДАНИЕ ТАБЛИЦЫ CERT_PEM (СЕРТИФИКАТЫ В ФОРМАТЕ PEM)
    // ========================================================================
    // Таблица для хранения сертификатов в текстовом формате PEM:
    // - cn: Common Name (PRIMARY KEY) - идентификатор сертификата
    // - cert_pem: сертификат в формате PEM (текстовая строка)
    QString createCertPemTable = R"(
        CREATE TABLE IF NOT EXISTS cert_pem(
            cn TEXT PRIMARY KEY, 
            cert_pem TEXT
        )
    )";
    
    if (!exec(createCertPemTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 6: СОЗДАНИЕ ТАБЛИЦЫ CSR_PEM (ЗАПРОСЫ НА СЕРТИФИКАТЫ)
    // ========================================================================
    // Таблица для хранения запросов на сертификаты (Certificate Signing Request) в формате PEM:
    // - cn: Common Name (PRIMARY KEY) - идентификатор запроса
    // - csr_pem: запрос на сертификат в формате PEM (текстовая строка)
    QString createCsrPemTable = R"(
        CREATE TABLE IF NOT EXISTS csr_pem(
            cn TEXT PRIMARY KEY, 
            csr_pem TEXT
        )
    )";
    
    if (!exec(createCsrPemTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 7: СОЗДАНИЕ ТАБЛИЦЫ ROOT_CERT (КОРНЕВОЙ СЕРТИФИКАТ)
    // ========================================================================
    // Таблица для хранения корневого сертификата CA:
    // - id: идентификатор (PRIMARY KEY, CHECK(id=1)) - только одна запись
    // - cert_pem: корневой сертификат в формате PEM (текстовая строка)
    // - checksum: контрольная сумма сертификата для проверки целостности
    QString createRootCertTable = R"(
        CREATE TABLE IF NOT EXISTS root_cert(
            id INTEGER PRIMARY KEY CHECK(id=1), 
            cert_pem TEXT,
            checksum TEXT
        )
    )";
    
    if (!exec(createRootCertTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 8: МИГРАЦИЯ - ДОБАВЛЕНИЕ КОЛОНКИ CHECKSUM
    // ========================================================================
    // Добавляем колонку checksum если таблица уже существует (миграция)
    // Игнорируем ошибку если колонка уже существует (для существующих баз данных)
    QString addChecksumColumn = "ALTER TABLE root_cert ADD COLUMN checksum TEXT";
    exec(addChecksumColumn); // Игнорируем ошибку если колонка уже существует
    
    // ========================================================================
    // ДЕЙСТВИЕ 9: СОЗДАНИЕ ТАБЛИЦЫ AUDIT_LOG (ЖУРНАЛ АУДИТА)
    // ========================================================================
    // Таблица для хранения журнала всех операций с сертификатами:
    // - id: уникальный идентификатор записи (PRIMARY KEY, AUTOINCREMENT)
    // - timestamp: время события (Unix timestamp)
    // - event: тип события (например, "certificate_issued", "certificate_revoked")
    // - detail: детальная информация о событии (текстовая строка)
    QString createAuditLogTable = R"(
        CREATE TABLE IF NOT EXISTS audit_log(
            id INTEGER PRIMARY KEY AUTOINCREMENT, 
            timestamp INTEGER, 
            event TEXT, 
            detail TEXT
        )
    )";
    
    if (!exec(createAuditLogTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 10: СОЗДАНИЕ ТАБЛИЦЫ SERIAL_NUMBER (СЧЕТЧИК СЕРИЙНЫХ НОМЕРОВ)
    // ========================================================================
    // Таблица для хранения следующего серийного номера для новых сертификатов:
    // - id: идентификатор (PRIMARY KEY, CHECK(id=1)) - только одна запись
    // - next_serial: следующий серийный номер для выдачи (DEFAULT 2)
    // DEFAULT 2 означает, что первый сертификат получит серийный номер 2
    // (серийный номер 1 обычно зарезервирован для корневого сертификата)
    QString createSerialNumberTable = R"(
        CREATE TABLE IF NOT EXISTS serial_number(
            id INTEGER PRIMARY KEY CHECK(id=1), 
            next_serial INTEGER DEFAULT 2
        )
    )";
    
    if (!exec(createSerialNumberTable)) 
    {
        return false;
    }
    
    // ========================================================================
    // ДЕЙСТВИЕ 11: СОЗДАНИЕ ИНДЕКСОВ ДЛЯ ОПТИМИЗАЦИИ ЗАПРОСОВ
    // ========================================================================
    // Индексы ускоряют поиск и сортировку данных в таблицах.
    // Создаем индексы для часто используемых полей.
    //
    // ПРИМЕЧАНИЕ:
    // Ошибки создания индексов не критичны - база данных будет работать,
    // но запросы могут выполняться медленнее. Поэтому мы логируем ошибки,
    // но не прерываем инициализацию.
    
    // ========================================================================
    // ИНДЕКС 1: IDX_CERTS_SUBJECT - ПОИСК ПО СУБЪЕКТУ СЕРТИФИКАТА
    // ========================================================================
    // Индекс для поля subject в таблице certs.
    // Ускоряет следующие типы запросов:
    // - SELECT * FROM certs WHERE subject = 'CN=example.com'
    // - SELECT * FROM certs WHERE subject LIKE 'CN=%'
    // - SELECT * FROM certs ORDER BY subject
    //
    // ИСПОЛЬЗОВАНИЕ:
    // Используется при поиске сертификатов по Common Name (CN) или полному
    // Distinguished Name (DN). Критичен для операций:
    // - Поиск сертификата по доменному имени
    // - Проверка существования сертификата для субъекта
    // - Получение списка сертификатов, отсортированных по субъекту
    QString createSubjectIndex = "CREATE INDEX IF NOT EXISTS idx_certs_subject ON certs(subject)";
    if (!exec(createSubjectIndex)) 
    {
        // Не критичная ошибка - индекс не создан, но работа продолжится
        // Запросы по subject будут выполняться медленнее (full table scan)
        qDebug() << "Не удалось создать индекс для subject:" << m_lastError;
    }
    
    // ========================================================================
    // ИНДЕКС 2: IDX_CERTS_STATUS - ФИЛЬТРАЦИЯ ПО СТАТУСУ СЕРТИФИКАТА
    // ========================================================================
    // Индекс для поля status в таблице certs.
    // Ускоряет следующие типы запросов:
    // - SELECT * FROM certs WHERE status = 'active'
    // - SELECT * FROM certs WHERE status IN ('expired', 'revoked')
    // - SELECT COUNT(*) FROM certs WHERE status = 'active'
    //
    // ИСПОЛЬЗОВАНИЕ:
    // Используется при фильтрации сертификатов по статусу:
    // - active: активные сертификаты
    // - expired: истекшие сертификаты
    // - revoked: отозванные сертификаты
    // Критичен для операций:
    // - Получение списка активных сертификатов
    // - Подсчет количества сертификатов по статусам
    // - Поиск истекших сертификатов для обновления
    QString createStatusIndex = "CREATE INDEX IF NOT EXISTS idx_certs_status ON certs(status)";
    if (!exec(createStatusIndex)) 
    {
        // Не критичная ошибка - индекс не создан, но работа продолжится
        // Запросы по status будут выполняться медленнее (full table scan)
        qDebug() << "Не удалось создать индекс для status:" << m_lastError;
    }
    
    // ========================================================================
    // ИНДЕКС 3: IDX_CERTS_SERIAL_STATUS - СОСТАВНОЙ ИНДЕКС
    // ========================================================================
    // Составной индекс для полей serial и status в таблице certs.
    // Ускоряет следующие типы запросов:
    // - SELECT * FROM certs WHERE serial = 12345 AND status = 'active'
    // - SELECT * FROM certs WHERE serial = 12345
    // - SELECT * FROM certs WHERE status = 'active' AND serial > 1000
    //
    // ОСОБЕННОСТИ СОСТАВНОГО ИНДЕКСА:
    // Составной индекс упорядочен по нескольким полям (serial, затем status).
    // Он эффективен для запросов, которые используют:
    // - Оба поля вместе (наиболее эффективно)
    // - Только первое поле (serial) - также эффективно
    // - Только второе поле (status) - менее эффективно, лучше использовать idx_certs_status
    //
    // ИСПОЛЬЗОВАНИЕ:
    // Критичен для операций:
    // - Проверка статуса конкретного сертификата по серийному номеру
    // - Поиск активных сертификатов в диапазоне серийных номеров
    // - Валидация сертификата перед выдачей (проверка, не отозван ли)
    QString createSerialStatusIndex = "CREATE INDEX IF NOT EXISTS idx_certs_serial_status ON certs(serial, status)";
    if (!exec(createSerialStatusIndex)) 
    {
        // Не критичная ошибка - индекс не создан, но работа продолжится
        // Запросы с комбинацией serial и status будут выполняться медленнее
        qDebug() << "Не удалось создать составной индекс:" << m_lastError;
    }
    
    // ========================================================================
    // ИНДЕКС 4: IDX_AUDIT_LOG_TIMESTAMP - ПОИСК ПО ВРЕМЕНИ В ЖУРНАЛЕ АУДИТА
    // ========================================================================
    // Индекс для поля timestamp в таблице audit_log.
    // Ускоряет следующие типы запросов:
    // - SELECT * FROM audit_log WHERE timestamp > 1234567890
    // - SELECT * FROM audit_log WHERE timestamp BETWEEN 1234567890 AND 1234567900
    // - SELECT * FROM audit_log ORDER BY timestamp DESC
    // - SELECT * FROM audit_log WHERE timestamp > ? ORDER BY timestamp
    //
    // ИСПОЛЬЗОВАНИЕ:
    // Используется при работе с журналом аудита:
    // - Получение записей за определенный период времени
    // - Поиск последних операций (ORDER BY timestamp DESC)
    // - Фильтрация записей по временным меткам
    // - Очистка старых записей (DELETE WHERE timestamp < ?)
    //
    // КРИТИЧНОСТЬ:
    // Особенно важен для больших журналов аудита, так как без индекса
    // поиск по времени требует полного сканирования таблицы, что может
    // быть очень медленным при тысячах записей.
    QString createTimestampIndex = "CREATE INDEX IF NOT EXISTS idx_audit_log_timestamp ON audit_log(timestamp)";
    if (!exec(createTimestampIndex)) 
    {
        // Не критичная ошибка - индекс не создан, но работа продолжится
        // Запросы по timestamp будут выполняться медленнее (full table scan)
        // Это особенно заметно при большом количестве записей в audit_log
        qDebug() << "Не удалось создать индекс для timestamp:" << m_lastError;
    }
    
    // ========================================================================
    // ЗАВЕРШЕНИЕ ИНИЦИАЛИЗАЦИИ
    // ========================================================================
    // Все таблицы и индексы созданы (или уже существовали).
    // База данных готова к использованию.
    qDebug() << "Таблицы базы данных CA инициализированы";
    return true;
}


