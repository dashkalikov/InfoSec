#!/usr/bin/env python3
# ============================================================================
# СКРИПТ VERIFY_PDF_SIGNATURE.PY - ПРОВЕРКА ЦИФРОВОЙ ПОДПИСИ PDF ДОКУМЕНТОВ
# ============================================================================
# Этот скрипт проверяет цифровую подпись PDF документов с использованием
# библиотеки pyHanko. Поддерживает проверку валидности подписи, целостности
# документа, извлечение метаданных сертификата, проверку временных меток
# (timestamp) и проверку доверия к сертификату через CA.
#
# НАЗНАЧЕНИЕ:
# - Проверка наличия цифровой подписи в PDF документе
# - Валидация подписи на целостность и подлинность
# - Извлечение и отображение метаданных сертификата (подписант, издатель)
# - Проверка наличия временной метки (timestamp) в подписи
# - Проверка доверия к сертификату через указанный CA сертификат
#
# АЛГОРИТМ РАБОТЫ:
# 1. Настройка путей к библиотекам Python (site-packages)
# 2. Импорт необходимых библиотек (pyhanko, cryptography)
# 3. Парсинг аргументов командной строки (путь к PDF, опционально CA сертификат)
# 4. Проверка существования входных файлов
# 5. Открытие PDF файла и создание PdfFileReader
# 6. Поиск полей подписи в PDF (основной метод и альтернативный)
# 7. Для каждой найденной подписи:
#    - Извлечение объекта поля подписи из PDF структуры
#    - Создание EmbeddedPdfSignature объекта
#    - Создание ValidationContext с CA сертификатом (если указан)
#    - Валидация подписи через validate_pdf_signature
#    - Извлечение метаданных сертификата (CN подписанта и издателя)
#    - Проверка наличия временной метки (timestamp)
#    - Проверка статуса валидации (валидна/невалидна, доверенная/недоверенная)
# 8. Вывод результатов проверки
#
# ПРОТОКОЛ ИСПОЛЬЗОВАНИЯ:
# Базовое использование (проверка без CA):
#   python3 verify_pdf_signature.py signed_document.pdf
#
# С указанием CA сертификата (для проверки доверия):
#   python3 verify_pdf_signature.py signed_document.pdf ca_cert.pem
#
# КОДЫ ВОЗВРАТА:
# 0  - Успешное выполнение
# 1  - Ошибка: неверное количество аргументов
# 1  - Ошибка: PDF файл не найден
# 1  - Ошибка: CA сертификат не найден
# 1  - Ошибка: подпись не найдена в PDF
# 1  - Ошибка: pyhanko не установлен
# 1  - Ошибка: ошибка проверки PDF
# ============================================================================

# ============================================================================
# ИМПОРТЫ СТАНДАРТНОЙ БИБЛИОТЕКИ
# ============================================================================
import sys                # Системные функции (argv, exit, path)
import site               # Работа с site-packages для поиска установленных библиотек
from pathlib import Path  # Работа с путями к файлам (кроссплатформенно)

# ============================================================================
# НАСТРОЙКА ПУТЕЙ К БИБЛИОТЕКАМ PYTHON
# ============================================================================
# ДЕЙСТВИЕ 1: Добавление user site-packages в sys.path
# ========================================================================
# site.getusersitepackages() возвращает путь к директории user site-packages,
# где пользователь устанавливает пакеты через pip install --user.
# Это необходимо для поиска pyhanko и других библиотек, установленных
# пользователем без прав администратора.
# ДЕЙСТВИЕ 1.1: Получение пути к user site-packages
# site.getusersitepackages() возвращает строку с путем к директории, где
# Python ищет пакеты, установленные пользователем (например, ~/.local/lib/python3.x/site-packages).
user_site = site.getusersitepackages()
# ДЕЙСТВИЕ 1.2: Проверка наличия пути и его отсутствия в sys.path
# Проверяем, что путь существует (не None) и еще не добавлен в sys.path.
# Это предотвращает дублирование путей в sys.path.
if user_site and user_site not in sys.path:
    # ДЕЙСТВИЕ 1.3: Добавление пути в начало sys.path
    # sys.path.insert(0, path) добавляет путь в начало списка путей поиска,
    # что дает приоритет user site-packages над системными пакетами.
    sys.path.insert(0, user_site)

# ========================================================================
# ДЕЙСТВИЕ 2: Добавление альтернативных путей для macOS
# ========================================================================
# На macOS библиотеки могут быть установлены в различных версиях Python
# в директории Library/Python/{version}/lib/python/site-packages.
# Проверяем все возможные версии Python и добавляем существующие пути.
# ДЕЙСТВИЕ 2.1: Получение домашней директории пользователя
# Path.home() возвращает объект Path для домашней директории пользователя
# (например, /Users/username на macOS).
home = Path.home()
# ДЕЙСТВИЕ 2.2: Перебор возможных версий Python
# На macOS Python может быть установлен в разных версиях, и каждая версия
# имеет свою директорию site-packages в ~/Library/Python/{version}/.
# Перебираем версии от 3.14 до 3.9 (от новых к старым).
for ver in ['3.14', '3.13', '3.12', '3.11', '3.10', '3.9']:
    # ДЕЙСТВИЕ 2.3: Формирование пути к site-packages для версии Python
    # Используем оператор / для конкатенации путей (кроссплатформенно).
    # Результирующий путь: ~/Library/Python/3.x/lib/python/site-packages
    alt_path = home / f'Library/Python/{ver}/lib/python/site-packages'
    # ДЕЙСТВИЕ 2.4: Проверка существования пути и его отсутствия в sys.path
    # alt_path.exists() проверяет, существует ли директория на диске.
    # str(alt_path) not in sys.path проверяет, не добавлен ли путь уже в sys.path.
    if alt_path.exists() and str(alt_path) not in sys.path:
        # ДЕЙСТВИЕ 2.5: Добавление пути в начало sys.path
        # sys.path.insert(0, str(alt_path)) добавляет путь в начало списка,
        # давая приоритет найденным пакетам над системными.
        sys.path.insert(0, str(alt_path))

# ============================================================================
# ИМПОРТЫ БИБЛИОТЕК ТРЕТЬИХ СТОРОН
# ============================================================================
# ДЕЙСТВИЕ 3: Импорт pyhanko библиотек
# ========================================================================
# pyhanko - библиотека для работы с цифровыми подписями PDF документов.
# validate_pdf_signature - функция для валидации подписи в PDF.
# PdfFileReader - класс для чтения и парсинга PDF файлов.
# enumerate_sig_fields - функция для поиска полей подписи в PDF.
try:
    # ДЕЙСТВИЕ 3.1: Импорт функции валидации подписи
    # validate_pdf_signature - основная функция pyhanko для проверки валидности
    # цифровой подписи в PDF. Выполняет криптографическую проверку подписи,
    # целостности документа и цепочки сертификатов.
    from pyhanko.sign.validation import validate_pdf_signature  # Валидация подписи
    # ДЕЙСТВИЕ 3.2: Импорт класса для чтения PDF
    # PdfFileReader - класс для парсинга и чтения структуры PDF файла.
    # Предоставляет доступ к корневому объекту, полям формы, полям подписи.
    from pyhanko.pdf_utils.reader import PdfFileReader  # Чтение PDF файлов
    # ДЕЙСТВИЕ 3.3: Импорт функции поиска полей подписи
    # enumerate_sig_fields - функция для поиска всех полей подписи в PDF.
    # Возвращает список кортежей (field_name, field_obj, widget_dict).
    from pyhanko.sign.fields import enumerate_sig_fields  # Поиск полей подписи
except ImportError as exc:
    # ДЕЙСТВИЕ 3.4: Обработка ошибки импорта
    # Если pyhanko не установлен, выводим сообщение об ошибке с инструкцией
    # по установке и завершаем выполнение скрипта с кодом возврата 1.
    print(f"ОШИБКА: pyhanko не установлен. Установите: python3 -m pip install --user pyhanko")
    print(f"Ошибка импорта: {exc}")
    sys.exit(1)


# ============================================================================
# ФУНКЦИЯ main - ГЛАВНАЯ ФУНКЦИЯ СКРИПТА
# ============================================================================
# Основная функция для проверки цифровой подписи PDF документов.
# Обрабатывает аргументы командной строки, открывает PDF файл, ищет поля
# подписи, валидирует каждую найденную подпись, извлекает метаданные
# сертификата и проверяет наличие временных меток.
#
# АЛГОРИТМ:
# 1. Парсинг аргументов командной строки
# 2. Проверка существования входных файлов (PDF, опционально CA сертификат)
# 3. Открытие PDF файла и создание PdfFileReader
# 4. Поиск полей подписи в PDF (основной метод и альтернативный)
# 5. Для каждой найденной подписи:
#    - Извлечение объекта поля подписи из PDF структуры
#    - Создание EmbeddedPdfSignature объекта
#    - Создание ValidationContext с CA сертификатом (если указан)
#    - Валидация подписи через validate_pdf_signature
#    - Извлечение метаданных сертификата (CN подписанта и издателя)
#    - Проверка наличия временной метки (timestamp)
#    - Проверка статуса валидации (валидна/невалидна, доверенная/недоверенная)
# 6. Вывод результатов проверки
#
# ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
#   None - функция завершает выполнение через sys.exit() с кодом возврата
# ============================================================================
def main():
    # ========================================================================
    # ДЕЙСТВИЕ 1: ПАРСИНГ АРГУМЕНТОВ КОМАНДНОЙ СТРОКИ
    # ========================================================================
    # Проверяем количество аргументов командной строки.
    # sys.argv[0] - имя скрипта
    # sys.argv[1] - обязательный аргумент: путь к PDF файлу
    # sys.argv[2] - опциональный аргумент: путь к CA сертификату
    # ДЕЙСТВИЕ 1.1: Проверка минимального количества аргументов
    # len(sys.argv) < 2 означает, что указан только sys.argv[0] (имя скрипта),
    # но не указан обязательный аргумент - путь к PDF файлу.
    if len(sys.argv) < 2:
        # ДЕЙСТВИЕ 1.2: Вывод справки об использовании
        # Выводим сообщение с правильным синтаксисом вызова скрипта.
        print("Использование: python3 verify_pdf_signature.py <путь_к_подписанному_pdf> [путь_к_ca_сертификату.pem]")
        # ДЕЙСТВИЕ 1.3: Завершение выполнения с кодом ошибки
        # sys.exit(1) завершает выполнение скрипта с кодом возврата 1 (ошибка).
        sys.exit(1)
    
    # ========================================================================
    # ДЕЙСТВИЕ 2: ПРОВЕРКА СУЩЕСТВОВАНИЯ PDF ФАЙЛА
    # ========================================================================
    # Создаем объект Path для пути к PDF файлу из первого аргумента.
    # Path предоставляет кроссплатформенную работу с путями и методы
    # для проверки существования файлов.
    # ДЕЙСТВИЕ 2.1: Создание объекта Path для PDF файла
    # Path(sys.argv[1]) создает объект Path из строки пути, указанной
    # пользователем в командной строке. Path автоматически обрабатывает
    # разделители путей для разных операционных систем.
    pdf_path = Path(sys.argv[1])
    # ДЕЙСТВИЕ 2.2: Проверка существования файла
    # pdf_path.exists() проверяет, существует ли файл или директория по указанному пути.
    # Если файл не существует, выводим ошибку и завершаем выполнение.
    if not pdf_path.exists():
        # ДЕЙСТВИЕ 2.3: Вывод сообщения об ошибке
        # Выводим сообщение с указанием пути к файлу, который не был найден.
        print(f"ОШИБКА: PDF файл не найден: {pdf_path}")
        # ДЕЙСТВИЕ 2.4: Завершение выполнения с кодом ошибки
        sys.exit(1)
    
    # ========================================================================
    # ДЕЙСТВИЕ 3: ПРОВЕРКА СУЩЕСТВОВАНИЯ CA СЕРТИФИКАТА (ЕСЛИ УКАЗАН)
    # ========================================================================
    # Если указан второй аргумент, создаем объект Path для CA сертификата
    # и проверяем его существование. CA сертификат используется для проверки
    # доверия к сертификату подписанта (проверка цепочки сертификатов).
    # ДЕЙСТВИЕ 3.1: Инициализация переменной для пути к CA сертификату
    # Изначально устанавливаем ca_cert_path в None, так как CA сертификат
    # является опциональным параметром.
    ca_cert_path = None
    # ДЕЙСТВИЕ 3.2: Проверка наличия второго аргумента
    # len(sys.argv) > 2 означает, что пользователь указал второй аргумент
    # (путь к CA сертификату) в командной строке.
    if len(sys.argv) > 2:
        # ДЕЙСТВИЕ 3.3: Создание объекта Path для CA сертификата
        # Path(sys.argv[2]) создает объект Path из строки пути к CA сертификату.
        ca_cert_path = Path(sys.argv[2])
        # ДЕЙСТВИЕ 3.4: Проверка существования CA сертификата
        # ca_cert_path.exists() проверяет, существует ли файл сертификата.
        if not ca_cert_path.exists():
            # ДЕЙСТВИЕ 3.5: Вывод сообщения об ошибке
            print(f"ОШИБКА: CA сертификат не найден: {ca_cert_path}")
            # ДЕЙСТВИЕ 3.6: Завершение выполнения с кодом ошибки
            sys.exit(1)
    
    # ========================================================================
    # ДЕЙСТВИЕ 4: ВЫВОД ИНФОРМАЦИИ О PDF ФАЙЛЕ
    # ========================================================================
    # Выводим заголовок проверки, путь к файлу и его размер в байтах.
    # pdf_path.stat().st_size возвращает размер файла в байтах через
    # системный вызов stat().
    # ДЕЙСТВИЕ 4.1: Вывод заголовка проверки
    # Выводим заголовок с информацией о начале проверки цифровой подписи.
    print(f"\n=== Проверка цифровой подписи PDF ===")
    # ДЕЙСТВИЕ 4.2: Вывод пути к PDF файлу
    # Выводим полный путь к проверяемому PDF файлу.
    print(f"Файл: {pdf_path}")
    # ДЕЙСТВИЕ 4.3: Вывод размера файла
    # pdf_path.stat() вызывает системный вызов stat() для получения метаданных файла.
    # .st_size возвращает размер файла в байтах.
    print(f"Размер: {pdf_path.stat().st_size} байт\n")
    
    # ========================================================================
    # ДЕЙСТВИЕ 5: ОТКРЫТИЕ PDF ФАЙЛА И СОЗДАНИЕ READER
    # ========================================================================
    # Открываем PDF файл в бинарном режиме ("rb") и создаем PdfFileReader
    # для парсинга структуры PDF и доступа к полям подписи.
    # Используем контекстный менеджер (with) для автоматического закрытия файла.
    try:
        # ДЕЙСТВИЕ 5.1: Открытие PDF файла в бинарном режиме
        # pdf_path.open("rb") открывает файл в режиме чтения бинарных данных ("rb").
        # Контекстный менеджер (with) гарантирует автоматическое закрытие файла
        # даже при возникновении исключения.
        with pdf_path.open("rb") as f:
            # ДЕЙСТВИЕ 5.2: Создание PdfFileReader для парсинга PDF
            # PdfFileReader(f) создает объект для чтения и парсинга структуры PDF.
            # Парсит заголовок PDF, xref таблицу, объекты, корневой каталог,
            # поля формы (AcroForm) и поля подписи (Sig).
            reader = PdfFileReader(f)
            
            # ====================================================================
            # ДЕЙСТВИЕ 6: ПОИСК ПОЛЕЙ ПОДПИСИ В PDF
            # ====================================================================
            # enumerate_sig_fields() - основной метод поиска полей подписи.
            # Возвращает список кортежей (field_name, field_obj, widget_dict),
            # где field_name - имя поля подписи, field_obj - объект поля,
            # widget_dict - словарь виджета подписи.
            # ДЕЙСТВИЕ 6.1: Инициализация списка полей подписи
            # sig_fields будет содержать список найденных полей подписи.
            sig_fields = []
            try:
                # ДЕЙСТВИЕ 6.2: Основной метод поиска полей подписи
                # enumerate_sig_fields(reader) - функция pyhanko для поиска всех полей
                # подписи в PDF. Проходит по структуре AcroForm, находит поля типа Sig,
                # извлекает их имена, объекты полей и виджеты.
                # Возвращает итератор кортежей (field_name, field_obj, widget_dict).
                sig_fields = list(enumerate_sig_fields(reader))
            except Exception as e:
                # ДЕЙСТВИЕ 6.3: Обработка ошибки основного метода
                # Если enumerate_sig_fields() не сработал (несовместимость версий pyhanko,
                # нестандартная структура PDF, поврежденный файл), выводим предупреждение.
                print(f"⚠ Ошибка поиска подписей: {e}")
                # ДЕЙСТВИЕ 6.4: Альтернативный метод поиска через форму документа
                # Пытаемся найти поля подписи через прямой доступ к форме документа (AcroForm).
                try:
                    # reader.get_form_sig_fields() возвращает список имен полей подписи
                    # из формы документа. Это менее надежный метод, так как не извлекает
                    # объекты полей, но может работать в случаях, когда основной метод не работает.
                    for field_name in reader.get_form_sig_fields():
                        # Добавляем кортеж (field_name, None), так как объект поля недоступен
                        sig_fields.append((field_name, None))
                except:
                    # Если альтернативный метод тоже не сработал, просто пропускаем
                    pass
            
            # ====================================================================
            # ДЕЙСТВИЕ 7: ПРОВЕРКА НАЛИЧИЯ ПОДПИСЕЙ
            # ====================================================================
            # Если поля подписи не найдены, выводим сообщение об ошибке и
            # инструкции по проверке подписи в PDF-просмотрщике.
            # ДЕЙСТВИЕ 7.1: Проверка наличия найденных полей подписи
            # Если sig_fields пуст, значит в PDF не найдено ни одного поля подписи.
            if not sig_fields:
                # ДЕЙСТВИЕ 7.2: Вывод сообщения об отсутствии подписей
                print("❌ ПОДПИСЬ НЕ НАЙДЕНА")
                print("   Этот PDF не содержит цифровых подписей.")
                # ДЕЙСТВИЕ 7.3: Вывод инструкций по проверке в PDF-просмотрщике
                # Предоставляем пользователю инструкции, как проверить наличие подписи
                # в различных PDF-просмотрщиках, так как некоторые подписи могут быть
                # невидимыми или скрытыми.
                print("\n💡 Проверьте в PDF-просмотрщике:")
                print("   - macOS Preview: ищите значок подписи внизу документа")
                print("   - Adobe Reader: Правка → Подписи и инициалы → Управлять подписями")
                print("   - Chrome/Edge: при открытии должно быть уведомление о подписи")
                # ДЕЙСТВИЕ 7.4: Завершение выполнения с кодом ошибки
                sys.exit(1)
            
            # ДЕЙСТВИЕ 7.5: Вывод количества найденных подписей
            # Если подписи найдены, выводим их количество для информации пользователя.
            print(f"✓ Найдено подписей: {len(sig_fields)}\n")
            
            # ====================================================================
            # ДЕЙСТВИЕ 8: ОБРАБОТКА КАЖДОЙ НАЙДЕННОЙ ПОДПИСИ
            # ====================================================================
            # enumerate_sig_fields возвращает кортежи (field_name, field_obj, widget_dict).
            # Обрабатываем каждую найденную подпись: извлекаем объект поля, создаем
            # EmbeddedPdfSignature, валидируем подпись и извлекаем метаданные.
            # ДЕЙСТВИЕ 8.0: Перебор всех найденных полей подписи
            # Обрабатываем каждую найденную подпись отдельно, так как в PDF может
            # быть несколько подписей от разных подписантов или в разное время.
            for sig_info in sig_fields:
                # ДЕЙСТВИЕ 8.0.1: Извлечение данных из кортежа поля подписи
                # sig_info может быть кортежем разной длины:
                # - (field_name, field_obj, widget_dict) - при основном методе
                # - (field_name, None) - при альтернативном методе
                if len(sig_info) >= 2:
                    # ДЕЙСТВИЕ 8.0.2: Извлечение имени поля подписи
                    # field_name - полное имя поля подписи (например, "Signature1").
                    field_name = sig_info[0]  # Имя поля подписи
                    # ДЕЙСТВИЕ 8.0.3: Извлечение объекта поля подписи
                    # field_obj - словарь PDF объекта поля подписи, содержащий
                    # метаданные подписи, сертификат, временную метку и т.д.
                    field_obj = sig_info[1] if len(sig_info) > 1 else None  # Объект поля
                else:
                    # ДЕЙСТВИЕ 8.0.4: Пропуск невалидного кортежа
                    # Если кортеж слишком короткий (меньше 2 элементов), пропускаем
                    # эту подпись, так как нет даже имени поля.
                    continue
                
                # ДЕЙСТВИЕ 8.0.5: Вывод заголовка для текущей подписи
                # Выводим имя поля подписи для идентификации обрабатываемой подписи.
                print(f"--- Подпись: {field_name} ---")
                
                try:
                    # ================================================================
                    # ДЕЙСТВИЕ 8.1: ИЗВЛЕЧЕНИЕ ОБЪЕКТА ПОЛЯ ПОДПИСИ
                    # ================================================================
                    # ДЕЙСТВИЕ 8.1.1: Инициализация переменной для результата валидации
                    # validation_result будет содержать результат валидации подписи
                    # (объект PdfSignatureStatus с информацией о валидности, целостности и т.д.).
                    validation_result = None
                    
                    # ДЕЙСТВИЕ 8.1.2: Импорт классов для работы с встроенными подписями
                    # Импортируем классы внутри try блока, так как они могут быть недоступны
                    # в некоторых версиях pyhanko или при отсутствии зависимостей.
                    try:
                        # EmbeddedPdfSignature - класс для работы с встроенной подписью в PDF.
                        # Инкапсулирует доступ к метаданным подписи, сертификату, временной метке.
                        from pyhanko.sign.validation.pdf_embedded import EmbeddedPdfSignature  # Класс для встроенной подписи
                        # ValidationContext - класс для создания контекста валидации с доверенными CA.
                        # Определяет, какие корневые сертификаты считаются доверенными.
                        from pyhanko_certvalidator import ValidationContext  # Контекст валидации с доверенными CA
                        
                        # ДЕЙСТВИЕ 8.1.3: Получение словаря поля подписи из объекта поля
                        # field_obj из enumerate_sig_fields должен быть словарем PDF объекта
                        # поля подписи, содержащим метаданные подписи, сертификат и т.д.
                        sig_field_dict = field_obj
                        
                        # ДЕЙСТВИЕ 8.1.4: Поиск поля подписи через структуру формы (если не найдено)
                        # Если объект поля не был получен (например, при альтернативном методе поиска),
                        # пытаемся найти поле подписи через прямую навигацию по структуре формы документа (AcroForm).
                        if not sig_field_dict:
                            try:
                                # ДЕЙСТВИЕ 8.1.4.1: Получение объекта формы документа (AcroForm)
                                # reader.root.get('/AcroForm') получает объект формы документа из корневого каталога PDF.
                                # AcroForm содержит все интерактивные поля формы, включая поля подписи.
                                form = reader.root.get('/AcroForm')
                                if form:
                                    # ДЕЙСТВИЕ 8.1.4.2: Получение списка полей формы
                                    # form.get('/Fields') возвращает массив ссылок на объекты полей формы.
                                    fields = form.get('/Fields')
                                    if fields:
                                        # ДЕЙСТВИЕ 8.1.4.3: Перебор всех полей формы
                                        # Перебираем все поля формы и ищем поле подписи по имени.
                                        for field_ref in fields:
                                            # ДЕЙСТВИЕ 8.1.4.4: Разрешение ссылки на объект поля
                                            # reader.resolve(field_ref) разрешает косвенную ссылку на объект поля
                                            # (PDF использует косвенные ссылки для ссылок на объекты).
                                            field_obj_ref = reader.resolve(field_ref)
                                            if field_obj_ref:
                                                # ДЕЙСТВИЕ 8.1.4.5: Получение имени поля и сравнение
                                                # field_obj_ref.get('/T') получает атрибут /T (имя поля) из объекта поля.
                                                # Сравниваем имя поля с искомым именем подписи.
                                                field_name_attr = field_obj_ref.get('/T')
                                                if field_name_attr == field_name:
                                                    # ДЕЙСТВИЕ 8.1.4.6: Сохранение найденного объекта поля
                                                    # Нашли нужное поле подписи, сохраняем его объект.
                                                    sig_field_dict = field_obj_ref
                                                    break
                            except Exception as find_err:
                                # ДЕЙСТВИЕ 8.1.4.7: Обработка ошибки поиска поля
                                # Если не удалось найти поле подписи через структуру формы,
                                # выводим предупреждение, но продолжаем обработку.
                                print(f"  ⚠ Не удалось найти поле подписи в PDF: {find_err}")
                        
                        # ДЕЙСТВИЕ 8.1.5: Проверка наличия объекта поля подписи
                        # Если не удалось получить объект поля подписи ни основным, ни альтернативным методом,
                        # выводим сообщение и переходим к следующей подписи (без детальной валидации).
                        if not sig_field_dict:
                            print(f"  ✓ Подпись найдена в поле '{field_name}'")
                            print(f"  ⚠ Не удалось получить объект поля для детальной валидации")
                            print(f"  💡 Для полной проверки откройте PDF в Preview или Adobe Reader")
                            continue
                        
                        # ================================================================
                        # ДЕЙСТВИЕ 8.2: СОЗДАНИЕ ОБЪЕКТА ВСТРОЕННОЙ ПОДПИСИ
                        # ================================================================
                        # EmbeddedPdfSignature инкапсулирует встроенную подпись в PDF
                        # и предоставляет доступ к метаданным подписи, сертификату,
                        # временной метке и другим атрибутам.
                        # ДЕЙСТВИЕ 8.2.1: Создание объекта EmbeddedPdfSignature
                        # EmbeddedPdfSignature объединяет PdfFileReader, объект поля подписи
                        # и имя поля в единый объект для удобной работы с подписью.
                        # Предоставляет методы для извлечения сертификата, временной метки,
                        # метаданных подписи и доступа к содержимому подписи (CMS структура).
                        embedded_sig = EmbeddedPdfSignature(
                            reader=reader,           # PdfFileReader для доступа к PDF структуре
                            sig_field=sig_field_dict,  # Словарь поля подписи (PDF объект)
                            fq_name=field_name        # Полное имя поля подписи (Fully Qualified Name)
                        )
                        
                        # ================================================================
                        # ДЕЙСТВИЕ 8.3: СОЗДАНИЕ КОНТЕКСТА ВАЛИДАЦИИ
                        # ================================================================
                        # ValidationContext определяет доверенные корневые сертификаты (CA)
                        # для проверки цепочки сертификатов подписанта. Если CA сертификат
                        # указан, загружаем его и добавляем в список доверенных корней.
                        # ДЕЙСТВИЕ 8.3.1: Инициализация переменной для контекста валидации
                        validation_context = None
                        # ДЕЙСТВИЕ 8.3.2: Проверка наличия CA сертификата
                        # Если пользователь указал путь к CA сертификату, загружаем его
                        # и используем для проверки доверия к сертификату подписанта.
                        if ca_cert_path and ca_cert_path.exists():
                            try:
                                # ДЕЙСТВИЕ 8.3.2.1: Загрузка CA сертификата из файла
                                # Открываем файл CA сертификата в бинарном режиме и читаем его содержимое.
                                with ca_cert_path.open('rb') as f:
                                    ca_cert_data = f.read()
                                # ДЕЙСТВИЕ 8.3.2.2: Импорт библиотеки cryptography для работы с сертификатами
                                from cryptography import x509  # Библиотека для работы с X.509 сертификатами
                                # ДЕЙСТВИЕ 8.3.2.3: Парсинг PEM-кодированного сертификата
                                # x509.load_pem_x509_certificate() парсит PEM-кодированный сертификат
                                # (формат -----BEGIN CERTIFICATE----- ... -----END CERTIFICATE-----)
                                # и создает объект x509.Certificate для работы с сертификатом.
                                ca_cert = x509.load_pem_x509_certificate(ca_cert_data)
                                
                                # ДЕЙСТВИЕ 8.3.2.4: Создание контекста валидации с доверенным корневым сертификатом
                                # ValidationContext(trust_roots=[ca_cert]) создает контекст валидации,
                                # в котором указанный CA сертификат считается доверенным корневым.
                                # При проверке цепочки сертификатов подписанта, если цепочка ведет
                                # к этому CA сертификату, подпись считается доверенной.
                                validation_context = ValidationContext(trust_roots=[ca_cert])
                            except Exception as context_err:
                                # ДЕЙСТВИЕ 8.3.2.5: Обработка ошибки загрузки CA сертификата
                                # Если не удалось загрузить или распарсить CA сертификат (неверный формат,
                                # поврежденный файл, ошибка парсинга), выводим предупреждение и создаем
                                # контекст без доверенных корней (проверка будет зависеть от системных хранилищ).
                                print(f"  ⚠ Не удалось создать контекст валидации: {context_err}")
                                validation_context = ValidationContext()
                        else:
                            # ДЕЙСТВИЕ 8.3.3: Создание контекста без доверенных корней
                            # Если CA сертификат не указан, создаем контекст валидации без доверенных корней.
                            # В этом случае проверка доверия к сертификату подписанта будет зависеть
                            # от системных хранилищ сертификатов (например, системного хранилища CA на macOS).
                            validation_context = ValidationContext()
                        
                        # ================================================================
                        # ДЕЙСТВИЕ 8.4: ВАЛИДАЦИЯ ПОДПИСИ
                        # ================================================================
                        # validate_pdf_signature выполняет полную валидацию подписи:
                        # - Проверка целостности документа (не был ли изменен после подписания)
                        # - Проверка подлинности подписи (криптографическая проверка)
                        # - Проверка цепочки сертификатов (если указан CA)
                        # - Проверка срока действия сертификата
                        # Возвращает объект с результатами валидации (PdfSignatureStatus)
                        # ДЕЙСТВИЕ 8.4.1: Выполнение валидации подписи
                        # validate_pdf_signature() выполняет комплексную проверку подписи:
                        # 1. Извлекает подпись из PDF (CMS структура)
                        # 2. Проверяет целостность документа (вычисляет хеш документа и сравнивает
                        #    с хешем, зашифрованным в подписи)
                        # 3. Проверяет криптографическую подлинность подписи (расшифровывает
                        #    подпись публичным ключом из сертификата и проверяет соответствие)
                        # 4. Проверяет цепочку сертификатов (от сертификата подписанта до корневого CA)
                        # 5. Проверяет срок действия сертификата (notBefore, notAfter)
                        # 6. Проверяет отзыв сертификата (CRL, OCSP, если доступно)
                        # Возвращает объект PdfSignatureStatus с результатами всех проверок.
                        validation_result = validate_pdf_signature(
                            embedded_sig=embedded_sig,              # Объект встроенной подписи
                            signer_validation_context=validation_context  # Контекст валидации с CA
                        )
                        
                    except ImportError as import_err:
                        # ДЕЙСТВИЕ 8.4.2: Обработка ошибки импорта модулей валидации
                        # Если не удалось импортировать модули валидации (например, из-за
                        # несовместимости версий pyhanko, отсутствия зависимостей pyhanko_certvalidator),
                        # выводим сообщение об ошибке и переходим к следующей подписи без детальной валидации.
                        print(f"  ⚠ Не удалось импортировать модули валидации: {import_err}")
                        print(f"  ✓ Подпись найдена в поле '{field_name}'")
                        print(f"  ⚠ Детальная валидация недоступна")
                        print(f"  💡 Для полной проверки откройте PDF в Preview или Adobe Reader")
                        continue
                    except Exception as validation_err:
                        # ДЕЙСТВИЕ 8.4.3: Обработка ошибки валидации подписи
                        # Если валидация завершилась с ошибкой (например, поврежденная подпись,
                        # несовместимая структура PDF, ошибка парсинга CMS структуры, ошибка проверки
                        # цепочки сертификатов), все равно сообщаем о найденной подписи и выводим
                        # информацию об ошибке для диагностики.
                        print(f"  ✓ Подпись найдена в поле '{field_name}'")
                        print(f"  ⚠ Ошибка валидации: {validation_err}")
                        print(f"  💡 Для полной проверки откройте PDF в Preview или Adobe Reader")
                        continue
                    
                    # ДЕЙСТВИЕ 8.4.4: Проверка наличия результата валидации
                    # Если результат валидации None (не удалось получить результат из-за ошибки
                    # в validate_pdf_signature или несовместимости версий pyhanko), выводим
                    # сообщение и переходим к следующей подписи.
                    if validation_result is None:
                        print(f"  ✓ Подпись найдена в поле '{field_name}'")
                        print(f"  ⚠ Детальная валидация недоступна в текущей версии pyhanko")
                        print(f"  💡 Для полной проверки откройте PDF в Preview или Adobe Reader")
                        continue
                    
                    # ================================================================
                    # ДЕЙСТВИЕ 8.5: ИЗВЛЕЧЕНИЕ МЕТАДАННЫХ СЕРТИФИКАТА
                    # ================================================================
                    # ДЕЙСТВИЕ 8.5.1: Импорт PdfSignatureStatus для проверки типа результата
                    # PdfSignatureStatus - класс, представляющий статус валидации подписи.
                    # Используется для проверки типа validation_result и доступа к атрибутам статуса.
                    from pyhanko.sign.validation import PdfSignatureStatus
                    
                    # ДЕЙСТВИЕ 8.5.2: Проверка наличия сертификата в результате валидации
                    # Пытаемся извлечь информацию о сертификате подписанта из результата валидации.
                    # validation_result может содержать сертификат в разных атрибутах в зависимости
                    # от версии pyhanko и структуры результата валидации:
                    # - signer_cert - прямой атрибут с сертификатом подписанта
                    # - cert_path - цепочка сертификатов (от подписанта до корневого CA)
                    if hasattr(validation_result, 'signer_cert') or hasattr(validation_result, 'cert_path'):
                        try:
                            # ДЕЙСТВИЕ 8.5.2.1: Импорт библиотеки cryptography для работы с сертификатами
                            from cryptography import x509  # Библиотека для работы с X.509 сертификатами
                            
                            # ДЕЙСТВИЕ 8.5.2.2: Получение сертификата подписанта
                            # Пытаемся получить сертификат разными способами, так как структура
                            # validation_result может отличаться в разных версиях pyhanko.
                            cert = None
                            # Способ 1: сертификат в атрибуте signer_cert
                            # В некоторых версиях pyhanko сертификат подписанта хранится напрямую
                            # в атрибуте signer_cert результата валидации.
                            if hasattr(validation_result, 'signer_cert'):
                                cert = validation_result.signer_cert
                            # Способ 2: сертификат в цепочке cert_path (берем первый сертификат)
                            # В других версиях pyhanko сертификат подписанта находится в цепочке
                            # сертификатов cert_path. Первый элемент цепочки - сертификат подписанта,
                            # последующие - промежуточные CA, последний - корневой CA.
                            elif hasattr(validation_result, 'cert_path') and validation_result.cert_path:
                                cert = validation_result.cert_path[0]
                            
                            # ДЕЙСТВИЕ 8.5.2.3: Извлечение Common Name (CN) из subject сертификата
                            # subject содержит информацию о владельце сертификата (подписанте).
                            # Common Name (CN) - это имя владельца сертификата, обычно используется
                            # для идентификации подписанта (например, "Иван Иванов" или "example.com").
                            if cert and hasattr(cert, 'subject'):
                                # get_attributes_for_oid возвращает список атрибутов с указанным OID.
                                # NameOID.COMMON_NAME соответствует OID 2.5.4.3 (CN в X.500 Distinguished Name).
                                subject_names = cert.subject.get_attributes_for_oid(x509.NameOID.COMMON_NAME)
                                if subject_names:
                                    # Берем первый CN (обычно он один, но теоретически может быть несколько).
                                    cn = subject_names[0].value
                                    print(f"  Подписант: {cn}")
                            
                            # ДЕЙСТВИЕ 8.5.2.4: Извлечение Common Name (CN) из issuer сертификата
                            # issuer содержит информацию об издателе сертификата (Certificate Authority, CA).
                            # Common Name (CN) издателя - это имя CA, выдавшего сертификат подписанта.
                            if cert and hasattr(cert, 'issuer'):
                                # get_attributes_for_oid возвращает список атрибутов издателя с указанным OID.
                                issuer_names = cert.issuer.get_attributes_for_oid(x509.NameOID.COMMON_NAME)
                                if issuer_names:
                                    # Берем первый CN издателя (обычно он один).
                                    issuer_cn = issuer_names[0].value
                                    print(f"  Издатель: {issuer_cn}")
                        except Exception as cert_err:
                            # ДЕЙСТВИЕ 8.5.2.5: Обработка ошибки извлечения метаданных сертификата
                            # Если не удалось извлечь метаданные сертификата (ошибка доступа к атрибутам,
                            # неверный формат сертификата, отсутствие CN в subject/issuer), просто пропускаем.
                            # Это не критичная ошибка, так как подпись все равно будет проверена на валидность.
                            pass
                    
                    # ================================================================
                    # ДЕЙСТВИЕ 8.6: ПРОВЕРКА НАЛИЧИЯ ВРЕМЕННОЙ МЕТКИ (TIMESTAMP)
                    # ================================================================
                    # Временная метка (timestamp) - это криптографически защищенное
                    # доказательство времени подписания документа, полученное от
                    # Time Stamping Authority (TSA) по протоколу RFC 3161.
                    # В отличие от простого времени подписания (/M), timestamp
                    # невозможно подделать и он доказывает, что документ был подписан
                    # в определенное время.
                    # ДЕЙСТВИЕ 8.6.1: Инициализация переменных для timestamp
                    has_timestamp = False  # Флаг наличия timestamp
                    timestamp_info = None  # Информация о timestamp (время подписания)
                    try:
                        # ДЕЙСТВИЕ 8.6.2: Способ 1 - Извлечение timestamp из объекта встроенной подписи
                        # Проверяем наличие объекта подписи в embedded_sig для доступа к CMS структуре.
                        if hasattr(embedded_sig, 'sig_object'):
                            sig_obj = embedded_sig.sig_object
                            if sig_obj:
                                # Поле /M (signing time) всегда присутствует в подписи,
                                # но это не timestamp token. Настоящий timestamp token
                                # находится в unsigned attributes подписи (CMS структура).
                                try:
                                    # ДЕЙСТВИЕ 8.6.2.1: Проверка наличия поля /Contents (содержимое подписи)
                                    # /Contents содержит зашифрованную подпись (CMS структура).
                                    # Timestamp token находится внутри этой структуры в unsigned attributes.
                                    if '/Contents' in sig_obj:
                                        # ДЕЙСТВИЕ 8.6.2.2: Попытка извлечения timestamp через pyhanko API
                                        try:
                                            # extract_timestamp_info извлекает timestamp token
                                            # из unsigned attributes подписи (RFC 3161).
                                            # Парсит CMS структуру, находит timestamp token, извлекает время.
                                            from pyhanko.sign.timestamps import extract_timestamp_info
                                            timestamp_info = extract_timestamp_info(embedded_sig)
                                            if timestamp_info:
                                                has_timestamp = True
                                        except (ImportError, AttributeError, Exception):
                                            # ДЕЙСТВИЕ 8.6.2.3: Обработка ошибки извлечения timestamp через API
                                            # Если не удалось извлечь через API (модуль недоступен, ошибка парсинга),
                                            # проверяем наличие поля /M (но это не настоящий timestamp).
                                            try:
                                                # /M - это время подписания, но не timestamp token.
                                                # Настоящий timestamp требует парсинга CMS структуры и находится
                                                # в unsigned attributes, а не в поле /M.
                                                if '/M' in sig_obj:
                                                    # Поле /M есть, но это не timestamp token.
                                                    # Для настоящего timestamp нужен парсинг unsigned attrs.
                                                    pass
                                            except:
                                                pass
                                except Exception as parse_err:
                                    # ДЕЙСТВИЕ 8.6.2.4: Обработка ошибки парсинга объекта подписи
                                    pass
                        
                        # ДЕЙСТВИЕ 8.6.3: Способ 2 - Проверка результата валидации на наличие timestamp
                        # В некоторых версиях pyhanko timestamp может быть в результате валидации,
                        # так как валидация может извлекать timestamp для проверки времени подписания.
                        if not has_timestamp and validation_result:
                            try:
                                # ДЕЙСТВИЕ 8.6.3.1: Проверка атрибута timestamp_info в результате валидации
                                # В некоторых версиях pyhanko результат валидации содержит timestamp_info
                                # с информацией о временной метке, если она присутствует в подписи.
                                if hasattr(validation_result, 'timestamp_info'):
                                    timestamp_info = validation_result.timestamp_info
                                    if timestamp_info:
                                        has_timestamp = True
                                # ДЕЙСТВИЕ 8.6.3.2: Проверка альтернативного атрибута timestamp
                                # В других версиях pyhanko timestamp может быть в атрибуте timestamp.
                                elif hasattr(validation_result, 'timestamp'):
                                    timestamp_info = validation_result.timestamp
                                    if timestamp_info:
                                        has_timestamp = True
                            except:
                                # ДЕЙСТВИЕ 8.6.3.3: Обработка ошибки доступа к атрибутам timestamp
                                pass
                    except Exception as ts_err:
                        # ДЕЙСТВИЕ 8.6.4: Обработка общей ошибки проверки timestamp
                        # Если произошла ошибка при проверке timestamp (ошибка доступа к embedded_sig,
                        # ошибка парсинга CMS структуры), просто пропускаем.
                        # Это не критичная ошибка, так как подпись все равно будет проверена на валидность.
                        pass
                    
                    # ДЕЙСТВИЕ 8.6.5: Вывод информации о наличии временной метки
                    if has_timestamp:
                        print(f"  ✓ МЕТКА ВРЕМЕНИ ПРИСУТСТВУЕТ")
                        if timestamp_info:
                            # ДЕЙСТВИЕ 8.6.5.1: Вывод времени подписания в зависимости от типа timestamp_info
                            # timestamp_info может быть разных типов в зависимости от версии pyhanko:
                            # - str - строка с временем подписания
                            # - объект с атрибутом timestamp - объект с временем подписания
                            # - другой тип - просто сообщаем о наличии timestamp
                            if isinstance(timestamp_info, str):
                                print(f"  Время подписания: {timestamp_info}")
                            elif hasattr(timestamp_info, 'timestamp'):
                                print(f"  Время подписания: {timestamp_info.timestamp}")
                            else:
                                print(f"  Метка времени: присутствует")
                    else:
                        # ДЕЙСТВИЕ 8.6.5.2: Вывод предупреждения об отсутствии timestamp
                        # Если timestamp отсутствует, выводим предупреждение, так как без timestamp
                        # время подписания может быть изменено (поле /M не защищено криптографически).
                        print(f"  ⚠ МЕТКА ВРЕМЕНИ ОТСУТСТВУЕТ")
                        print(f"  (Подпись без timestamp - время подписания может быть изменено)")
                    
                    # ================================================================
                    # ДЕЙСТВИЕ 8.7: ПРОВЕРКА СТАТУСА ВАЛИДАЦИИ ПОДПИСИ
                    # ================================================================
                    # Извлекаем статус валидации из результата. Статус содержит информацию
                    # о валидности подписи, целостности документа и доверии к сертификату.
                    # ДЕЙСТВИЕ 8.7.1: Извлечение статуса валидации из результата
                    status = None
                    # Способ 1: результат валидации сам является PdfSignatureStatus
                    # В некоторых версиях pyhanko validate_pdf_signature возвращает PdfSignatureStatus напрямую.
                    if isinstance(validation_result, PdfSignatureStatus):
                        status = validation_result
                    # Способ 2: статус в атрибуте status результата валидации
                    # В других версиях pyhanko результат валидации - это объект-обертка,
                    # а статус находится в атрибуте status.
                    elif hasattr(validation_result, 'status'):
                        status = validation_result.status
                    
                    # ДЕЙСТВИЕ 8.7.2: Обработка статуса валидации
                    if status:
                        # ДЕЙСТВИЕ 8.7.2.1: Проверка валидности подписи
                        # status.valid указывает, прошла ли подпись все проверки:
                        # - целостность документа (не был ли изменен после подписания)
                        # - криптографическая подлинность подписи
                        # - срок действия сертификата
                        if status.valid:
                            print(f"  ✓ ПОДПИСЬ ВАЛИДНА")
                            print(f"  ✓ Документ не изменён после подписания")
                            # ДЕЙСТВИЕ 8.7.2.2: Проверка доверия к сертификату (trust_anchor)
                            # trust_anchor указывает, найден ли доверенный корневой CA в цепочке сертификатов.
                            # Если trust_anchor есть, значит цепочка сертификатов ведет к доверенному CA.
                            if hasattr(status, 'trust_anchor'):
                                if status.trust_anchor:
                                    print(f"  ✓ Сертификат доверенный")
                                else:
                                    print(f"  ⚠ Сертификат не доверенный (не в списке доверенных CA)")
                        else:
                            # ДЕЙСТВИЕ 8.7.2.3: Обработка невалидной подписи
                            # Подпись невалидна - документ был изменен или подпись повреждена.
                            # Возможные причины: документ изменен после подписания, поврежденная подпись,
                            # истекший сертификат, отозванный сертификат, ошибка криптографической проверки.
                            print(f"  ❌ ПОДПИСЬ НЕВЕРНА")
                            if hasattr(status, 'summary'):
                                # Если есть summary, выводим детальное описание причины невалидности.
                                print(f"  Причина: {status.summary}")
                            else:
                                print(f"  Причина: документ изменён или подпись повреждена")
                    else:
                        # ДЕЙСТВИЕ 8.7.3: Обработка отсутствия статуса валидации
                        # Если статус не получен (несовместимость версий pyhanko, нестандартная структура
                        # результата), пытаемся проверить валидность напрямую через атрибут valid.
                        if hasattr(validation_result, 'valid'):
                            if validation_result.valid:
                                print(f"  ✓ ПОДПИСЬ ВАЛИДНА")
                            else:
                                print(f"  ❌ ПОДПИСЬ НЕВЕРНА")
                        else:
                            # ДЕЙСТВИЕ 8.7.3.1: Обработка невозможности определить статус
                            # Если не удалось определить статус валидации (нет атрибута valid,
                            # нет атрибута status, несовместимость версий pyhanko), просто сообщаем
                            # о найденной подписи без детальной информации о валидности.
                            print(f"  ✓ Подпись найдена и обработана")
                    
                except Exception as e:
                    # ДЕЙСТВИЕ 8.8: Обработка ошибки при обработке конкретной подписи
                    # Если произошла ошибка при обработке конкретной подписи (ошибка извлечения объекта поля,
                    # ошибка создания EmbeddedPdfSignature, ошибка валидации, ошибка извлечения метаданных),
                    # выводим сообщение об ошибке и трассировку стека для отладки, но продолжаем обработку
                    # остальных подписей (если они есть).
                    print(f"  ⚠ Ошибка проверки: {e}")
                    import traceback  # Модуль для вывода трассировки стека
                    traceback.print_exc()  # Выводим полную трассировку стека для диагностики ошибки
                
                # ДЕЙСТВИЕ 8.9: Разделитель между подписями
                # Выводим пустую строку для визуального разделения результатов проверки разных подписей.
                print()
            
            # ====================================================================
            # ДЕЙСТВИЕ 9: ВЫВОД ИТОГОВЫХ РЕЗУЛЬТАТОВ ПРОВЕРКИ
            # ====================================================================
            # После обработки всех подписей выводим итоговую информацию о результате
            # проверки и инструкции по проверке метки времени в PDF-просмотрщике.
            # ДЕЙСТВИЕ 9.1: Вывод заголовка итоговых результатов
            print("=== Результат проверки ===")
            # ДЕЙСТВИЕ 9.2: Вывод информации о наличии подписи в PDF
            print(f"✓ PDF содержит цифровую подпись")
            # ДЕЙСТВИЕ 9.3: Вывод информации о формате подписи
            # PAdES (PDF Advanced Electronic Signatures) - стандарт подписания PDF документов,
            # основанный на стандартах ETSI (European Telecommunications Standards Institute).
            print(f"✓ Подпись встроена в документ (PAdES format)")
            # ДЕЙСТВИЕ 9.4: Вывод инструкций по проверке метки времени в PDF-просмотрщике
            # Предоставляем пользователю инструкции, как проверить метку времени в различных
            # PDF-просмотрщиках, так как детальная проверка timestamp может быть недоступна
            # в текущей версии pyhanko или требует дополнительных настроек.
            print(f"\n💡 Как проверить метку времени в PDF-просмотрщике:")
            print(f"   - macOS Preview: откройте PDF → Правка → Подписи → выберите подпись → Свойства")
            print(f"   - Adobe Reader: Правка → Подписи и инициалы → Управлять подписями → выберите подпись → Свойства")
            print(f"   - Chrome/Edge: откройте PDF → нажмите на значок подписи → Свойства подписи")
            
    except Exception as e:
        # ДЕЙСТВИЕ 10: Обработка критической ошибки при открытии/чтении PDF
        # Если произошла критическая ошибка при открытии или чтении PDF файла (файл поврежден,
        # неверный формат PDF, ошибка парсинга структуры PDF, ошибка создания PdfFileReader),
        # выводим сообщение об ошибке, трассировку стека и завершаем выполнение скрипта с кодом ошибки.
        print(f"ОШИБКА: Не удалось проверить PDF: {e}")
        import traceback  # Модуль для вывода трассировки стека
        traceback.print_exc()  # Выводим полную трассировку стека для диагностики критической ошибки
        sys.exit(1)

