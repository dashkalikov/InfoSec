#ifndef PRIME_FILE_MANAGER_H
#define PRIME_FILE_MANAGER_H

#include "BigInt.h"             // Основной класс для работы с большими целыми числами
#include <string>               // Строки для работы с именами файлов
#include <fstream>              // Работа с файлами
#include <vector>               // Вектор для списков файлов

using namespace std;

// =============================================================================
// Менеджер файлов для сохранения и загрузки простых чисел
// =============================================================================
// 
// Архитектура: Класс для управления файлами с простыми числами
// Назначение: Сохранение, загрузка и управление файлами с простыми числами
// 
// Особенности:
// - Автоматическое создание директории generated_primes
// - Форматирование имен файлов с префиксом размера (_256, _512, _1024)
// - Сохранение в десятичном формате без дополнительных надписей
// - Загрузка простых чисел из файлов
// - Проверка существования файлов
// 
// Использование:
// PrimeFileManager manager;
// manager.savePrime(prime, "my_prime", 256);  // Сохранит как my_prime_256.txt
// BigInt loaded = manager.loadPrime("my_prime", 256);
// =============================================================================

class PrimeFileManager 
{
private:
    string baseDirectory;       // Базовая директория для хранения файлов
    
    /**
     * @brief Создает полный путь к файлу с простым числом
     * 
     * Формат имени файла: {filename}_{bitSize}.txt
     * Пример: my_prime_256.txt, test_prime_1024.txt
     * 
     * @param filename Базовое имя файла (без расширения)
     * @param bitSize Размер простого числа в битах
     * @return Полный путь к файлу
     */
    string createFilePath(const string& filename, int bitSize) const;
    
    /**
     * @brief Создает директорию для хранения файлов, если она не существует
     * 
     * Проверяет существование директории generated_primes и создает её при необходимости
     * 
     * @return true если директория существует или была создана, false при ошибке
     */
    bool ensureDirectoryExists() const;

public:
    /**
     * @brief Конструктор менеджера файлов
     * 
     * Инициализирует базовую директорию как "generated_primes"
     * и создает её при необходимости
     */
    PrimeFileManager();
    
    /**
     * @brief Сохраняет простое число в файл
     * 
     * Алгоритм:
     * 1. Создает директорию generated_primes если не существует
     * 2. Формирует имя файла с префиксом размера (_256, _512, etc.)
     * 3. Сохраняет число в десятичном формате без дополнительных надписей
     * 4. Записывает только само число в файл
     * 
     * @param prime Простое число для сохранения
     * @param filename Базовое имя файла (без расширения и размера)
     * @param bitSize Размер простого числа в битах (для префикса)
     * @return true если сохранение успешно, false при ошибке
     */
    bool savePrime(const BigInt& prime, const string& filename, int bitSize) const;
    
    /**
     * @brief Загружает простое число из файла
     * 
     * Алгоритм:
     * 1. Формирует путь к файлу с учетом размера
     * 2. Читает файл построчно
     * 3. Конвертирует десятичную строку в BigInt
     * 4. Возвращает загруженное число
     * 
     * @param filename Базовое имя файла (без расширения и размера)
     * @param bitSize Размер простого числа в битах
     * @return Загруженное простое число или BigInt::zero() при ошибке
     */
    BigInt loadPrime(const string& filename, int bitSize) const;
    
    /**
     * @brief Проверяет существование файла с простым числом
     * 
     * @param filename Базовое имя файла
     * @param bitSize Размер простого числа в битах
     * @return true если файл существует, false иначе
     */
    bool fileExists(const string& filename, int bitSize) const;
    
    /**
     * @brief Получает список всех файлов с простыми числами определенного размера
     * 
     * @param bitSize Размер простых чисел в битах
     * @return Вектор имен файлов (без расширения и префикса размера)
     */
    vector<string> getPrimeFiles(int bitSize) const;

    /**
     * @brief Получает список всех файлов с простыми числами в директории.
     *
     * Возвращает все файлы в формате "имя_размер.txt" из папки generated_primes/.
     * Полезно для просмотра всех сгенерированных простых чисел.
     *
     * @return Вектор строк с полными именами файлов (включая размер и расширение).
     */
    vector<string> getAllPrimeFiles() const;
    
    /**
     * @brief Удаляет файл с простым числом
     * 
     * @param filename Базовое имя файла
     * @param bitSize Размер простого числа в битах
     * @return true если файл удален, false при ошибке
     */
    bool deletePrimeFile(const string& filename, int bitSize) const;
    
    /**
     * @brief Получает информацию о файле (размер, дата создания)
     * 
     * @param filename Базовое имя файла
     * @param bitSize Размер простого числа в битах
     * @return Строка с информацией о файле или пустая строка при ошибке
     */
    string getFileInfo(const string& filename, int bitSize) const;
};

#endif // PRIME_FILE_MANAGER_H
