// ============================================================================
// ФАЙЛ KUZNECHIK_CONSTANTS_DATA.H - ДАННЫЕ КОНСТАНТ АЛГОРИТМА КУЗНЕЧИК
// ============================================================================
// Этот файл содержит объявления константных данных для алгоритма блочного
// шифрования Кузнечик (ГОСТ Р 34.12-2015). Включает коэффициенты для
// линейного преобразования L, S-таблицу и обратную S-таблицу

#ifndef KUZNECHIK_CONSTANTS_DATA_H
#define KUZNECHIK_CONSTANTS_DATA_H

// ============================================================================
// КОЭФФИЦИЕНТЫ ДЛЯ ЛИНЕЙНОГО ПРЕОБРАЗОВАНИЯ L (LFSR)
// ============================================================================
// Коэффициенты для линейного преобразования L согласно ГОСТ Р 34.12-2015.
// Используются в R-преобразовании для создания линейного регистра сдвига
// с обратной связью (LFSR). Каждый коэффициент представляет элемент
// конечного поля GF(2^8) по модулю неприводимого полинома
//
// ИСТОЧНИК: ГОСТ Р 34.12-2015, строка 148, 32, 133, 16, 194, 192, 1, 251, 1, 192, 194, 16, 133, 32, 148, 1
// РАЗМЕР: 16 байт (128 бит)
// НАЗНАЧЕНИЕ: Коэффициенты для вычисления констант раундов C1-C32
// ============================================================================

extern const unsigned char kuz_lvec[16];

// ============================================================================
// S-ТАБЛИЦА ДЛЯ АЛГОРИТМА КУЗНЕЧИК
// ============================================================================
// S-таблица (таблица подстановки) для нелинейного преобразования S
// согласно ГОСТ Р 34.12-2015. Каждый байт входных данных заменяется
// соответствующим байтом из S-таблицы для обеспечения нелинейности
//
// ИСТОЧНИК: ГОСТ Р 34.12-2015, таблица подстановки
// РАЗМЕР: 256 байт (по одному байту для каждого возможного входного значения 0-255)
// НАЗНАЧЕНИЕ: Нелинейное преобразование S в раундах шифрования
// ============================================================================

extern const unsigned char s_box[256];

// ============================================================================
// ОБРАТНАЯ S-ТАБЛИЦА ДЛЯ РАСШИФРОВАНИЯ
// ============================================================================
// Обратная S-таблица для выполнения обратного нелинейного преобразования S^(-1)
// при расшифровании. Вычисляется динамически из прямой S-таблицы при инициализации
//
// РАЗМЕР: 256 байт (по одному байту для каждого возможного входного значения 0-255)
// НАЗНАЧЕНИЕ: Обратное нелинейное преобразование S^(-1) в раундах расшифрования
// ИНИЦИАЛИЗАЦИЯ: Выполняется функцией init_inverse_s_box()
// ============================================================================

extern unsigned char inverse_s_box[256];

// ============================================================================
// ФУНКЦИЯ ИНИЦИАЛИЗАЦИИ ОБРАТНОЙ S-ТАБЛИЦЫ
// ============================================================================
// Функция инициализирует обратную S-таблицу на основе прямой S-таблицы.
// Для каждого значения i в прямой S-таблице устанавливает обратное
// соответствие: inverse_s_box[s_box[i]] = i
//
// АЛГОРИТМ:
// 1. Проход по всем 256 элементам прямой S-таблицы
// 2. Для каждого элемента s_box[i] устанавливается inverse_s_box[s_box[i]] = i
// 3. Результат: полная обратная таблица для расшифрования
//
// ВЫЗОВ: Автоматически вызывается в конструкторе KuznechikConstants
// ============================================================================

void init_inverse_s_box();

#endif // KUZNECHIK_CONSTANTS_DATA_H