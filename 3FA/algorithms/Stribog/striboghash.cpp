#include "striboghash.h"
#include "standard/stribog.h"

// ============================================================================
// МЕТОД hash256 - ВЫЧИСЛЕНИЕ 256-БИТНОГО ХЕША
// ============================================================================
// Вычисляет 256-битный (32 байта) хеш от входных данных с использованием
// алгоритма Stribog (ГОСТ Р 34.11-2012).
//
// АЛГОРИТМ:
// 1. Преобразование QByteArray в указатель на uint8_t
// 2. Вычисление длины данных в битах
// 3. Выделение памяти для результата хеширования
// 4. Вызов нативной функции hash_256 из алгоритма Stribog
// 5. Преобразование результата обратно в QByteArray
// ============================================================================

QByteArray StribogHash::hash256(const QByteArray &data)
{
    // Преобразуем QByteArray в указатель на uint8_t
    const uint8_t* message = reinterpret_cast<const uint8_t*>(data.constData());
    
    // Вычисляем длину данных в битах
    uint64_t length = static_cast<uint64_t>(data.size()) * 8;
    
    // Выделяем память для результата хеширования (32 байта = 256 бит)
    uint8_t hash[32];
    
    // Вызываем нативную функцию hash_256
    hash_256(message, length, hash);
    
    // Преобразуем результат обратно в QByteArray
    return QByteArray(reinterpret_cast<const char*>(hash), 32);
}


