#ifndef STRIBOGHASH_H
#define STRIBOGHASH_H

// ============================================================================
// ЗАГОЛОВОЧНЫЙ ФАЙЛ STRIBOGHASH.H - QT-ОБЕРТКА НАД АЛГОРИТМОМ STRIBOG
// ============================================================================
// Этот файл содержит Qt-обертку над реализацией алгоритма хеширования Stribog
// (ГОСТ Р 34.11-2012). Предоставляет удобный интерфейс для работы с алгоритмом
// в Qt-приложениях, используя типы данных Qt (QByteArray) вместо сырых указателей.
// ============================================================================

#include <QByteArray>

// ============================================================================
// КЛАСС STRIBOGHASH - QT-ОБЕРТКА НАД АЛГОРИТМОМ STRIBOG
// ============================================================================
// Класс предоставляет статические методы для вычисления хешей Stribog
// с использованием Qt-типов данных. Все методы являются статическими,
// что позволяет использовать их без создания экземпляра класса.
// ============================================================================

class StribogHash
{
public:
    // ============================================================================
    // МЕТОД hash256 - ВЫЧИСЛЕНИЕ 256-БИТНОГО ХЕША
    // ============================================================================
    // Вычисляет 256-битный (32 байта) хеш от входных данных с использованием
    // алгоритма Stribog (ГОСТ Р 34.11-2012).
    //
    // ПАРАМЕТРЫ:
    //   data - входные данные для хеширования (QByteArray)
    //
    // ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
    //   QByteArray размером 32 байта, содержащий 256-битный хеш
    // ============================================================================
    static QByteArray hash256(const QByteArray &data);
    
    // ============================================================================
    // МЕТОД hash512 - ВЫЧИСЛЕНИЕ 512-БИТНОГО ХЕША
    // ============================================================================
    // Вычисляет 512-битный (64 байта) хеш от входных данных с использованием
    // алгоритма Stribog (ГОСТ Р 34.11-2012).
    //
    // ПАРАМЕТРЫ:
    //   data - входные данные для хеширования (QByteArray)
    //
    // ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
    //   QByteArray размером 64 байта, содержащий 512-битный хеш
    // ============================================================================
    static QByteArray hash512(const QByteArray &data);
};

#endif // STRIBOGHASH_H

