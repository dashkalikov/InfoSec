#ifndef STRIBOG_H_
#define STRIBOG_H_

// ============================================================================
// ЗАГОЛОВОЧНЫЙ ФАЙЛ STRIBOG.H - ПУБЛИЧНЫЙ API АЛГОРИТМА STRIBOG
// ============================================================================
// Этот файл содержит объявления публичных функций для работы с алгоритмом
// хеширования Stribog (ГОСТ Р 34.11-2012). Он предоставляет интерфейс для
// получения хешей длиной 256 и 512 бит, а также для разбиения сообщений на блоки.


#include <cstdint>                      // подключаем стандартные типы данных для работы с беззнаковыми целыми числами

// ============================================================================
// ОБЪЯВЛЕНИЕ ФУНКЦИИ ХЕШИРОВАНИЯ С ДЛИНОЙ 512 БИТ
// ============================================================================
// Функция для получения хеша длиной 512 бит (64 байта) от произвольного сообщения

void hash_512(const uint8_t *message,   // указатель на входное сообщение для хеширования
              uint64_t length,          // длина сообщения в битах (uint64_t для поддержки больших сообщений)
              uint8_t *hash);           // указатель на выходной массив для хеша (должен быть размером 64 байта)


// ============================================================================
// ОБЪЯВЛЕНИЕ ФУНКЦИИ ХЕШИРОВАНИЯ С ДЛИНОЙ 256 БИТ
// ============================================================================
// Функция для получения хеша длиной 256 бит (32 байта) от произвольного сообщения

void hash_256(const uint8_t *message,   // указатель на входное сообщение для хеширования
              uint64_t length,          // длина сообщения в битах (uint64_t для поддержки больших сообщений)
              uint8_t *hash);           // указатель на выходной массив для хеша (должен быть размером 32 байта)


// ============================================================================
// ЗАВЕРШЕНИЕ ЗАГОЛОВОЧНОГО ФАЙЛА
// ============================================================================

#endif /* STRIBOG_H_ */
