// Этот файл содержит полную реализацию алгоритма хеширования Stribog
// (ГОСТ Р 34.11-2012). Включает все криптографические функции, преобразования
// и вспомогательные функции для работы с алгоритмом

#include <cstring>        // для работы со строками C (memcpy, memset)
