// ============================================================================
// ФАЙЛ MAIN.CPP - ТОЧКА ВХОДА ПРИЛОЖЕНИЯ 3FA
// ============================================================================
// Этот файл содержит функцию main() - точку входа в приложение 3FA
// (Three-Factor Authentication). Инициализирует Qt приложение, устанавливает
// метаданные приложения, стиль интерфейса и создает главное окно.
//
// НАЗНАЧЕНИЕ:
// - Инициализация Qt Application
// - Установка метаданных приложения (имя, версия, организация)
// - Настройка стиля интерфейса
// - Создание и отображение главного окна
// - Запуск главного цикла обработки событий
// ============================================================================

// Windows заголовки ДОЛЖНЫ быть включены ДО Qt/STL для избежания конфликта byte
#ifdef _WIN32
#include <windows.h>                            // Windows API для настройки консоли
#endif

#include <QApplication>                         // базовый класс Qt приложения
#include "src/mainwindow.h"                     // главное окно приложения

// ============================================================================
// ФУНКЦИЯ main - ТОЧКА ВХОДА ПРИЛОЖЕНИЯ
// ============================================================================
// Основная функция приложения, которая инициализирует Qt приложение,
// настраивает его параметры и запускает главный цикл обработки событий.
//
// ПАРАМЕТРЫ:
//   argc - количество аргументов командной строки
//   argv - массив аргументов командной строки
//
// ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
//   int - код возврата приложения (0 при успешном завершении)
//
// АЛГОРИТМ:
// 1. Создание объекта QApplication
// 2. Установка метаданных приложения
// 3. Настройка стиля интерфейса
// 4. Создание и отображение главного окна
// 5. Запуск главного цикла обработки событий
// ============================================================================

int main(int argc, char *argv[])
{
#ifdef _WIN32
    // НАСТРОЙКА КОДИРОВКИ КОНСОЛИ ДЛЯ ПРАВИЛЬНОГО ОТОБРАЖЕНИЯ КИРИЛЛИЦЫ
    // Устанавливаем кодировку консоли в Windows-1251 для корректного отображения русских символов
    SetConsoleOutputCP(1251);                  // Windows-1251 для вывода
    SetConsoleCP(1251);                        // Windows-1251 для ввода
#endif

    // ДЕЙСТВИЕ 1: СОЗДАНИЕ ОБЪЕКТА QAPPLICATION
    // Создаем экземпляр QApplication, который управляет жизненным циклом
    // приложения и обрабатывает события GUI
    QApplication app(argc, argv);
    
    // ДЕЙСТВИЕ 2: УСТАНОВКА МЕТАДАННЫХ ПРИЛОЖЕНИЯ
    // Устанавливаем информацию о приложении для использования в системе
    // (иконки, настройки, регистрация в системе)
    app.setApplicationName("3FA");                  // название приложения
    app.setApplicationVersion("0.1.0");                 // версия приложения
    app.setOrganizationName("3FA Security");            // название организации
    app.setOrganizationDomain("3fa-security.com");    // домен организации
    
    // ДЕЙСТВИЕ 3: НАСТРОЙКА СТИЛЯ ИНТЕРФЕЙСА
    // Устанавливаем стиль "Fusion" - современный кроссплатформенный стиль Qt,
    // который обеспечивает единообразный внешний вид на всех платформах
    
    // ДЕЙСТВИЕ 4: СОЗДАНИЕ И ОТОБРАЖЕНИЕ ГЛАВНОГО ОКНА
    // Создаем экземпляр главного окна приложения и отображаем его на экране
    MainWindow window;                                           // создание главного окна
    window.show();                                               // отображение окна
    
    // ДЕЙСТВИЕ 5: ЗАПУСК ГЛАВНОГО ЦИКЛА ОБРАБОТКИ СОБЫТИЙ
    // Запускаем главный цикл обработки событий Qt. Функция exec() блокирует
    // выполнение до тех пор, пока приложение не будет закрыто, и возвращает
    // код возврата приложения при завершении
    return app.exec();
}
