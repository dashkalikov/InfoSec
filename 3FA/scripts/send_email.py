#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ============================================================================
# СКРИПТ SEND_EMAIL.PY - ОТПРАВКА EMAIL ЧЕРЕЗ SMTP
# ============================================================================
# Этот скрипт отправляет email сообщения через SMTP протокол.
# Используется из C++ приложения для отправки кодов верификации пользователям.
# Работает в режиме чтения JSON данных из stdin и вывода результата в stdout.
#
# НАЗНАЧЕНИЕ:
# - Интеграция с Qt-приложением для отправки кодов верификации по email
# - Поддержка различных SMTP серверов (Gmail, Outlook, кастомные)
# - Поддержка SSL/TLS шифрования (SMTP_SSL и STARTTLS)
#
# АЛГОРИТМ РАБОТЫ:
# 1. Чтение JSON данных из stdin (настройки SMTP, получатель, тема, тело)
# 2. Создание MIME сообщения с HTML телом
# 3. Подключение к SMTP серверу (с выбором SSL/TLS метода)
# 4. Авторизация на SMTP сервере
# 5. Отправка email сообщения
# 6. Вывод результата в JSON формате в stdout
# ============================================================================

import sys                                  # Системные функции (stdin, stdout, stderr, exit)
import json                                 # Работа с JSON данными (парсинг, сериализация)
import smtplib                              # Библиотека для работы с SMTP протоколом
import ssl                                  # Проверка сертификатов SMTP-сервера
from email.mime.text import MIMEText        # Класс для создания текстовых частей сообщения
from email.mime.multipart import MIMEMultipart  # Класс для создания многочастных сообщений
from email.header import Header                 # Класс для корректной обработки заголовков с UTF-8


# ============================================================================
# ФУНКЦИЯ send_email - ОТПРАВКА EMAIL ЧЕРЕЗ SMTP
# ============================================================================
# Отправляет email сообщение через SMTP протокол с поддержкой SSL/TLS.
# Поддерживает различные методы шифрования в зависимости от настроек SMTP сервера.
#
# ПАРАМЕТРЫ:
#   smtp_config - словарь с настройками SMTP сервера:
#     - host: адрес SMTP сервера (например, 'smtp.gmail.com')
#     - port: порт SMTP сервера (465 для SSL, 587 для STARTTLS)
#     - username: имя пользователя для авторизации
#     - password: пароль для авторизации
#     - from_email: email отправителя (опционально, по умолчанию = username)
#     - use_ssl: использовать SSL (True/False, по умолчанию True)
#     - use_starttls: использовать STARTTLS (True/False/None, None = автоопределение)
#   to_email - email адрес получателя
#   subject - тема письма (строка)
#   body - тело письма в HTML формате (строка)
#
# ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
#   dict с результатом отправки:
#     - {"success": True, "error": None} - успешная отправка
#     - {"success": False, "error": "описание ошибки"} - ошибка отправки
#
# АЛГОРИТМ:
# 1. Создание MIME сообщения с HTML телом
# 2. Определение метода подключения (SSL/STARTTLS/без шифрования)
# 3. Подключение к SMTP серверу
# 4. Авторизация на сервере
# 5. Отправка сообщения
# 6. Закрытие соединения
# ============================================================================
def send_email(smtp_config, to_email, subject, body):
    try:
        # ========================================================================
        # ДЕЙСТВИЕ 1: СОЗДАНИЕ MIME СООБЩЕНИЯ
        # ========================================================================
        # MIMEMultipart('alternative') создает многочастное сообщение
        # 'alternative' означает, что части сообщения являются альтернативными
        # версиями одного и того же контента (plain text и HTML)
        msg = MIMEMultipart('alternative')
        
        # Устанавливаем адрес отправителя
        # smtp_config.get('from_email', smtp_config['username']) - используем
        # 'from_email' если указан, иначе используем 'username' как email отправителя
        msg['From'] = smtp_config.get('from_email', smtp_config['username'])
        
        # Устанавливаем адрес получателя
        msg['To'] = to_email
        
        # Устанавливаем тему письма с корректной обработкой UTF-8
        # Header() обеспечивает правильное кодирование кириллицы и других символов
        msg['Subject'] = Header(subject, 'utf-8')
        
        # ========================================================================
        # ДЕЙСТВИЕ 2: ДОБАВЛЕНИЕ HTML ТЕЛА СООБЩЕНИЯ
        # ========================================================================
        # MIMEText создает текстовую часть сообщения
        #   body - HTML содержимое письма
        #   'html' - тип содержимого (HTML формат)
        #   'utf-8' - кодировка для корректного отображения кириллицы
        html_part = MIMEText(body, 'html', 'utf-8')
        
        # Прикрепляем HTML часть к сообщению
        msg.attach(html_part)
        
        # ========================================================================
        # ДЕЙСТВИЕ 3: ОПРЕДЕЛЕНИЕ ПАРАМЕТРОВ ПОДКЛЮЧЕНИЯ
        # ========================================================================
        # Извлекаем параметры подключения из конфигурации
        host = smtp_config['host']                  # Адрес SMTP сервера
        port = smtp_config['port']                  # Порт SMTP сервера
        use_ssl = smtp_config.get('use_ssl', True)  # Использовать SSL (по умолчанию True)
        
        # use_starttls - использовать STARTTLS (None = автоопределение по порту)
        # STARTTLS - метод шифрования, который начинается с незашифрованного соединения,
        # а затем переходит на зашифрованное
        use_starttls = smtp_config.get('use_starttls', None)
        
        # Автоматическое определение метода шифрования по порту
        # Порт 587 обычно использует STARTTLS, порт 465 - SMTP_SSL
        if use_starttls is None:
            use_starttls = (port == 587)            # Порт 587 обычно использует STARTTLS
        
        # ========================================================================
        # ДЕЙСТВИЕ 4: ПОДКЛЮЧЕНИЕ К SMTP СЕРВЕРУ
        # ========================================================================
        # Выбираем метод подключения в зависимости от настроек
        if use_starttls:
            # Для порта 587 (Gmail, Outlook) используем SMTP с STARTTLS
            # smtplib.SMTP() создает незашифленное соединение
            server = smtplib.SMTP(host, port)
            # server.starttls() переводит соединение на TLS шифрование
            server.starttls(context=ssl.create_default_context())
        elif use_ssl:
            # Для порта 465 (Gmail SSL) используем SMTP_SSL
            # smtplib.SMTP_SSL() создает сразу зашифрованное SSL соединение
            server = smtplib.SMTP_SSL(host, port, context=ssl.create_default_context())
        else:
            # Без SSL (не рекомендуется для безопасности)
            # Используется только для тестирования или внутренних сетей
            server = smtplib.SMTP(host, port)
        
        # ========================================================================
        # ДЕЙСТВИЕ 5: АВТОРИЗАЦИЯ НА SMTP СЕРВЕРЕ
        # ========================================================================
        # Извлекаем учетные данные из конфигурации
        username = smtp_config['username']  # Имя пользователя (обычно email)
        password = smtp_config['password']  # Пароль или app-specific password
        
        # Выполняем авторизацию на SMTP сервере
        # server.login() отправляет команду AUTH и проверяет учетные данные
        server.login(username, password)
        
        # ========================================================================
        # ДЕЙСТВИЕ 6: ОТПРАВКА СООБЩЕНИЯ
        # ========================================================================
        # Отправляем подготовленное сообщение
        # server.send_message() отправляет MIME сообщение на сервер
        server.send_message(msg)
        
        # Закрываем соединение с SMTP сервером
        # server.quit() корректно завершает сессию и закрывает соединение
        server.quit()
        
        # Возвращаем успешный результат
        return {"success": True, "error": None}
        
    except Exception as e:
        # ========================================================================
        # ОБРАБОТКА ОШИБОК
        # ========================================================================
        # Перехватываем все исключения и возвращаем информацию об ошибке
        # Возможные ошибки:
        #   - smtplib.SMTPAuthenticationError - неверные учетные данные
        #   - smtplib.SMTPConnectError - ошибка подключения к серверу
        #   - smtplib.SMTPException - общие ошибки SMTP
        #   - socket.error - сетевые ошибки
        #   - KeyError - отсутствие обязательных полей в smtp_config
        return {"success": False, "error": str(e)}


# ============================================================================
# БЛОК if __name__ == "__main__" - ТОЧКА ВХОДА СКРИПТА
# ============================================================================
# Основная функция для работы скрипта в режиме командной строки.
# Читает JSON данные из stdin, отправляет email и выводит результат в stdout.
#
# ПРОТОКОЛ ВЗАИМОДЕЙСТВИЯ:
# - Вход: JSON строка через stdin с полями:
#   {
#     "smtp_config": {
#       "host": "smtp.gmail.com",
#       "port": 587,
#       "username": "user@example.com",
#       "password": "password",
#       "use_ssl": true,
#       "use_starttls": null
#     },
#     "to": "recipient@example.com",
#     "subject": "Тема письма",
#     "body": "<html>Тело письма</html>"
#   }
# - Выход: JSON строка через stdout с результатом:
#   {"success": true, "error": null} - успех
#   {"success": false, "error": "описание ошибки"} - ошибка
# - Ошибки: сообщения об ошибках выводятся в stderr
# - Код выхода: 0 при успехе, 1 при ошибке
# ============================================================================
if __name__ == "__main__":
    try:
        # ========================================================================
        # ДЕЙСТВИЕ 1: ЧТЕНИЕ JSON ДАННЫХ ИЗ STDIN
        # ========================================================================
        # sys.stdin.read() читает весь ввод из стандартного потока ввода
        # C++ приложение отправляет JSON данные через stdin
        # На Windows может быть проблема с кодировкой, поэтому используем binary mode
        # и явно декодируем в UTF-8 с обработкой ошибок
        # ВАЖНО: Используем errors='strict' для сохранения эмодзи, а не 'replace'
        if sys.platform == 'win32':
            # На Windows читаем в бинарном режиме и декодируем в UTF-8
            input_bytes = sys.stdin.buffer.read()
            try:
                # Используем 'strict' для сохранения всех символов, включая эмодзи
                input_text = input_bytes.decode('utf-8')
            except UnicodeDecodeError as e:
                # Только в случае реальной ошибки используем 'replace'
                error_result = {"success": False, "error": f"Ошибка декодирования UTF-8: {str(e)}"}
                print(json.dumps(error_result, ensure_ascii=False), file=sys.stderr)
                sys.exit(1)
        else:
            # На Unix-системах читаем напрямую (уже в UTF-8)
            input_text = sys.stdin.read()
        
        # Проверяем, что данные были получены
        if not input_text:
            error_result = {"success": False, "error": "Не получены данные из stdin"}
            print(json.dumps(error_result, ensure_ascii=False), file=sys.stderr)
            sys.exit(1)
        
        # ========================================================================
        # ДЕЙСТВИЕ 2: ПАРСИНГ JSON ДАННЫХ
        # ========================================================================
        # json.loads() преобразует JSON строку в Python словарь
        # input_data - словарь с данными для отправки email
        input_data = json.loads(input_text)
        
        # ========================================================================
        # ДЕЙСТВИЕ 3: ПРОВЕРКА ОБЯЗАТЕЛЬНЫХ ПОЛЕЙ
        # ========================================================================
        # Проверяем наличие обязательной секции 'smtp_config'
        if 'smtp_config' not in input_data:
            error_result = {"success": False, "error": "Отсутствует секция 'smtp_config' в данных"}
            print(json.dumps(error_result, ensure_ascii=False), file=sys.stderr)
            sys.exit(1)
        
        # Извлекаем данные из JSON
        smtp_config = input_data['smtp_config']  # Настройки SMTP сервера (обязательно)
        to_email = input_data.get('to', '')      # Email получателя (опционально, проверяется ниже)
        subject = input_data.get('subject', '')  # Тема письма (опционально, по умолчанию пустая)
        body = input_data.get('body', '')        # Тело письма (опционально, по умолчанию пустое)
        
        # Проверяем наличие email получателя
        if not to_email:
            error_result = {"success": False, "error": "Не указан email получателя"}
            print(json.dumps(error_result, ensure_ascii=False), file=sys.stderr)
            sys.exit(1)
        
        # ========================================================================
        # ДЕЙСТВИЕ 4: ОТПРАВКА EMAIL
        # ========================================================================
        # Вызываем функцию отправки email с извлеченными данными
        result = send_email(smtp_config, to_email, subject, body)
        
        # ========================================================================
        # ДЕЙСТВИЕ 5: ВЫВОД РЕЗУЛЬТАТА В STDOUT
        # ========================================================================
        # Выводим результат в JSON формате в stdout
        # json.dumps() преобразует Python словарь в JSON строку
        # ensure_ascii=False позволяет использовать кириллицу без экранирования
        print(json.dumps(result, ensure_ascii=False))
        
        # ========================================================================
        # ДЕЙСТВИЕ 6: ЗАВЕРШЕНИЕ С КОДОМ ВЫХОДА
        # ========================================================================
        # sys.exit() завершает выполнение скрипта с кодом выхода
        # 0 - успешное выполнение, 1 - ошибка
        # C++ приложение может проверить код выхода для определения успешности
        sys.exit(0 if result['success'] else 1)
        
    except json.JSONDecodeError as e:
        # ========================================================================
        # ОБРАБОТКА ОШИБКИ ПАРСИНГА JSON
        # ========================================================================
        # json.JSONDecodeError возникает при неверном формате JSON
        # Возможные причины: синтаксические ошибки, неполные данные
        error_result = {"success": False, "error": f"Ошибка парсинга JSON: {str(e)}"}
        print(json.dumps(error_result, ensure_ascii=False), file=sys.stderr)
        sys.exit(1)
        
    except KeyError as e:
        # ========================================================================
        # ОБРАБОТКА ОТСУТСТВИЯ ОБЯЗАТЕЛЬНОГО ПОЛЯ
        # ========================================================================
        # KeyError возникает при обращении к несуществующему ключу словаря
        # Например, если в smtp_config отсутствует обязательное поле 'host'
        error_result = {"success": False, "error": f"Отсутствует обязательное поле: {str(e)}"}
        print(json.dumps(error_result, ensure_ascii=False), file=sys.stderr)
        sys.exit(1)
        
    except Exception as e:
        # ========================================================================
        # ОБРАБОТКА НЕОЖИДАННЫХ ОШИБОК
        # ========================================================================
        # Перехватываем все остальные исключения, которые не были обработаны выше
        # Возможные ошибки:
        #   - Сетевые ошибки при подключении к SMTP серверу
        #   - Ошибки авторизации
        #   - Ошибки отправки сообщения
        #   - Другие неожиданные исключения
        error_result = {"success": False, "error": f"Неожиданная ошибка: {str(e)}"}
        print(json.dumps(error_result, ensure_ascii=False), file=sys.stderr)
        
        # Выводим полный traceback в stderr для отладки
        # traceback.print_exc() выводит полную информацию о стеке вызовов
        import traceback
        traceback.print_exc(file=sys.stderr)
        sys.exit(1)

