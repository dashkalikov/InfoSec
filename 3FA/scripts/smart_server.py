#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ============================================================================
# СКРИПТ SMART_SERVER.PY - УМНЫЙ HTTP СЕРВЕР ДЛЯ УПРАВЛЕНИЯ TOTP ВЕБ-СТРАНИЦЕЙ
# ============================================================================
# Этот скрипт реализует HTTP сервер для обслуживания TOTP веб-страницы
# и управления её жизненным циклом. Отправляет специальные команды для
# закрытия страницы на телефоне пользователя.
#
# НАЗНАЧЕНИЕ:
# - Интеграция с Qt-приложением для отображения TOTP кода на мобильном устройстве
# - Проксирование запросов к WebSocket серверу для получения TOTP кода
# - Управление жизненным циклом веб-страницы (команды закрытия)
# - Обслуживание статических файлов (HTML, CSS, JS)
#
# АЛГОРИТМ РАБОТЫ:
# 1. Запуск HTTP сервера на указанном порту (с автоматическим поиском свободного)
# 2. Обработка GET запросов (получение TOTP кода, отображение страницы)
# 3. Обработка POST запросов (команды закрытия страницы)
# 4. Проксирование запросов к WebSocket серверу для получения актуального кода
# 5. Работа в отдельном потоке для неблокирующей работы
# ============================================================================

import http.server                   # Базовый класс для HTTP сервера
import socketserver                  # Классы для создания TCP серверов
import sys                           # Системные функции (stderr, argv)
import json                          # Работа с JSON данными (парсинг, сериализация)
from hmac import compare_digest
import threading                     # Работа с потоками (Thread)
import time                          # Работа со временем (sleep)
from urllib.parse import parse_qs, urlparse
from urllib.request import urlopen   # HTTP клиент для проксирования запросов к WebSocket серверу

# ============================================================================
# КЛАСС SmartTOTPHandler - ОБРАБОТЧИК HTTP ЗАПРОСОВ ДЛЯ TOTP
# ============================================================================
# Класс-обработчик HTTP запросов для управления TOTP веб-страницей.
# Обслуживает страницу входа и её API
# для проксирования запросов к WebSocket серверу и управления жизненным циклом страницы.
# ============================================================================
class SmartTOTPHandler(http.server.BaseHTTPRequestHandler):
    def log_message(self, format, *args):
        # Отключаем стандартные логи HTTP сервера для уменьшения спама
        pass
    

    # ============================================================================
    # МЕТОД do_GET - ОБРАБОТКА GET ЗАПРОСОВ
    # ============================================================================
    # Обрабатывает все GET запросы к HTTP серверу. Поддерживает три типа запросов:
    # 1. /get_current_code - получение текущего TOTP кода (проксирование к WebSocket серверу)
    # 2. /check_close_status - проверка статуса закрытия страницы
    # 3. /totp_setup.html - отображение основной страницы TOTP
    #
    # АЛГОРИТМ:
    # 1. Парсинг URL запроса для извлечения пути
    # 2. Определение типа запроса по пути
    # 3. Обработка соответствующего эндпоинта
    # 4. Возврат ответа клиенту
    # ============================================================================
    def do_GET(self):
        # Парсим URL запроса для извлечения пути
        # urlparse() разбирает URL на компоненты (scheme, host, path, query и т.д.)
        parsed_path = urlparse(self.path)
        access_token = getattr(self.server, 'access_token', '')
        if access_token:
            supplied_token = parse_qs(parsed_path.query).get('token', [''])[0]
            if not compare_digest(supplied_token.encode('utf-8'), access_token.encode('utf-8')):
                self.send_error(404)
                return
        
        # ========================================================================
        # ЭНДПОИНТ: /get_current_code - ПОЛУЧЕНИЕ ТЕКУЩЕГО TOTP КОДА
        # ========================================================================
        # Проксирует запрос к WebSocket серверу для получения актуального TOTP кода.
        # Если WebSocket сервер недоступен, возвращает код по умолчанию.
        if parsed_path.path == '/get_current_code':
            # Отправляем HTTP заголовки ответа
            self.send_response(200)  # HTTP статус 200 (OK)
            self.send_header('Content-type', 'application/json')  # Тип содержимого: JSON
            self.send_header('Cache-Control', 'no-store')
            self.end_headers()                                    # Завершаем отправку заголовков
            
            try:
                # Проверяем, установлен ли порт WebSocket сервера
                websocket_port = getattr(self.server, 'websocket_port', None)
                if websocket_port:
                    # Проксируем запрос к WebSocket серверу
                    # urlopen() выполняет HTTP GET запрос к указанному URL
                    # WebSocket сервер также имеет HTTP эндпоинт /get_current_code
                    with urlopen(f'http://127.0.0.1:{websocket_port}/get_current_code', timeout=3) as resp:
                        # Читаем данные ответа от WebSocket сервера
                        data = resp.read()
                        # Пересылаем данные клиенту без изменений
                        self.wfile.write(data)
                else:
                    # Если порт WebSocket сервера не установлен,
                    # возвращаем код по умолчанию. Это может произойти при запуске сервера
                    # без указания websocket_port в качестве аргумента.
                    #
                    # Формат ответа соответствует ожидаемому формату от WebSocket сервера:
                    #   - code: '000000' - код по умолчанию (невалидный TOTP код)
                    #   - timeLeft: 30 - оставшееся время в секундах (максимальное значение)
                    #   - message: 'ws port not set' - сообщение об ошибке для отладки
                    #
                    # Клиент (веб-страница) получит этот ответ и отобразит код '000000',
                    # что сигнализирует о проблеме с подключением к WebSocket серверу.
                    self.wfile.write(json.dumps({
                        'code': '000000',      # Код по умолчанию (невалидный TOTP)
                        'timeLeft': 30,        # Максимальное время жизни кода (30 секунд)
                        'message': 'ws port not set'  # Сообщение об ошибке конфигурации
                    }).encode('utf-8'))
            except Exception as e:
                # ========================================================================
                # ОБРАБОТКА ОШИБОК ПРИ ПРОКСИРОВАНИИ ЗАПРОСА
                # ========================================================================
                # Перехватываем все исключения при попытке проксирования запроса к
                # WebSocket серверу. Это гарантирует, что клиент всегда получит ответ,
                # даже если WebSocket сервер недоступен или произошла ошибка.
                #
                # Возможные типы ошибок:
                #   - urllib.error.URLError - WebSocket сервер недоступен (не запущен)
                #   - ConnectionRefusedError - соединение отклонено (порт закрыт)
                #   - TimeoutError - таймаут при подключении
                #   - socket.error - сетевые ошибки (DNS, сетевая недоступность)
                #   - Другие неожиданные ошибки
                #
                # Формат ответа аналогичен случаю отсутствия порта:
                #   - code: '000000' - код по умолчанию (невалидный TOTP)
                #   - timeLeft: 30 - оставшееся время (максимальное значение)
                #   - message: содержит описание ошибки для отладки
                #
                # Важно: мы не пробрасываем исключение дальше, чтобы не прервать
                # работу HTTP сервера. Клиент получит ответ с кодом по умолчанию,
                # что позволит веб-странице продолжить работу, хотя и без актуального кода.
                self.wfile.write(json.dumps({
                    'code': '000000',               # Код по умолчанию (невалидный TOTP)
                    'timeLeft': 30,                 # Максимальное время жизни кода (30 секунд)
                    'message': f'Ошибка: {str(e)}'  # Сообщение с описанием ошибки
                }).encode('utf-8'))
            return
        
        # ========================================================================
        # ЭНДПОИНТ: /check_close_status - ПРОВЕРКА СТАТУСА ЗАКРЫТИЯ
        # ========================================================================
        # Возвращает текущий статус флага should_close для проверки необходимости
        # закрытия страницы на клиенте. Используется веб-страницей для периодической
        # проверки, нужно ли закрыть страницу (например, после завершения настройки TOTP).
        #
        # ПРОТОКОЛ ВЗАИМОДЕЙСТВИЯ:
        # - Запрос: GET /check_close_status
        # - Ответ: JSON с полями:
        #   {
        #     "shouldClose": bool,  # true - закрыть страницу, false - продолжать работу
        #     "message": string     # Текстовое сообщение для пользователя
        #   }
        #
        # ИСПОЛЬЗОВАНИЕ:
        # Веб-страница периодически опрашивает этот
        # эндпоинт через fetch() или XMLHttpRequest. Когда C++ приложение отправляет
        # команду закрытия через /close_page, флаг should_close устанавливается в True,
        # и следующий запрос к /check_close_status вернет shouldClose: true, что
        # сигнализирует клиенту о необходимости закрыть страницу.
        if parsed_path.path == '/check_close_status':
            # Отправляем HTTP заголовки ответа
            self.send_response(200)                               # HTTP статус 200 (OK)
            self.send_header('Content-type', 'application/json')  # Тип содержимого: JSON
            self.send_header('Access-Control-Allow-Origin', '*')  # CORS: разрешаем запросы с любого домена
            self.end_headers()                                    # Завершаем отправку заголовков
            
            # Формируем ответ с текущим статусом закрытия
            # shouldClose - булево значение, указывающее, нужно ли закрыть страницу
            # message - текстовое сообщение для отображения пользователю
            should_close = getattr(self.server, 'should_close', False)
            response = {
                'shouldClose': should_close,
                'message': 'Закройте страницу' if should_close else 'Продолжайте работу'
            }
            if access_token:
                response['accepted'] = getattr(self.server, 'accepted', False)

            # Отправляем JSON ответ клиенту
            # json.dumps() преобразует Python словарь в JSON строку
            # .encode('utf-8') преобразует строку в байты для отправки по HTTP
            self.wfile.write(json.dumps(response).encode('utf-8'))
            return
        
        # ========================================================================
        # ЭНДПОИНТ: /totp_setup.html - ОТОБРАЖЕНИЕ ОСНОВНОЙ СТРАНИЦЫ TOTP
        # ========================================================================
        # Отображает HTML страницу для отображения TOTP кода на мобильном устройстве.
        # Эта страница содержит JavaScript код для подключения к WebSocket серверу,
        # получения и отображения TOTP кода в реальном времени.
        #
        # ПРОТОКОЛ ВЗАИМОДЕЙСТВИЯ:
        # - Запрос: GET /totp_setup.html
        # - Ответ: HTML страница с JavaScript для работы с TOTP кодом
        #
        # ЗАГОЛОВКИ ПРОТИВ КЭШИРОВАНИЯ:
        # Добавляются специальные заголовки для предотвращения кэширования страницы,
        # чтобы браузер всегда загружал актуальную версию. Это критично, так как
        # страница может обновляться между сессиями, и старая версия из кэша может
        # содержать устаревший код или логику.
        if parsed_path.path == '/totp_setup.html':
            # Отправляем HTTP заголовки ответа
            self.send_response(200)                                       # HTTP статус 200 (OK)
            self.send_header('Content-type', 'text/html; charset=utf-8')  # Тип: HTML с UTF-8 кодировкой
            
            # Добавляем заголовки для предотвращения кэширования
            # Это гарантирует, что браузер всегда загружает актуальную версию страницы
            # Cache-Control: no-cache - не использовать кэш без проверки актуальности
            #                no-store - не сохранять ответ в кэш
            #                must-revalidate - всегда проверять актуальность при использовании
            self.send_header('Cache-Control', 'no-cache, no-store, must-revalidate')
            
            # Pragma: no-cache - совместимость с HTTP/1.0 браузерами
            # (HTTP/1.1 использует Cache-Control, но старые браузеры могут не поддерживать)
            self.send_header('Pragma', 'no-cache')
            
            # Expires: 0 - истечение кэша: немедленно (прошлая дата)
            # Указывает браузеру, что страница уже устарела и не должна кэшироваться
            self.send_header('Expires', '0')
            self.end_headers()  # Завершаем отправку заголовков
            
            # Читаем HTML файл из текущей директории
            try:
                # Открываем файл totp_setup.html для чтения
                # Файл должен находиться в той же директории, где запущен скрипт
                # (обычно это корневая директория проекта)
                # encoding='utf-8' обеспечивает корректное чтение кириллицы и других символов
                with open('totp_setup.html', 'r', encoding='utf-8') as f:
                    # Читаем всё содержимое файла в строку
                    # read() читает весь файл целиком, что подходит для небольших HTML файлов
                    html_content = f.read()
                
                # Отправляем HTML содержимое клиенту
                # .encode('utf-8') преобразует строку в байты для отправки по HTTP
                self.wfile.write(html_content.encode('utf-8'))
            except FileNotFoundError:
                # ========================================================================
                # ОБРАБОТКА ОШИБКИ: ФАЙЛ НЕ НАЙДЕН
                # ========================================================================
                # Если файл totp_setup.html не найден в текущей директории, отправляем
                # простое HTML сообщение об ошибке. Это может произойти, если:
                # - Файл был удален или перемещен
                # - Скрипт запущен из неправильной директории
                # - Файл еще не был создан C++ приложением
                #
                # Вместо отправки ошибки 404 мы отправляем HTML страницу с сообщением,
                # чтобы пользователь видел понятное сообщение, а не стандартную ошибку браузера.
                self.wfile.write('<h1>Файл не найден</h1>'.encode('utf-8'))
            return
        
        self.send_error(404)
    

    # ============================================================================
    # МЕТОД do_POST - ОБРАБОТКА POST ЗАПРОСОВ
    # ============================================================================
    # Обрабатывает POST запросы к HTTP серверу. Поддерживает команду закрытия страницы.
    #
    # ЭНДПОИНТЫ:
    #   /close_page - команда закрытия страницы (от C++ приложения)
    #
    # АЛГОРИТМ:
    # 1. Парсинг URL запроса
    # 2. Чтение тела POST запроса
    # 3. Парсинг JSON данных
    # 4. Обработка команды закрытия
    # 5. Установка флага should_close = True
    # 6. Возврат ответа клиенту
    # ============================================================================
    def do_POST(self):
        # Парсим URL запроса для извлечения пути
        parsed_path = urlparse(self.path)
        
        # ========================================================================
        # ЭНДПОИНТ: /close_page - КОМАНДА ЗАКРЫТИЯ СТРАНИЦЫ
        # ========================================================================
        # Принимает команду закрытия страницы от C++ приложения.
        # Устанавливает флаг should_close = True, который затем проверяется
        # клиентом через эндпоинт /check_close_status.
        #
        # ПРОТОКОЛ ВЗАИМОДЕЙСТВИЯ:
        # - Запрос: POST /close_page
        # - Тело запроса: JSON {"action": "close"}
        # - Ответ: JSON {"status": "success", "message": "Страница будет закрыта"}
        #
        # АЛГОРИТМ РАБОТЫ:
        # 1. C++ приложение отправляет POST запрос с командой закрытия
        # 2. HTTP сервер устанавливает флаг should_close = True
        # 3. Веб-страница периодически опрашивает /check_close_status
        # 4. Когда флаг should_close == True, страница получает команду закрытия
        # 5. Страница закрывается автоматически через window.close()
        #
        # ИСПОЛЬЗОВАНИЕ:
        # Вызывается из C++ приложения после завершения настройки TOTP или отмены
        # операции. Это позволяет корректно закрыть веб-страницу на мобильном
        # устройстве без необходимости ручного закрытия пользователем.
        if parsed_path.path == '/close_page':
            if self.client_address[0] != '127.0.0.1':
                self.send_error(403)
                return
            # ========================================================================
            # ДЕЙСТВИЕ 1: ЧТЕНИЕ ТЕЛА POST ЗАПРОСА
            # ========================================================================
            # Получаем длину тела запроса из заголовка Content-Length
            # Это необходимо для чтения правильного количества байтов из потока
            # Без этого мы не знали бы, сколько данных нужно прочитать
            content_length = int(self.headers['Content-Length'])
            
            # Читаем тело POST запроса
            # self.rfile - файловый объект для чтения данных запроса (наследуется от BaseHTTPRequestHandler)
            # read(content_length) читает ровно столько байтов, сколько указано в Content-Length
            post_data = self.rfile.read(content_length)
            
            # ========================================================================
            # ДЕЙСТВИЕ 2: ПАРСИНГ И ОБРАБОТКА JSON ДАННЫХ
            # ========================================================================
            try:
                # Парсим JSON данные из тела запроса
                # post_data - байты, поэтому сначала декодируем в строку UTF-8
                # Ожидаемый формат: {"action": "close"}
                # json.loads() преобразует JSON строку в Python словарь
                data = json.loads(post_data.decode('utf-8'))
                
                # Проверяем, что команда действительно для закрытия страницы
                # data.get('action') безопасно получает значение ключа 'action'
                # Если ключ отсутствует, возвращает None (не вызывает KeyError)
                action = data.get('action')
                if action == 'close' or (action == 'success' and getattr(self.server, 'access_token', '')):
                    # ========================================================================
                    # ДЕЙСТВИЕ 3: УСТАНОВКА ФЛАГА ЗАКРЫТИЯ
                    # ========================================================================
                    # Устанавливаем флаг закрытия страницы в True
                    # Этот флаг будет проверяться клиентом через /check_close_status
                    self.server.should_close = True
                    self.server.accepted = action == 'success'

                    # ========================================================================
                    # ДЕЙСТВИЕ 4: ОТПРАВКА УСПЕШНОГО ОТВЕТА
                    # ========================================================================
                    # Отправляем успешный ответ клиенту (C++ приложению)
                    self.send_response(200)  # HTTP статус 200 (OK)
                    self.send_header('Content-type', 'application/json')  # Тип содержимого: JSON
                    self.send_header('Access-Control-Allow-Origin', '*')  # CORS: разрешаем запросы с любого домена
                    self.end_headers()  # Завершаем отправку заголовков
                    
                    # Формируем ответ об успешном принятии команды
                    # status: 'success' - команда успешно обработана
                    # message: текстовое сообщение для логирования/отладки
                    response = {'status': 'success', 'message': 'Страница будет закрыта'}
                    self.wfile.write(json.dumps(response).encode('utf-8'))
                    return
                    
            except json.JSONDecodeError:
                # ========================================================================
                # ОБРАБОТКА ОШИБКИ ПАРСИНГА JSON
                # ========================================================================
                # json.JSONDecodeError возникает, если данные не являются валидным JSON
                # Возможные причины:
                #   - Неправильный формат данных (не JSON)
                #   - Поврежденные данные при передаче
                #   - Пустое тело запроса
                #
                # Игнорируем ошибку (pass) и отправляем ответ 400 ниже
                # Это позволяет обработать все случаи ошибок в одном месте
                pass
            
            # ========================================================================
            # ОТПРАВКА ОШИБКИ 400 (BAD REQUEST)
            # ========================================================================
            # Отправляем ошибку 400 в следующих случаях:
            # - JSON невалиден (json.JSONDecodeError был перехвачен выше)
            # - Отсутствует поле 'action' в JSON (data.get('action') вернул None)
            # - Поле 'action' не равно 'close' (неизвестная команда)
            #
            # HTTP статус 400 (Bad Request) означает, что запрос был неправильно
            # сформирован клиентом (C++ приложением)
            self.send_response(400)
            self.send_header('Content-type', 'application/json')
            self.end_headers()
            # Отправляем JSON ответ с информацией об ошибке
            self.wfile.write(json.dumps({'status': 'error'}).encode('utf-8'))
            return
        
        # Для всех остальных POST запросов отправляем ошибку 404 (Not Found)
        self.send_error(404, "Not found")


