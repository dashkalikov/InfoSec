# ФУНКЦИЯ start_smart_server - ЗАПУСК HTTP СЕРВЕРА В ОТДЕЛЬНОМ ПОТОКЕ
# ============================================================================
# Запускает HTTP сервер для обслуживания TOTP веб-страницы в отдельном потоке.
# Автоматически ищет свободный порт, если указанный порт занят.
#
# ПАРАМЕТРЫ:
#   port - начальный порт для запуска сервера (int)
#   websocket_port - порт WebSocket сервера для проксирования запросов (int, опционально)
#
# ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
#   threading.Thread - поток, в котором работает сервер
#
# АЛГОРИТМ:
# 1. Создание класса SmartTCPServer с настройками переиспользования адреса
# 2. Попытка запуска сервера на указанном порту
# 3. Если порт занят, попытка запуска на следующем порту (до 20 попыток)
# 4. Запуск сервера в отдельном потоке (daemon thread)
# ============================================================================
def start_smart_server(port, websocket_port=None, access_token=''):
    # ========================================================================
    # КЛАСС SmartTCPServer - НАСТРОЕННЫЙ TCP СЕРВЕР
    # ========================================================================
    # Наследуется от socketserver.TCPServer и добавляет настройки для
    # переиспользования адреса и порта. Это позволяет перезапускать сервер
    # без ожидания освобождения порта операционной системой.
    class SmartTCPServer(socketserver.TCPServer):
        # allow_reuse_address - разрешить переиспользование адреса
        # Позволяет серверу запускаться на адресе, который еще не освобожден ОС
        allow_reuse_address = True
        
        # allow_reuse_port - разрешить переиспользование порта (если поддерживается)
        # hasattr() проверяет наличие ThreadingTCPServer для определения поддержки
        # Это флаг совместимости для разных версий Python и ОС
        allow_reuse_port = hasattr(socketserver, 'ThreadingTCPServer')
    
    # ========================================================================
    # ФУНКЦИЯ run_server - ЗАПУСК СЕРВЕРА С ПОИСКОМ СВОБОДНОГО ПОРТА
    # ========================================================================
    # Внутренняя функция для запуска сервера с автоматическим поиском
    # свободного порта, если указанный порт занят.
    def run_server():
        start_port = port          # Начальный порт для поиска
        max_tries = 20             # Максимальное количество попыток
        last_err = None            # Последняя ошибка для вывода в случае неудачи
        
        # Пытаемся запустить сервер на портах от start_port до start_port + max_tries
        for attempt in range(max_tries):
            candidate = start_port if access_token else start_port + attempt
            try:
                # Создаем экземпляр TCP сервера
                # ("", candidate) - слушаем на всех интерфейсах (0.0.0.0) на порту candidate
                # SmartTOTPHandler - класс-обработчик HTTP запросов
                httpd = SmartTCPServer(("", candidate), SmartTOTPHandler)
                
                # Устанавливаем порт WebSocket сервера для проксирования запросов
                # Это значение будет доступно в обработчике через self.server.websocket_port
                httpd.websocket_port = websocket_port
                httpd.access_token = access_token
                
                # Выводим сообщение об успешном запуске
                print(f"🌐 HTTP сервер запущен на http://localhost:{candidate}")
                
                # Запускаем сервер в бесконечном цикле обработки запросов
                # serve_forever() блокирует выполнение до остановки сервера
                httpd.serve_forever()
                return
                
            except OSError as e:
                # Обработка ошибки занятого порта
                last_err = e
                
                # Проверяем код ошибки: 98 (Linux) или 48 (macOS) - адрес уже используется
                if getattr(e, 'errno', None) in (48, 98):
                    print(f"⚠️ Порт {candidate} занят, повторяем попытку")
                    # Небольшая задержка перед следующей попыткой
                    time.sleep(0.05)
                    continue
                
                # Если ошибка не связана с занятым портом, пробрасываем исключение
                raise
        
        # Если не удалось занять порт ни разу, выводим ошибку в stderr
        print(f"❌ Не удалось запустить HTTP сервер после {max_tries} попыток: {last_err}", file=sys.stderr)
    
    # ========================================================================
    # ЗАПУСК СЕРВЕРА В ОТДЕЛЬНОМ ПОТОКЕ
    # ========================================================================
    # Создаем поток для запуска сервера, чтобы не блокировать основной поток
    # daemon=True означает, что поток завершится при завершении основного потока
    server_thread = threading.Thread(target=run_server, daemon=True)
    
    # Запускаем поток
    server_thread.start()
    
    # Возвращаем объект потока для возможного управления им извне
    return server_thread


# ============================================================================
# БЛОК if __name__ == "__main__" - ТОЧКА ВХОДА СКРИПТА
# ============================================================================
# Основная функция для работы скрипта в режиме командной строки.
# Запускает HTTP сервер с параметрами из аргументов командной строки.
#
# ИСПОЛЬЗОВАНИЕ:
#   python3 smart_server.py [port] [websocket_port]
#
# ПАРАМЕТРЫ:
#   port - порт для запуска HTTP сервера (по умолчанию 8080)
#   websocket_port - порт WebSocket сервера для проксирования (опционально)
#
# ПРИМЕРЫ:
#   python3 smart_server.py 8080 8765
#   python3 smart_server.py 8080
#   python3 smart_server.py
# ============================================================================
if __name__ == "__main__":
    # ========================================================================
    # ДЕЙСТВИЕ 1: ПАРСИНГ АРГУМЕНТОВ КОМАНДНОЙ СТРОКИ
    # ========================================================================
    # Извлекаем порт HTTP сервера из первого аргумента
    # Если аргумент не указан, используем порт по умолчанию 8080
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8080
    
    # Извлекаем порт WebSocket сервера из второго аргумента
    # Если аргумент не указан, websocket_port будет None
    ws_port = int(sys.argv[2]) if len(sys.argv) > 2 else None
    
    # ========================================================================
    # ДЕЙСТВИЕ 2: ЗАПУСК HTTP СЕРВЕРА
    # ========================================================================
    # Запускаем HTTP сервер в отдельном потоке
    # Сервер будет автоматически искать свободный порт, если указанный занят
    token = sys.argv[3] if len(sys.argv) > 3 else ''
    worker = start_smart_server(port, ws_port, token)
    
    # ========================================================================
    # ДЕЙСТВИЕ 3: ПОДДЕРЖАНИЕ ЖИЗНЕННОГО ЦИКЛА ОСНОВНОГО ПОТОКА
    # ========================================================================
    # Держим основной поток живым, чтобы скрипт не завершился сразу
    # Сервер работает в отдельном потоке (daemon), поэтому основной поток
    # должен продолжать работать для поддержания работы приложения
    try:
        worker.join()
    except KeyboardInterrupt:
        # Обработка прерывания пользователем (Ctrl+C)
        # Выводим сообщение и корректно завершаем работу
        print("\nСервер остановлен")
