# ФУНКЦИЯ start_http_server - ЗАПУСК HTTP СЕРВЕРА В ОТДЕЛЬНОМ ПОТОКЕ
# ============================================================================
# Запускает HTTP сервер в отдельном потоке для обработки API запросов
# от C++ приложения. Работает на том же порту, что и WebSocket сервер.
#
# ПАРАМЕТРЫ:
#   port - порт для запуска HTTP сервера (int)
#
# АЛГОРИТМ:
# 1. Создание HTTP сервера на указанном порту
# 2. Запуск сервера в бесконечном цикле (serve_forever)
#
# ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
#   Нет (функция работает бесконечно)
# ============================================================================
def start_http_server(port):
    # Создаем HTTP сервер на localhost с указанным портом
    # HTTPUpdateHandler - класс обработчика для всех HTTP запросов
    http_server = HTTPServer(('localhost', port), HTTPUpdateHandler)
    print(f"🌐 HTTP сервер запущен на http://localhost:{port}")
    # serve_forever() запускает сервер в бесконечном цикле
    # Сервер будет обрабатывать запросы до остановки скрипта
    http_server.serve_forever()


