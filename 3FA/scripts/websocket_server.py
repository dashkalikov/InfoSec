# ============================================================================
# АСИНХРОННАЯ ФУНКЦИЯ main - ГЛАВНАЯ ФУНКЦИЯ СКРИПТА
# ============================================================================
# Главная функция скрипта. Инициализирует WebSocket и HTTP серверы и
# запускает их работу.
#
# АЛГОРИТМ:
# 1. Проверка аргументов командной строки (порт)
# 2. Создание экземпляра TOTPWebSocketServer
# 3. Запуск HTTP сервера в отдельном потоке
# 4. Запуск WebSocket сервера в основном потоке
#
# ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
#   Нет (async функция, работает бесконечно)
# ============================================================================
async def main():
    global server_instance
    
    # ========================================================================
    # ПРОВЕРКА АРГУМЕНТОВ КОМАНДНОЙ СТРОКИ
    # ========================================================================
    # Скрипт должен быть запущен с одним аргументом - портом для сервера
    if len(sys.argv) not in (2, 3):
        print("Использование: python3 websocket_server.py <порт> [LAN-адрес]")
        sys.exit(1)
    
    # Парсим порт из аргументов командной строки
    port = int(sys.argv[1])
    host = sys.argv[2] if len(sys.argv) == 3 else "0.0.0.0"
    
    # ========================================================================
    # СОЗДАНИЕ ЭКЗЕМПЛЯРА WEBSOCKET СЕРВЕРА
    # ========================================================================
    # Создаем экземпляр TOTPWebSocketServer с указанным портом
    server_instance = TOTPWebSocketServer(port)
    
    # ========================================================================
    # ЗАПУСК HTTP СЕРВЕРА В ОТДЕЛЬНОМ ПОТОКЕ
    # ========================================================================
    # Запускаем HTTP сервер в отдельном потоке, чтобы он не блокировал
    # работу WebSocket сервера. HTTP сервер обрабатывает API запросы от C++.
    http_thread = threading.Thread(target=start_http_server, args=(port,))
    # daemon=True означает, что поток завершится при завершении основного потока
    http_thread.daemon = True
    http_thread.start()
    
    # ========================================================================
    # ЗАПУСК WEBSOCKET СЕРВЕРА
    # ========================================================================
    # Запускаем WebSocket сервер в основном потоке
    # Сервер будет работать бесконечно до остановки скрипта
    await server_instance.start_server(host)


# ============================================================================
# БЛОК if __name__ == "__main__" - ТОЧКА ВХОДА СКРИПТА
# ============================================================================
# Точка входа скрипта. Запускает главную функцию main() и обрабатывает
# исключения (KeyboardInterrupt для Ctrl+C, другие исключения).
# ============================================================================
if __name__ == "__main__":
    try:
        # Запускаем главную асинхронную функцию
        # asyncio.run() создает event loop и запускает функцию
        asyncio.run(main())
    except KeyboardInterrupt:
        # Обработка прерывания пользователем (Ctrl+C)
        print("\n🛑 Сервер остановлен")
    except Exception as e:
        # Обработка других исключений
        print(f"❌ Ошибка сервера: {e}")
